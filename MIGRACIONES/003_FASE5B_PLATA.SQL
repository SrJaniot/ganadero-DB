-- PLATA DE LA FINCA (FASE 5B): INGRESOS Y GASTOS QUE ANOTA EL DUEÑO (SOLO EL LOS VE). SE ANOTAN SIN SEÑAL (UUID DEL CELULAR)
-- LA VENTA DE UN ANIMAL NO SE ANOTA AQUI: ENTRA SOLA DESDE TAB_SALIDAS (TIPO VENTA CON VALOR) EN FUN_OBTENER_PLATA_JSON
-- CATEGORIAS: INGRESO -> VENTA_LECHE, OTRO_INGRESO; GASTO -> COMPRA_ANIMAL, DROGAS, SAL_CONCENTRADO, JORNALES, OTRO_GASTO
-- LITROS_MOVIMIENTO: SOLO EN VENTA_LECHE (OPCIONAL), PARA SACAR EL PRECIO POR LITRO
CREATE TABLE IF NOT EXISTS TAB_MOVIMIENTOS
(
    ID_MOVIMIENTO INTEGER NOT NULL,
    UUID_MOVIMIENTO UUID NOT NULL UNIQUE,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    FECHA_EVENTO TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    TIPO_MOVIMIENTO VARCHAR(10) NOT NULL,
    CATEGORIA_MOVIMIENTO VARCHAR(20) NOT NULL,
    VALOR_MOVIMIENTO NUMERIC(12,0) NOT NULL,
    LITROS_MOVIMIENTO NUMERIC(8,1),
    DESCRIPCION_MOVIMIENTO VARCHAR(200),
    ESTADO_MOVIMIENTO VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_MOVIMIENTO),
    CONSTRAINT CK_TIPO_MOVIMIENTO CHECK (TIPO_MOVIMIENTO IN ('INGRESO', 'GASTO')),
    CONSTRAINT CK_CATEGORIA_MOVIMIENTO CHECK (
        (TIPO_MOVIMIENTO = 'INGRESO' AND CATEGORIA_MOVIMIENTO IN ('VENTA_LECHE', 'OTRO_INGRESO')) OR
        (TIPO_MOVIMIENTO = 'GASTO' AND CATEGORIA_MOVIMIENTO IN ('COMPRA_ANIMAL', 'DROGAS', 'SAL_CONCENTRADO', 'JORNALES', 'OTRO_GASTO'))),
    CONSTRAINT CK_VALOR_MOVIMIENTO CHECK (VALOR_MOVIMIENTO > 0),
    CONSTRAINT CK_LITROS_MOVIMIENTO CHECK (LITROS_MOVIMIENTO IS NULL OR (LITROS_MOVIMIENTO > 0 AND CATEGORIA_MOVIMIENTO = 'VENTA_LECHE')),
    CONSTRAINT CK_ESTADO_MOVIMIENTO CHECK (ESTADO_MOVIMIENTO IN ('ACTIVO', 'ANULADO'))
);
CREATE INDEX IF NOT EXISTS IX_MOVIMIENTOS_SINCRONIZACION ON TAB_MOVIMIENTOS (ID_FINCA, FECHA_MODIFICACION);
CREATE INDEX IF NOT EXISTS IX_MOVIMIENTOS_FECHA ON TAB_MOVIMIENTOS (ID_FINCA, FECHA_EVENTO);

-- TRIGGERS (LOS MISMOS DE FUN_TAB_AUDITORIA.SQL)
CREATE OR REPLACE TRIGGER TRG_PROTEGER_MOVIMIENTOS BEFORE INSERT OR UPDATE ON TAB_MOVIMIENTOS FOR EACH ROW EXECUTE FUNCTION FUN_TRG_PROTEGER_REGISTRO('uuid_movimiento');
CREATE OR REPLACE TRIGGER TRG_NO_BORRAR_MOVIMIENTOS BEFORE DELETE ON TAB_MOVIMIENTOS FOR EACH ROW EXECUTE FUNCTION FUN_TRG_NO_BORRAR();
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_MOVIMIENTOS AFTER INSERT OR UPDATE OR DELETE ON TAB_MOVIMIENTOS FOR EACH ROW EXECUTE FUNCTION FUN_TRG_AUDITORIA('id_movimiento', 'uuid_movimiento', 'estado_movimiento');
