CREATE OR REPLACE TRIGGER TRG_PROTEGER_OCUPACIONES BEFORE INSERT OR UPDATE ON TAB_OCUPACIONES FOR EACH ROW EXECUTE FUNCTION FUN_TRG_PROTEGER_REGISTRO('uuid_ocupacion');
CREATE OR REPLACE TRIGGER TRG_NO_BORRAR_POTREROS BEFORE DELETE ON TAB_POTREROS FOR EACH ROW EXECUTE FUNCTION FUN_TRG_NO_BORRAR();
CREATE OR REPLACE TRIGGER TRG_NO_BORRAR_OCUPACIONES BEFORE DELETE ON TAB_OCUPACIONES FOR EACH ROW EXECUTE FUNCTION FUN_TRG_NO_BORRAR();
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_POTREROS AFTER INSERT OR UPDATE OR DELETE ON TAB_POTREROS FOR EACH ROW EXECUTE FUNCTION FUN_TRG_AUDITORIA('id_potrero', 'uuid_potrero', 'estado_potrero');
CREATE OR REPLACE TRIGGER TRG_AUDITORIA_OCUPACIONES AFTER INSERT OR UPDATE OR DELETE ON TAB_OCUPACIONES FOR EACH ROW EXECUTE FUNCTION FUN_TRG_AUDITORIA('id_ocupacion', 'uuid_ocupacion', 'estado_ocupacion');
