-- POTREROS DE LA FINCA (FASE 5A). SE CREAN SIN SEÑAL COMO LOS LOTES (UUID DEL CELULAR)
-- AREA_POTRERO: HECTAREAS (OPCIONAL). DIAS_DESCANSO_POTRERO: LOS DIAS QUE DEBE DESCANSAR ANTES DE VOLVER A METER UN LOTE
-- CONTORNO_POTRERO: OPCIONAL, LOS PUNTOS DEL CONTORNO DIBUJADO EN EL MAPA CUANDO HAY SEÑAL: [[LATITUD, LONGITUD], ...]
CREATE TABLE IF NOT EXISTS TAB_POTREROS
(
    ID_POTRERO INTEGER NOT NULL,
    UUID_POTRERO UUID NOT NULL UNIQUE,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    NOM_POTRERO VARCHAR(60) NOT NULL,
    AREA_POTRERO NUMERIC(7,2),
    DIAS_DESCANSO_POTRERO INTEGER NOT NULL DEFAULT 30,
    CONTORNO_POTRERO JSON,
    ESTADO_POTRERO VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_POTRERO),
    CONSTRAINT CK_AREA_POTRERO CHECK (AREA_POTRERO IS NULL OR AREA_POTRERO > 0),
    CONSTRAINT CK_DIAS_DESCANSO_POTRERO CHECK (DIAS_DESCANSO_POTRERO BETWEEN 1 AND 365),
    CONSTRAINT CK_ESTADO_POTRERO CHECK (ESTADO_POTRERO IN ('ACTIVO', 'ANULADO'))
);
CREATE INDEX IF NOT EXISTS IX_POTREROS_SINCRONIZACION ON TAB_POTREROS (ID_FINCA, FECHA_MODIFICACION);
CREATE UNIQUE INDEX IF NOT EXISTS UQ_POTREROS_NOMBRE ON TAB_POTREROS (ID_FINCA, LOWER(NOM_POTRERO)) WHERE ESTADO_POTRERO = 'ACTIVO';

-- OCUPACIONES: CUANDO UN LOTE ENTRO A UN POTRERO (FECHA_EVENTO) Y CUANDO SALIO (FECHA_SALIDA_OCUPACION, NULL = SIGUE AHI)
-- UN LOTE ESTA EN UN SOLO POTRERO A LA VEZ: AL ENTRAR A OTRO, LA OCUPACION ANTERIOR SE CIERRA CON ESA MISMA FECHA
-- EN UN POTRERO PUEDE HABER VARIOS LOTES. LOS DIAS DE DESCANSO SE CUENTAN DESDE QUE SALIO EL ULTIMO LOTE
CREATE TABLE IF NOT EXISTS TAB_OCUPACIONES
(
    ID_OCUPACION INTEGER NOT NULL,
    UUID_OCUPACION UUID NOT NULL UNIQUE,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    ID_POTRERO INTEGER NOT NULL REFERENCES TAB_POTREROS(ID_POTRERO),
    ID_LOTE INTEGER NOT NULL REFERENCES TAB_LOTES(ID_LOTE),
    FECHA_EVENTO TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    FECHA_SALIDA_OCUPACION TIMESTAMP WITHOUT TIME ZONE,
    OBSERVACION_OCUPACION VARCHAR(300),
    ESTADO_OCUPACION VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_OCUPACION),
    CONSTRAINT CK_SALIDA_OCUPACION CHECK (FECHA_SALIDA_OCUPACION IS NULL OR FECHA_SALIDA_OCUPACION >= FECHA_EVENTO),
    CONSTRAINT CK_ESTADO_OCUPACION CHECK (ESTADO_OCUPACION IN ('ACTIVO', 'ANULADO'))
);
CREATE INDEX IF NOT EXISTS IX_OCUPACIONES_SINCRONIZACION ON TAB_OCUPACIONES (ID_FINCA, FECHA_MODIFICACION);
CREATE INDEX IF NOT EXISTS IX_OCUPACIONES_POTRERO ON TAB_OCUPACIONES (ID_POTRERO, FECHA_EVENTO);
CREATE UNIQUE INDEX IF NOT EXISTS UQ_OCUPACIONES_LOTE_ABIERTA ON TAB_OCUPACIONES (ID_LOTE) WHERE FECHA_SALIDA_OCUPACION IS NULL AND ESTADO_OCUPACION = 'ACTIVO';

