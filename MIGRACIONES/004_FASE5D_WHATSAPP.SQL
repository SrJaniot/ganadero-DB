-- COLA DE MENSAJES DE WHATSAPP (FASE 5D): EL RESUMEN DIARIO DE CADA DUEÑO QUE LO ACTIVO. LA LLENA FUN_ENCOLAR_RESUMENES_JSON Y LA VACIA ms-logica
-- (DE A UNO, CON PAUSA ENTRE MENSAJES). UN SOLO RESUMEN POR DUEÑO, FINCA Y DIA. NO SE LLENA DESDE EL CELULAR: SIN UUID
-- ESTADO: PENDIENTE (POR MANDAR), ENVIADO, FALLIDO (3 INTENTOS SIN EXITO) Y SIN_NUMERO (LA CUENTA NO TIENE CELULAR VALIDO)
CREATE TABLE IF NOT EXISTS TAB_MENSAJES_WHATSAPP
(
    ID_MENSAJE INTEGER NOT NULL,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    ID_USUARIO VARCHAR(60) NOT NULL,
    FECHA_RESUMEN DATE NOT NULL,
    TEXTO_MENSAJE VARCHAR(4000) NOT NULL,
    ESTADO_MENSAJE VARCHAR(12) NOT NULL DEFAULT 'PENDIENTE',
    INTENTOS_MENSAJE INTEGER NOT NULL DEFAULT 0,
    ERROR_MENSAJE VARCHAR(300),
    FECHA_ENVIO_MENSAJE TIMESTAMP WITHOUT TIME ZONE,
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_MENSAJE),
    CONSTRAINT UQ_MENSAJE_DIA UNIQUE (ID_FINCA, ID_USUARIO, FECHA_RESUMEN),
    CONSTRAINT CK_ESTADO_MENSAJE CHECK (ESTADO_MENSAJE IN ('PENDIENTE', 'ENVIADO', 'FALLIDO', 'SIN_NUMERO'))
);
CREATE INDEX IF NOT EXISTS IX_MENSAJES_PENDIENTES ON TAB_MENSAJES_WHATSAPP (ESTADO_MENSAJE, ID_MENSAJE);

