#!/bin/sh
# GENERA SETUP_CLEAN_DB.SQL UNIENDO EL DDL, LAS FUNCIONES (FUN_TAB_*.SQL), LOS TRIGGERS Y LOS DATOS SEMILLA
# EJECUTAR CADA VEZ QUE SE AGREGUE O CAMBIE UNA FUNCION:  sh generar_setup.sh
cd "$(dirname "$0")"
{
  echo "-- ════════════════════════════════════════════════════════════════════════════"
  echo "-- SETUP_CLEAN_DB.SQL - BASE DE DATOS DE NEGOCIO DE GANADERO"
  echo "-- ARCHIVO GENERADO CON generar_setup.sh, NO EDITAR A MANO"
  echo "-- FECHA: $(date '+%Y-%m-%d %H:%M')"
  echo "-- ════════════════════════════════════════════════════════════════════════════"
  # ORDEN: TABLAS -> FUNCIONES -> TRIGGERS (FUN_TAB_AUDITORIA) -> DATOS SEMILLA (LOS TRIGGERS YA LOS AUDITAN)
  for f in DDL_GANADERO.SQL FUNCIONES/FUN_GENERALES/FUN_TAB_GENERALES.SQL FUNCIONES/FUN_FINCAS/FUN_TAB_FINCAS.SQL FUNCIONES/FUN_CATALOGOS/FUN_TAB_CATALOGOS.SQL FUNCIONES/FUN_LOTES/FUN_TAB_LOTES.SQL FUNCIONES/FUN_ANIMALES/FUN_TAB_ANIMALES.SQL FUNCIONES/FUN_PESAJES/FUN_TAB_PESAJES.SQL FUNCIONES/FUN_VACUNACIONES/FUN_TAB_VACUNACIONES.SQL FUNCIONES/FUN_SERVICIOS/FUN_TAB_SERVICIOS.SQL FUNCIONES/FUN_PALPACIONES/FUN_TAB_PALPACIONES.SQL FUNCIONES/FUN_PARTOS/FUN_TAB_PARTOS.SQL FUNCIONES/FUN_ORDENOS/FUN_TAB_ORDENOS.SQL FUNCIONES/FUN_SALIDAS/FUN_TAB_SALIDAS.SQL FUNCIONES/FUN_EVENTOS/FUN_TAB_EVENTOS.SQL FUNCIONES/FUN_SINCRONIZACION/FUN_TAB_SINCRONIZACION.SQL FUNCIONES/FUN_AUDITORIA/FUN_TAB_AUDITORIA.SQL FUNCIONES/FUN_CATALOGOS/DML_TAB_CATALOGOS.SQL; do
    echo; echo; echo "-- ═══════════ $f ═══════════"; cat "$f"; echo
  done
} > SETUP_CLEAN_DB.SQL
echo "SETUP_CLEAN_DB.SQL generado"
