--FUNCION PARA VALIDAR LOS DATOS DE UNA FINCA (SIRVE PARA CREAR Y ACTUALIZAR)
--EL ORDEN DE LAS VALIDACIONES ES EL DEL FORMULARIO
CREATE OR REPLACE FUNCTION FUN_VALIDAR_FINCAS(
    jNOM_FINCA TAB_FINCAS.NOM_FINCA%TYPE,
    jMUNICIPIO_FINCA TAB_FINCAS.MUNICIPIO_FINCA%TYPE,
    jVEREDA_FINCA TAB_FINCAS.VEREDA_FINCA%TYPE,
    jREGISTRO_ICA_FINCA TAB_FINCAS.REGISTRO_ICA_FINCA%TYPE,
    jHIERRO_FINCA TAB_FINCAS.HIERRO_FINCA%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    --VALIDACION VARIABLE NOM_FINCA (OBLIGATORIO)
    IF jNOM_FINCA IS NULL OR TRIM(jNOM_FINCA) = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre de la finca');
        RETURN RETORNO;
    ELSIF LENGTH(TRIM(jNOM_FINCA)) > 100 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El nombre de la finca es demasiado largo (máximo 100 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE MUNICIPIO_FINCA (OBLIGATORIO)
    ELSIF jMUNICIPIO_FINCA IS NULL OR TRIM(jMUNICIPIO_FINCA) = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el municipio');
        RETURN RETORNO;
    ELSIF LENGTH(TRIM(jMUNICIPIO_FINCA)) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El municipio es demasiado largo (máximo 80 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE VEREDA_FINCA (OPCIONAL)
    ELSIF LENGTH(TRIM(COALESCE(jVEREDA_FINCA, ''))) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La vereda es demasiado larga (máximo 80 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE REGISTRO_ICA_FINCA (OPCIONAL: LETRAS, NUMEROS Y GUIONES)
    ELSIF COALESCE(TRIM(jREGISTRO_ICA_FINCA), '') <> '' AND NOT TRIM(jREGISTRO_ICA_FINCA) ~ '^[A-Za-z0-9-]{3,30}$' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El registro ICA solo puede tener letras, números y guiones (de 3 a 30)');
        RETURN RETORNO;

    --VALIDACION VARIABLE HIERRO_FINCA (OPCIONAL)
    ELSIF LENGTH(TRIM(COALESCE(jHIERRO_FINCA, ''))) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La descripción del hierro es demasiado larga (máximo 60 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
