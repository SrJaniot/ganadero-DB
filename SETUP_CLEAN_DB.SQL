-- TODAS COMPARTEN: UUID_X, ID_FINCA (REPETIDO A PROPOSITO PARA SINCRONIZAR CON INDICE), ID_ANIMAL, FECHA_EVENTO, OBSERVACION_X, ESTADO_X (ACTIVO / ANULADO)
