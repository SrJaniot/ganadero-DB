CREATE TABLE IF NOT EXISTS TAB_PALPACIONES
(
    ID_PALPACION INTEGER NOT NULL,
    UUID_PALPACION UUID NOT NULL UNIQUE,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    ID_ANIMAL INTEGER NOT NULL REFERENCES TAB_ANIMALES(ID_ANIMAL),
    FECHA_EVENTO TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    ID_SERVICIO INTEGER REFERENCES TAB_SERVICIOS(ID_SERVICIO),
    RESULTADO_PALPACION VARCHAR(10) NOT NULL,
    MESES_GESTACION INTEGER,
    OBSERVACION_PALPACION VARCHAR(300),
    ESTADO_PALPACION VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
