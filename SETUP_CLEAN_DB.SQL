-- FUNCIONES DE LA TABLA TAB_SERVICIOS ---------------------------------------------------------------------------------------------------------------
-- MONTA (CON UN TORO DE LA FINCA O UNO DE AFUERA) O INSEMINACION (LA PAJILLA VA EN TORO_EXTERNO)
-- EL PARTO PROBABLE ES FECHA DEL SERVICIO + DIAS_GESTACION (TAB_CONFIGURACION); LO USAN LA PANTALLA "HOY" Y LAS ALERTAS (FASE 3)



--FUNCION PARA VALIDAR LOS DATOS DE UN SERVICIO (EL TORO LLEGA YA TRADUCIDO A ID)
CREATE OR REPLACE FUNCTION FUN_VALIDAR_SERVICIOS(
    jID_ANIMAL TAB_SERVICIOS.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_SERVICIOS.FECHA_EVENTO%TYPE,
    jTIPO_SERVICIO TAB_SERVICIOS.TIPO_SERVICIO%TYPE,
    jID_TORO TAB_SERVICIOS.ID_TORO%TYPE,
    jTORO_EXTERNO TAB_SERVICIOS.TORO_EXTERNO%TYPE,
    jOBSERVACION TAB_SERVICIOS.OBSERVACION_SERVICIO%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jSEXO VARCHAR;
    jNACIMIENTO DATE;
    jSEXO_TORO VARCHAR;
    jESTADO_TORO VARCHAR;
    jMESES_MINIMOS INTEGER;
BEGIN
    SELECT SEXO_ANIMAL, FECHA_NACIMIENTO INTO jSEXO, jNACIMIENTO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;
    SELECT SEXO_ANIMAL, ESTADO_ANIMAL INTO jSEXO_TORO, jESTADO_TORO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_TORO;
    jMESES_MINIMOS := COALESCE(FUN_CONFIGURACION_NUMERO('MESES_MINIMOS_SERVICIO'), 12)::INTEGER;

    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA)
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;

    --LA HEMBRA
    ELSIF jSEXO <> 'H' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El servicio se registra a una hembra');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO::DATE < jNACIMIENTO + make_interval(months => jMESES_MINIMOS) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', upper(left(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 1)) || substr(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 2)
            || ' tenía menos de ' || jMESES_MINIMOS || ' meses en esa fecha');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_SERVICIOS WHERE ID_ANIMAL = jID_ANIMAL AND FECHA_EVENTO::DATE = jFECHA_EVENTO::DATE AND ESTADO_SERVICIO = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya hay un servicio de ' || FUN_ETIQUETA_ANIMAL(jID_ANIMAL) || ' ese mismo día');
        RETURN RETORNO;

    --VALIDACION VARIABLE TIPO_SERVICIO
    ELSIF jTIPO_SERVICIO IS NULL OR jTIPO_SERVICIO NOT IN ('MONTA', 'INSEMINACION') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige si fue monta o inseminación');
        RETURN RETORNO;

    --EL TORO: DE LA FINCA (MACHO, NO ANULADO) O DE AFUERA, NO LOS DOS. LA INSEMINACION LLEVA LA PAJILLA
    ELSIF jID_TORO IS NOT NULL AND COALESCE(TRIM(jTORO_EXTERNO), '') <> '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige el toro de la finca o escribe el de afuera, no los dos');
        RETURN RETORNO;
    ELSIF jID_TORO IS NOT NULL AND (jSEXO_TORO <> 'M' OR jESTADO_TORO = 'ANULADO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El toro elegido no es un macho de la finca');
        RETURN RETORNO;
    ELSIF jTIPO_SERVICIO = 'INSEMINACION' AND jID_TORO IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'En la inseminación escribe la pajilla (toro de afuera)');
        RETURN RETORNO;
    ELSIF jTIPO_SERVICIO = 'INSEMINACION' AND COALESCE(TRIM(jTORO_EXTERNO), '') = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe la pajilla o el toro de la inseminación');
        RETURN RETORNO;
    ELSIF LENGTH(TRIM(COALESCE(jTORO_EXTERNO, ''))) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El toro de afuera es demasiado largo (máximo 80 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBSERVACION (OPCIONAL)
    ELSIF LENGTH(COALESCE(jOBSERVACION, '')) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La nota es demasiado larga (máximo 300 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



