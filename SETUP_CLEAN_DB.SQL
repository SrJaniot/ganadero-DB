    FROM TAB_ANIMALES WHERE ID_FINCA = jID_FINCA
      AND ((jCOMPLETO AND ESTADO_ANIMAL <> 'ANULADO') OR (NOT jCOMPLETO AND FECHA_MODIFICACION > jDESDE_REAL));

