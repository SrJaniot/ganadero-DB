-- FUNCIONES DE LA TABLA TAB_PESAJES -----------------------------------------------------------------------------------------------------------------
-- ES EL EVENTO CON EL QUE SE PRUEBA EL MOTOR DE SINCRONIZACION EN LA FASE 0
-- TODOS LOS ROLES DE LA FINCA PUEDEN PESAR. EL PESO ACTUAL DEL ANIMAL LO MANTIENE EL TRIGGER TRG_PESO_ACTUAL



-- FUNCION QUE ESTIMA EL PESO CON EL PERIMETRO TORACICO (CINTA). FORMULA DE QUETELET: KILOS = (PERIMETRO EN METROS)³ × COEFICIENTE_CINTA
-- ES UNA ESTIMACION: EL PESAJE QUEDA MARCADO CON ESTIMADO_CINTA = 'SI'
CREATE OR REPLACE FUNCTION FUN_PESO_POR_CINTA(
    jPERIMETRO_CM TAB_PESAJES.PERIMETRO_CM%TYPE
) RETURNS NUMERIC AS
$$
BEGIN
    IF jPERIMETRO_CM IS NULL OR jPERIMETRO_CM <= 0 THEN
        RETURN NULL;
    END IF;
    RETURN round(power(jPERIMETRO_CM / 100.0, 3) * COALESCE(FUN_CONFIGURACION_NUMERO('COEFICIENTE_CINTA'), 80), 1);
END;
$$ LANGUAGE plpgsql;



--FUNCION PARA VALIDAR LOS DATOS DE UN PESAJE
CREATE OR REPLACE FUNCTION FUN_VALIDAR_PESAJES(
    jID_ANIMAL TAB_PESAJES.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_PESAJES.FECHA_EVENTO%TYPE,
    jPESO_KG TAB_PESAJES.PESO_KG%TYPE,
    jESTIMADO_CINTA TAB_PESAJES.ESTIMADO_CINTA%TYPE,
    jPERIMETRO_CM TAB_PESAJES.PERIMETRO_CM%TYPE,
    jOBSERVACION TAB_PESAJES.OBSERVACION_PESAJE%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA)
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;

    --VALIDACION VARIABLE ESTIMADO_CINTA Y PERIMETRO_CM
    ELSIF jESTIMADO_CINTA IS NULL OR jESTIMADO_CINTA NOT IN ('SI', 'NO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Indica si el peso es con báscula o con cinta');
        RETURN RETORNO;
    ELSIF jESTIMADO_CINTA = 'SI' AND (jPERIMETRO_CM IS NULL OR jPERIMETRO_CM < 50 OR jPERIMETRO_CM > 300) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Con cinta, escribe el perímetro del pecho en centímetros (de 50 a 300)');
        RETURN RETORNO;

    --VALIDACION VARIABLE PESO_KG
    ELSIF jPESO_KG IS NULL OR jPESO_KG <= 0 OR jPESO_KG > 1500 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe un peso entre 1 y 1500 kilos');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBSERVACION (OPCIONAL)
    ELSIF LENGTH(COALESCE(jOBSERVACION, '')) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La nota es demasiado larga (máximo 300 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA REGISTRAR UN PESAJE. CON CINTA Y SIN PESO, EL PESO SE CALCULA CON EL PERIMETRO
-- IDEMPOTENTE: SI EL UUID YA EXISTE RESPONDE 200 CON YA_EXISTIA Y NO DUPLICA
CREATE OR REPLACE FUNCTION FUN_CREAR_PESAJE_JSON(
    jUUID_PESAJE TAB_PESAJES.UUID_PESAJE%TYPE,
    jID_FINCA TAB_PESAJES.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jPESO_KG TAB_PESAJES.PESO_KG%TYPE,
    jESTIMADO_CINTA TAB_PESAJES.ESTIMADO_CINTA%TYPE,
    jPERIMETRO_CM TAB_PESAJES.PERIMETRO_CM%TYPE,
    jFECHA_EVENTO TAB_PESAJES.FECHA_EVENTO%TYPE,
    jOBSERVACION TAB_PESAJES.OBSERVACION_PESAJE%TYPE,
    jID_USUARIO TAB_PESAJES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_PESAJE INTEGER;
    jID_ANIMAL INTEGER;
    jPESO NUMERIC;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_PESAJE INTO jID_PESAJE FROM TAB_PESAJES WHERE UUID_PESAJE = jUUID_PESAJE;
    IF jID_PESAJE IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El pesaje ya estaba guardado',
            'DATOS', json_build_object('ID_PESAJE', jID_PESAJE, 'UUID_PESAJE', jUUID_PESAJE, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_PESAJE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del pesaje');
        RETURN RETORNO;
    END IF;

    --TRADUCIR EL ANIMAL Y CALCULAR EL PESO CON CINTA SI NO VINO
    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    jPESO := CASE WHEN jESTIMADO_CINTA = 'SI' AND jPESO_KG IS NULL THEN FUN_PESO_POR_CINTA(jPERIMETRO_CM) ELSE jPESO_KG END;

    --LLAMAR A LA FUNCION DE VALIDACION
    jVALIDACION := FUN_VALIDAR_PESAJES(jID_ANIMAL, jFECHA_EVENTO, jPESO, COALESCE(jESTIMADO_CINTA, 'NO'), jPERIMETRO_CM, jOBSERVACION);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --INSERTAR EL PESAJE (EL TRIGGER TRG_PESO_ACTUAL ACTUALIZA EL PESO DEL ANIMAL)
    jID_PESAJE := funcion_Retorna_ultmoid('TAB_PESAJES', 'ID_PESAJE');
    INSERT INTO TAB_PESAJES (ID_PESAJE, UUID_PESAJE, ID_FINCA, ID_ANIMAL, FECHA_EVENTO, PESO_KG, ESTIMADO_CINTA, PERIMETRO_CM, OBSERVACION_PESAJE, USUARIO_CREACION)
    VALUES (jID_PESAJE, jUUID_PESAJE, jID_FINCA, jID_ANIMAL, jFECHA_EVENTO, jPESO, COALESCE(jESTIMADO_CINTA, 'NO'),
        CASE WHEN jESTIMADO_CINTA = 'SI' THEN jPERIMETRO_CM END, NULLIF(TRIM(jOBSERVACION), ''), jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Pesaje guardado: ' || trim(to_char(jPESO, 'FM9990.0')) || ' kg',
            'DATOS', json_build_object('ID_PESAJE', jID_PESAJE, 'UUID_PESAJE', jUUID_PESAJE, 'PESO_KG', jPESO, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al guardar el pesaje');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- ═══════════ FUNCIONES/FUN_VACUNACIONES/FUN_TAB_VACUNACIONES.SQL ═══════════
-- FUNCIONES DE LA TABLA TAB_VACUNACIONES ------------------------------------------------------------------------------------------------------------
-- VACUNAS, TRATAMIENTOS Y DESPARASITANTES. LA PROXIMA DOSIS Y EL FIN DEL RETIRO DE LECHE SE CALCULAN CON EL CATALOGO Y QUEDAN GUARDADOS
-- (SI EL ADMINISTRADOR CAMBIA EL CATALOGO DESPUES, LO YA REGISTRADO CONSERVA SUS FECHAS)



--FUNCION PARA VALIDAR LOS DATOS DE UNA VACUNACION
CREATE OR REPLACE FUNCTION FUN_VALIDAR_VACUNACIONES(
    jID_ANIMAL TAB_VACUNACIONES.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_VACUNACIONES.FECHA_EVENTO%TYPE,
    jID_VACUNA TAB_VACUNACIONES.ID_VACUNA%TYPE,
    jDOSIS TAB_VACUNACIONES.DOSIS_VACUNACION%TYPE,
    jOBSERVACION TAB_VACUNACIONES.OBSERVACION_VACUNACION%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA)
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;

    --VALIDACION VARIABLE ID_VACUNA
    ELSIF jID_VACUNA IS NULL OR NOT EXISTS (SELECT 1 FROM TAB_VACUNAS WHERE ID_VACUNA = jID_VACUNA AND ESTADO_VACUNA = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige la vacuna o el producto de la lista');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_VACUNACIONES WHERE ID_ANIMAL = jID_ANIMAL AND ID_VACUNA = jID_VACUNA
                  AND FECHA_EVENTO::DATE = jFECHA_EVENTO::DATE AND ESTADO_VACUNACION = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ese producto ya se le registró a ' || FUN_ETIQUETA_ANIMAL(jID_ANIMAL) || ' ese mismo día');
        RETURN RETORNO;

    --VALIDACION VARIABLE DOSIS (OPCIONAL)
    ELSIF LENGTH(TRIM(COALESCE(jDOSIS, ''))) > 40 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La dosis es demasiado larga (máximo 40 caracteres)');
