-- CREACION DE TABLAS INDEPENDIENTES --------------------------------------------------------------------------------------------------------------------------

-- TABLA DE FINCAS
-- REGISTRO_ICA_FINCA: REGISTRO DEL PREDIO ANTE EL ICA (OPCIONAL)
-- HIERRO_FINCA: DESCRIPCION O CODIGO DEL HIERRO CON QUE SE MARCA EL GANADO (OPCIONAL)
-- ESTADO_FINCA: ACTIVO / INACTIVO
CREATE TABLE IF NOT EXISTS TAB_FINCAS
(
    ID_FINCA INTEGER NOT NULL,
    NOM_FINCA VARCHAR(100) NOT NULL,
    MUNICIPIO_FINCA VARCHAR(80) NOT NULL,
    VEREDA_FINCA VARCHAR(80),
    REGISTRO_ICA_FINCA VARCHAR(30),
    HIERRO_FINCA VARCHAR(60),
    ESTADO_FINCA VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_FINCA),
    CONSTRAINT CK_ESTADO_FINCA CHECK (ESTADO_FINCA IN ('ACTIVO', 'INACTIVO'))
);

-- TABLA DE CONFIGURACION GENERAL (PARES NOMBRE / VALOR QUE EDITA EL ADMINISTRADOR)
-- VALOR_ORIGINAL_CONFIGURACION: EL VALOR DE FABRICA
CREATE TABLE IF NOT EXISTS TAB_CONFIGURACION
(
    ID_CONFIGURACION INTEGER NOT NULL,
    NOM_CONFIGURACION VARCHAR(80) NOT NULL UNIQUE,
    VALOR_CONFIGURACION VARCHAR NOT NULL DEFAULT '',
    VALOR_ORIGINAL_CONFIGURACION VARCHAR NOT NULL DEFAULT '',
    DESCRIPCION_CONFIGURACION VARCHAR,
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_CONFIGURACION)
);

-- CATALOGO GLOBAL DE RAZAS (LO MANTIENE EL ADMINISTRADOR; SE BAJA AL CELULAR)
CREATE TABLE IF NOT EXISTS TAB_RAZAS
(
    ID_RAZA INTEGER NOT NULL,
    NOM_RAZA VARCHAR(60) NOT NULL UNIQUE,
    ESTADO_RAZA VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_RAZA),
    CONSTRAINT CK_ESTADO_RAZA CHECK (ESTADO_RAZA IN ('ACTIVO', 'INACTIVO'))
);

-- CATALOGO GLOBAL DE VACUNAS, TRATAMIENTOS Y DESPARASITANTES (DECISION 27/10/2026: GLOBAL, LO MANTIENE EL ADMINISTRADOR)
-- DIAS_REFUERZO: CADA CUANTO SE REPITE (NULL = DOSIS UNICA). CON ESTO SE CALCULA LA PROXIMA DOSIS
-- DIAS_RETIRO_LECHE: DIAS QUE NO SE PUEDE VENDER LA LECHE DESPUES DE APLICARLO (SEGUN LA ETIQUETA DEL PRODUCTO)
-- OBLIGATORIA_ICA: SI = ENTRA EN LOS CICLOS DEL ICA (AFTOSA, BRUCELOSIS)
CREATE TABLE IF NOT EXISTS TAB_VACUNAS
(
    ID_VACUNA INTEGER NOT NULL,
    NOM_VACUNA VARCHAR(80) NOT NULL UNIQUE,
    TIPO_VACUNA VARCHAR(15) NOT NULL,
    DIAS_REFUERZO INTEGER,
    DIAS_RETIRO_LECHE INTEGER NOT NULL DEFAULT 0,
    OBLIGATORIA_ICA VARCHAR(2) NOT NULL DEFAULT 'NO',
    ESTADO_VACUNA VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_VACUNA),
    CONSTRAINT CK_TIPO_VACUNA CHECK (TIPO_VACUNA IN ('VACUNA', 'TRATAMIENTO', 'DESPARASITANTE', 'VITAMINA')),
    CONSTRAINT CK_DIAS_REFUERZO CHECK (DIAS_REFUERZO IS NULL OR DIAS_REFUERZO > 0),
    CONSTRAINT CK_DIAS_RETIRO_LECHE CHECK (DIAS_RETIRO_LECHE >= 0),
    CONSTRAINT CK_OBLIGATORIA_ICA CHECK (OBLIGATORIA_ICA IN ('SI', 'NO')),
    CONSTRAINT CK_ESTADO_VACUNA CHECK (ESTADO_VACUNA IN ('ACTIVO', 'INACTIVO'))
);

-- TABLA DE AUDITORIA: LA LLENAN SOLO LOS TRIGGERS TRG_AUDITORIA_* (NINGUNA FUNCION ESCRIBE AQUI)
-- EXCEPCION A LA REGLA DEL ID CON funcion_Retorna_ultmoid: SE ESCRIBE EN CADA CAMBIO DE CUALQUIER TABLA; CON EL CANDADO DE ultmoid
-- TODAS LAS ESCRITURAS DE LA BASE QUEDARIAN EN FILA. POR ESO USA IDENTITY (EL ID SOLO ORDENA; NADIE LO PIDE DESDE AFUERA)
-- OPERACION_AUDITORIA: CREAR, EDITAR, ANULAR (EL ESTADO PASO A ANULADO), BORRAR (SOLO LIMPIEZAS DE PRUEBA)
-- CAMBIOS_AUDITORIA: EN EDITAR Y ANULAR, SOLO LAS COLUMNAS QUE CAMBIARON {"columna": {"ANTES": .., "DESPUES": ..}}
-- DATOS_AUDITORIA: EN CREAR, LA FILA NUEVA; EN BORRAR, LA FILA QUE SE BORRO
CREATE TABLE IF NOT EXISTS TAB_AUDITORIAS
(
    ID_AUDITORIA BIGINT GENERATED ALWAYS AS IDENTITY,
    NOM_TABLA_AUDITORIA VARCHAR(60) NOT NULL,
    OPERACION_AUDITORIA VARCHAR(10) NOT NULL,
    ID_REGISTRO_AUDITORIA INTEGER,
    UUID_REGISTRO_AUDITORIA UUID,
    ID_FINCA INTEGER,
    CAMBIOS_AUDITORIA JSONB,
    DATOS_AUDITORIA JSONB,
    USUARIO_AUDITORIA VARCHAR,
    FECHA_AUDITORIA TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (ID_AUDITORIA),
    CONSTRAINT CK_OPERACION_AUDITORIA CHECK (OPERACION_AUDITORIA IN ('CREAR', 'EDITAR', 'ANULAR', 'BORRAR'))
);
CREATE INDEX IF NOT EXISTS IX_AUDITORIAS_REGISTRO ON TAB_AUDITORIAS (NOM_TABLA_AUDITORIA, ID_REGISTRO_AUDITORIA);
CREATE INDEX IF NOT EXISTS IX_AUDITORIAS_FINCA_FECHA ON TAB_AUDITORIAS (ID_FINCA, FECHA_AUDITORIA);



-- CREACION DE TABLAS DEPENDIENTES -----------------------------------------------------------------------------------------------------------------------

-- CICLOS DE VACUNACION DEL ICA (CAMBIAN CADA AÑO; LOS CREA EL ADMINISTRADOR)
CREATE TABLE IF NOT EXISTS TAB_CICLOS_ICA
(
    ID_CICLO INTEGER NOT NULL,
    ID_VACUNA INTEGER NOT NULL REFERENCES TAB_VACUNAS(ID_VACUNA),
    NOM_CICLO VARCHAR(80) NOT NULL,
    FECHA_INICIO_CICLO DATE NOT NULL,
    FECHA_FIN_CICLO DATE NOT NULL,
    ESTADO_CICLO VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_CICLO),
    CONSTRAINT CK_FECHAS_CICLO CHECK (FECHA_FIN_CICLO >= FECHA_INICIO_CICLO),
    CONSTRAINT CK_ESTADO_CICLO CHECK (ESTADO_CICLO IN ('ACTIVO', 'ANULADO'))
);

-- QUIEN TRABAJA EN QUE FINCA Y CON QUE ROL
-- ID_USUARIO: EL id_usuario DE SEGURIDAD (SIN FK). ms-logica LO SACA DEL TOKEN Y SE LO PASA A CADA FUNCION
-- NOM_PERSONA: COPIA DEL NOMBRE PARA MOSTRARLO SIN IR A SEGURIDAD
-- ROL_FINCA: DUENIO (TODO EN SU FINCA), VAQUERO (REGISTRA, NO CORRIGE NI ANULA), VETERINARIO (REGISTRA SANIDAD Y REPRODUCCION, FASE 5)
--   DECISION 27/10/2026: UN ROL POR PERSONA EN SEGURIDAD; ROL_FINCA QUEDA LISTO POR SI ALGUIEN TRABAJA EN DOS FINCAS CON ROLES DISTINTOS
-- ESTADO_FINCA_PERSONA: ACTIVO / INACTIVO (YA NO TRABAJA AHI; NO VE LA FINCA)
CREATE TABLE IF NOT EXISTS TAB_FINCAS_PERSONAS
(
    ID_FINCA_PERSONA INTEGER NOT NULL,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    ID_USUARIO VARCHAR(60) NOT NULL,
    NOM_PERSONA VARCHAR(150) NOT NULL,
    ROL_FINCA VARCHAR(12) NOT NULL,
    ESTADO_FINCA_PERSONA VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_FINCA_PERSONA),
    CONSTRAINT UQ_FINCA_USUARIO UNIQUE (ID_FINCA, ID_USUARIO),
    CONSTRAINT CK_ROL_FINCA CHECK (ROL_FINCA IN ('DUENIO', 'VAQUERO', 'VETERINARIO')),
    CONSTRAINT CK_ESTADO_FINCA_PERSONA CHECK (ESTADO_FINCA_PERSONA IN ('ACTIVO', 'INACTIVO'))
);
CREATE INDEX IF NOT EXISTS IX_FINCAS_PERSONAS_USUARIO ON TAB_FINCAS_PERSONAS (ID_USUARIO);

-- REGISTRO DE CADA SINCRONIZACION (PANTALLA "SINCRONIZACION" Y SOPORTE)
-- DETALLE_SINCRONIZACION: LOS RECHAZADOS CON SU MENSAJE
CREATE TABLE IF NOT EXISTS TAB_SINCRONIZACIONES
(
    ID_SINCRONIZACION INTEGER NOT NULL,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    ID_USUARIO VARCHAR(60) NOT NULL,
    FECHA_SINCRONIZACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    RECIBIDOS_SINCRONIZACION INTEGER NOT NULL DEFAULT 0,
    GUARDADOS_SINCRONIZACION INTEGER NOT NULL DEFAULT 0,
    OMITIDOS_SINCRONIZACION INTEGER NOT NULL DEFAULT 0,
    RECHAZADOS_SINCRONIZACION INTEGER NOT NULL DEFAULT 0,
    DETALLE_SINCRONIZACION JSON,
    PRIMARY KEY (ID_SINCRONIZACION)
);
CREATE INDEX IF NOT EXISTS IX_SINCRONIZACIONES_FINCA ON TAB_SINCRONIZACIONES (ID_FINCA, FECHA_SINCRONIZACION);

-- LOTES DE LA FINCA (ORDEÑO, HORRAS, LEVANTE, CEBA...). SE PUEDEN CREAR SIN SEÑAL
CREATE TABLE IF NOT EXISTS TAB_LOTES
(
    ID_LOTE INTEGER NOT NULL,
    UUID_LOTE UUID NOT NULL UNIQUE,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    NOM_LOTE VARCHAR(60) NOT NULL,
    ESTADO_LOTE VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_LOTE),
    CONSTRAINT CK_ESTADO_LOTE CHECK (ESTADO_LOTE IN ('ACTIVO', 'ANULADO'))
);
CREATE INDEX IF NOT EXISTS IX_LOTES_SINCRONIZACION ON TAB_LOTES (ID_FINCA, FECHA_MODIFICACION);
CREATE UNIQUE INDEX IF NOT EXISTS UQ_LOTES_NOMBRE ON TAB_LOTES (ID_FINCA, LOWER(NOM_LOTE)) WHERE ESTADO_LOTE = 'ACTIVO';

-- ANIMALES DEL HATO. LA CATEGORIA (TERNERA, NOVILLA, VACA, TORO...) NO SE GUARDA: LA CALCULA FUN_CATEGORIA_ANIMAL
-- CHAPETA_ANIMAL: NUMERO DE LA CHAPETA, UNICO POR FINCA ENTRE LOS NO ANULADOS (PUEDE ESTAR VACIA: UNA CRIA AUN SIN CHAPETA)
-- SEXO_ANIMAL: H (HEMBRA) / M (MACHO)
-- FECHA_NACIMIENTO_ESTIMADA: SI = ANIMAL COMPRADO DEL QUE SOLO SE SABE LA EDAD APROXIMADA
-- ID_MADRE / ID_PADRE: ANIMALES DE LA MISMA FINCA. PADRE_EXTERNO: PAJILLA O TORO PRESTADO (TEXTO LIBRE)
-- ORIGEN_ANIMAL: NACIDO (EN LA FINCA) / COMPRADO. FECHA_INGRESO_ANIMAL: CUANDO LLEGO (COMPRADO) O NACIO
-- PESO_ACTUAL_KG Y FECHA_ULTIMO_PESAJE: LOS MANTIENE EL TRIGGER TRG_PESO_ACTUAL CON EL ULTIMO PESAJE ACTIVO
-- FECHA_SALIDA_ANIMAL Y LOS ESTADOS VENDIDO / MUERTO / TRASLADADO: LOS PONE EL TRIGGER TRG_SALIDA_ANIMAL
CREATE TABLE IF NOT EXISTS TAB_ANIMALES
(
    ID_ANIMAL INTEGER NOT NULL,
    UUID_ANIMAL UUID NOT NULL UNIQUE,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    ID_LOTE INTEGER REFERENCES TAB_LOTES(ID_LOTE),
    ID_RAZA INTEGER REFERENCES TAB_RAZAS(ID_RAZA),
    CHAPETA_ANIMAL VARCHAR(20),
    NOM_ANIMAL VARCHAR(60),
    SEXO_ANIMAL VARCHAR(1) NOT NULL,
    FECHA_NACIMIENTO DATE NOT NULL,
    FECHA_NACIMIENTO_ESTIMADA VARCHAR(2) NOT NULL DEFAULT 'NO',
    ID_MADRE INTEGER REFERENCES TAB_ANIMALES(ID_ANIMAL),
    ID_PADRE INTEGER REFERENCES TAB_ANIMALES(ID_ANIMAL),
    PADRE_EXTERNO VARCHAR(80),
    ORIGEN_ANIMAL VARCHAR(10) NOT NULL DEFAULT 'NACIDO',
    FECHA_INGRESO_ANIMAL DATE NOT NULL,
    FOTO_ANIMAL VARCHAR(200),
    PESO_ACTUAL_KG NUMERIC(6,1),
    FECHA_ULTIMO_PESAJE TIMESTAMP WITHOUT TIME ZONE,
    FECHA_SALIDA_ANIMAL TIMESTAMP WITHOUT TIME ZONE,
    ESTADO_ANIMAL VARCHAR(12) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_ANIMAL),
    CONSTRAINT CK_SEXO_ANIMAL CHECK (SEXO_ANIMAL IN ('H', 'M')),
    CONSTRAINT CK_FECHA_NACIMIENTO_ESTIMADA CHECK (FECHA_NACIMIENTO_ESTIMADA IN ('SI', 'NO')),
    CONSTRAINT CK_ORIGEN_ANIMAL CHECK (ORIGEN_ANIMAL IN ('NACIDO', 'COMPRADO')),
    CONSTRAINT CK_ESTADO_ANIMAL CHECK (ESTADO_ANIMAL IN ('ACTIVO', 'VENDIDO', 'MUERTO', 'TRASLADADO', 'ANULADO')),
    CONSTRAINT CK_MADRE_PADRE_ANIMAL CHECK (ID_MADRE IS DISTINCT FROM ID_ANIMAL AND ID_PADRE IS DISTINCT FROM ID_ANIMAL)
);
CREATE INDEX IF NOT EXISTS IX_ANIMALES_SINCRONIZACION ON TAB_ANIMALES (ID_FINCA, FECHA_MODIFICACION);
CREATE UNIQUE INDEX IF NOT EXISTS UQ_ANIMALES_CHAPETA ON TAB_ANIMALES (ID_FINCA, CHAPETA_ANIMAL) WHERE CHAPETA_ANIMAL IS NOT NULL AND ESTADO_ANIMAL <> 'ANULADO';
CREATE INDEX IF NOT EXISTS IX_ANIMALES_MADRE ON TAB_ANIMALES (ID_MADRE);



