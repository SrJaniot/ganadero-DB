    CONSTRAINT CK_MESES_GESTACION CHECK ((RESULTADO_PALPACION = 'VACIA' AND MESES_GESTACION IS NULL) OR (RESULTADO_PALPACION = 'PRENIADA' AND MESES_GESTACION BETWEEN 1 AND 9)),
