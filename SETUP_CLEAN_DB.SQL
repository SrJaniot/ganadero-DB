CREATE INDEX IF NOT EXISTS IX_SERVICIOS_SINCRONIZACION ON TAB_SERVICIOS (ID_FINCA, FECHA_MODIFICACION);
CREATE INDEX IF NOT EXISTS IX_SERVICIOS_ANIMAL ON TAB_SERVICIOS (ID_ANIMAL, FECHA_EVENTO);

