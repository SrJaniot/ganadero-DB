CREATE INDEX IF NOT EXISTS IX_VACUNACIONES_SINCRONIZACION ON TAB_VACUNACIONES (ID_FINCA, FECHA_MODIFICACION);
CREATE INDEX IF NOT EXISTS IX_VACUNACIONES_ANIMAL ON TAB_VACUNACIONES (ID_ANIMAL, FECHA_EVENTO);

-- SERVICIOS: MONTA (CON UN TORO DE LA FINCA O UNO DE AFUERA) O INSEMINACION (PAJILLA EN TORO_EXTERNO)
