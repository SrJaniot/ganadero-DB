        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Finca creada: ya puedes registrar tus animales', 'DATOS', json_build_object('ID_FINCA', jID_FINCA));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



