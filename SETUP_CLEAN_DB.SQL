-- FUNCION QUE DEVUELVE LAS ULTIMAS 20 SINCRONIZACIONES (PANTALLA "SINCRONIZACION"). EL DUEÑO VE LAS DE TODOS; LOS DEMAS, LAS SUYAS
CREATE OR REPLACE FUNCTION FUN_OBTENER_SINCRONIZACIONES_JSON(
    jID_FINCA TAB_SINCRONIZACIONES.ID_FINCA%TYPE,
    jID_USUARIO TAB_SINCRONIZACIONES.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    LISTA_SINCRONIZACIONES JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT json_agg(json_build_object(
        'ID_SINCRONIZACION', T.ID_SINCRONIZACION,
        'NOM_PERSONA', T.NOM_PERSONA,
        'FECHA_SINCRONIZACION', T.FECHA_SINCRONIZACION,
        'RECIBIDOS_SINCRONIZACION', T.RECIBIDOS_SINCRONIZACION,
        'GUARDADOS_SINCRONIZACION', T.GUARDADOS_SINCRONIZACION,
        'OMITIDOS_SINCRONIZACION', T.OMITIDOS_SINCRONIZACION,
        'RECHAZADOS_SINCRONIZACION', T.RECHAZADOS_SINCRONIZACION,
        'DETALLE_SINCRONIZACION', T.DETALLE_SINCRONIZACION
    ) ORDER BY T.ID_SINCRONIZACION DESC) INTO LISTA_SINCRONIZACIONES
    FROM (
        SELECT S.*, P.NOM_PERSONA
        FROM TAB_SINCRONIZACIONES S
        LEFT JOIN TAB_FINCAS_PERSONAS P ON P.ID_FINCA = S.ID_FINCA AND P.ID_USUARIO = S.ID_USUARIO
        WHERE S.ID_FINCA = jID_FINCA
          AND (jVALIDACION -> 'DATOS' ->> 'ROL_FINCA' = 'DUENIO' OR S.ID_USUARIO = jID_USUARIO)
        ORDER BY S.ID_SINCRONIZACION DESC
        LIMIT 20
    ) T;

    IF LISTA_SINCRONIZACIONES IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Todavía no hay sincronizaciones');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Últimas sincronizaciones', 'DATOS', LISTA_SINCRONIZACIONES);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- ═══════════ FUNCIONES/FUN_AUDITORIA/FUN_TAB_AUDITORIA.SQL ═══════════
-- TRIGGERS DE GANADERO Y CONSULTAS DE LA AUDITORIA --------------------------------------------------------------------------------------------------
-- LA LOGICA DE NEGOCIO SIGUE EN LAS FUNCIONES FUN_*_JSON. LOS TRIGGERS SOLO HACEN LO QUE DEBE CUMPLIRSE SIEMPRE, VENGA EL CAMBIO DE DONDE VENGA
-- (UNA FUNCION, LA SINCRONIZACION O UN UPDATE A MANO EN psql):
--
--   TRIGGER                 CUANDO                          QUE HACE
--   TRG_PROTEGER_<TABLA>    BEFORE INSERT / UPDATE          PONE FECHA_MODIFICACION = NOW() (LA MARCA CON LA QUE EL CELULAR BAJA LOS CAMBIOS)
--                                                           E IMPIDE CAMBIAR UUID, FINCA, FECHA_CREACION Y USUARIO_CREACION
--   TRG_NO_BORRAR_<TABLA>   BEFORE DELETE                   IMPIDE EL DELETE: AQUI SE ANULA (SALVO LIMPIEZAS CON ganadero.permitir_borrar = 'SI')
--   TRG_AUDITORIA_<TABLA>   AFTER INSERT / UPDATE / DELETE  GUARDA EN TAB_AUDITORIAS QUIEN CAMBIO QUE Y CUANDO (SOLO LAS COLUMNAS QUE CAMBIARON)
--   TRG_PESO_ACTUAL         AFTER INSERT / UPDATE PESAJE    DEJA EN EL ANIMAL EL PESO DEL ULTIMO PESAJE ACTIVO (TAMBIEN AL ANULAR UNO)
--   TRG_SALIDA_ANIMAL       AFTER INSERT / UPDATE SALIDA    VENTA / MUERTE / TRASLADO CAMBIA EL ESTADO DEL ANIMAL; ANULAR LA SALIDA LO DEVUELVE A ACTIVO



-- FUNCION DEL TRIGGER QUE PROTEGE LOS REGISTROS SINCRONIZABLES
-- TG_ARGV[0]: COLUMNA UUID EN MINUSCULAS ('' SI LA TABLA NO TIENE)
-- FECHA_MODIFICACION TAMBIEN SE PONE AL CREAR: ASI "LO QUE CAMBIO DESDE LA MARCA" INCLUYE LO NUEVO SIN COALESCE
CREATE OR REPLACE FUNCTION FUN_TRG_PROTEGER_REGISTRO() RETURNS TRIGGER AS
$$
DECLARE
    jNUEVO JSONB;
    jVIEJO JSONB;
    jCOLUMNA VARCHAR;
BEGIN
    NEW.FECHA_MODIFICACION := NOW();
    IF TG_OP = 'INSERT' THEN
        RETURN NEW;
    END IF;

    --COLUMNAS QUE NO SE PUEDEN CAMBIAR NUNCA
    jNUEVO := to_jsonb(NEW);
    jVIEJO := to_jsonb(OLD);
    FOREACH jCOLUMNA IN ARRAY ARRAY[NULLIF(TG_ARGV[0], ''), 'id_finca', 'fecha_creacion', 'usuario_creacion'] LOOP
        IF jCOLUMNA IS NOT NULL AND jNUEVO ? jCOLUMNA AND (jNUEVO -> jCOLUMNA) IS DISTINCT FROM (jVIEJO -> jCOLUMNA) THEN
            RAISE EXCEPTION 'En % no se puede cambiar la columna %', upper(TG_TABLE_NAME), upper(jCOLUMNA);
        END IF;
    END LOOP;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;



-- FUNCION DEL TRIGGER QUE IMPIDE BORRAR: EN GANADERO SE ANULA (ESTADO = 'ANULADO') PARA QUE LA ANULACION LLEGUE A TODOS LOS CELULARES
-- PARA LIMPIAR DATOS DE PRUEBA O DE LA DEMO, DENTRO DE LA TRANSACCION: SET LOCAL ganadero.permitir_borrar = 'SI';
CREATE OR REPLACE FUNCTION FUN_TRG_NO_BORRAR() RETURNS TRIGGER AS
$$
BEGIN
    IF COALESCE(current_setting('ganadero.permitir_borrar', true), '') = 'SI' THEN
        RETURN OLD;
    END IF;
    RAISE EXCEPTION 'En % no se borra: se anula (ESTADO = ANULADO)', upper(TG_TABLE_NAME);
END;
$$ LANGUAGE plpgsql;



-- FUNCION DEL TRIGGER DE AUDITORIA
-- TG_ARGV[0]: COLUMNA ID, TG_ARGV[1]: COLUMNA UUID ('' SI NO TIENE), TG_ARGV[2]: COLUMNA ESTADO ('' SI NO TIENE). TODAS EN MINUSCULAS
-- EN UN UPDATE SOLO GUARDA LAS COLUMNAS QUE CAMBIARON; SI SOLO CAMBIO FECHA_MODIFICACION O USUARIO_MODIFICACION NO GUARDA NADA
CREATE OR REPLACE FUNCTION FUN_TRG_AUDITORIA() RETURNS TRIGGER AS
$$
DECLARE
    jNUEVO JSONB;
    jVIEJO JSONB;
    jFILA JSONB;
    jCAMBIOS JSONB;
    jOPERACION VARCHAR;
    jUSUARIO VARCHAR;
    jUUID_TEXTO VARCHAR;
BEGIN
    IF TG_OP IN ('INSERT', 'UPDATE') THEN
        jNUEVO := to_jsonb(NEW);
    END IF;
    IF TG_OP IN ('UPDATE', 'DELETE') THEN
        jVIEJO := to_jsonb(OLD);
    END IF;
    jFILA := COALESCE(jNUEVO, jVIEJO);

    --QUE OPERACION FUE Y QUIEN LA HIZO
    IF TG_OP = 'INSERT' THEN
        jOPERACION := 'CREAR';
        jUSUARIO := jNUEVO ->> 'usuario_creacion';
    ELSIF TG_OP = 'UPDATE' THEN
        --COLUMNAS QUE CAMBIARON (SIN CONTAR LA MARCA DE MODIFICACION)
        SELECT jsonb_object_agg(N.key, jsonb_build_object('ANTES', V.value, 'DESPUES', N.value)) INTO jCAMBIOS
        FROM jsonb_each(jNUEVO) N
        JOIN jsonb_each(jVIEJO) V ON V.key = N.key
        WHERE N.value IS DISTINCT FROM V.value
          AND N.key NOT IN ('fecha_modificacion', 'usuario_modificacion');
        IF jCAMBIOS IS NULL THEN
            RETURN NULL;
        END IF;
        jOPERACION := CASE WHEN TG_ARGV[2] <> '' AND jNUEVO ->> TG_ARGV[2] = 'ANULADO' AND jVIEJO ->> TG_ARGV[2] <> 'ANULADO' THEN 'ANULAR' ELSE 'EDITAR' END;
        jUSUARIO := COALESCE(jNUEVO ->> 'usuario_modificacion', jNUEVO ->> 'usuario_creacion');
    ELSE
        jOPERACION := 'BORRAR';
        jUSUARIO := current_user;
    END IF;

    jUUID_TEXTO := CASE WHEN TG_ARGV[1] <> '' THEN jFILA ->> TG_ARGV[1] END;

    --GUARDAR EL REGISTRO DE AUDITORIA
    INSERT INTO TAB_AUDITORIAS (NOM_TABLA_AUDITORIA, OPERACION_AUDITORIA, ID_REGISTRO_AUDITORIA, UUID_REGISTRO_AUDITORIA, ID_FINCA,
        CAMBIOS_AUDITORIA, DATOS_AUDITORIA, USUARIO_AUDITORIA)
    VALUES (upper(TG_TABLE_NAME), jOPERACION, (jFILA ->> TG_ARGV[0])::INTEGER, jUUID_TEXTO::UUID, (jFILA ->> 'id_finca')::INTEGER,
        jCAMBIOS, CASE WHEN TG_OP = 'UPDATE' THEN NULL ELSE jFILA END, jUSUARIO);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;



-- FUNCION DEL TRIGGER QUE DEJA EN EL ANIMAL EL PESO DE SU ULTIMO PESAJE ACTIVO
-- SE RECALCULA DESDE LOS PESAJES (NO SE COPIA EL NUEVO): ASI FUNCIONA IGUAL SI LLEGA TARDE UN PESAJE VIEJO O SI SE ANULA EL ULTIMO
CREATE OR REPLACE FUNCTION FUN_TRG_PESO_ACTUAL() RETURNS TRIGGER AS
$$
DECLARE
    jPESO NUMERIC;
    jFECHA TIMESTAMP;
BEGIN
    SELECT PESO_KG, FECHA_EVENTO INTO jPESO, jFECHA
    FROM TAB_PESAJES
    WHERE ID_ANIMAL = NEW.ID_ANIMAL AND ESTADO_PESAJE = 'ACTIVO'
    ORDER BY FECHA_EVENTO DESC, ID_PESAJE DESC
    LIMIT 1;

    UPDATE TAB_ANIMALES
    SET PESO_ACTUAL_KG = jPESO,
        FECHA_ULTIMO_PESAJE = jFECHA,
        USUARIO_MODIFICACION = COALESCE(NEW.USUARIO_MODIFICACION, NEW.USUARIO_CREACION)
    WHERE ID_ANIMAL = NEW.ID_ANIMAL
      AND (PESO_ACTUAL_KG IS DISTINCT FROM jPESO OR FECHA_ULTIMO_PESAJE IS DISTINCT FROM jFECHA);
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;



-- FUNCION DEL TRIGGER QUE CAMBIA EL ESTADO DEL ANIMAL CON SU SALIDA
-- SALIDA ACTIVA: VENTA -> VENDIDO, MUERTE -> MUERTO, TRASLADO -> TRASLADADO. SALIDA ANULADA: VUELVE A ACTIVO
CREATE OR REPLACE FUNCTION FUN_TRG_SALIDA_ANIMAL() RETURNS TRIGGER AS
$$
BEGIN
    IF NEW.ESTADO_SALIDA = 'ACTIVO' THEN
        UPDATE TAB_ANIMALES
        SET ESTADO_ANIMAL = CASE NEW.TIPO_SALIDA WHEN 'VENTA' THEN 'VENDIDO' WHEN 'MUERTE' THEN 'MUERTO' ELSE 'TRASLADADO' END,
            FECHA_SALIDA_ANIMAL = NEW.FECHA_EVENTO,
            USUARIO_MODIFICACION = COALESCE(NEW.USUARIO_MODIFICACION, NEW.USUARIO_CREACION)
        WHERE ID_ANIMAL = NEW.ID_ANIMAL;
    ELSIF TG_OP = 'UPDATE' AND OLD.ESTADO_SALIDA = 'ACTIVO' THEN
        UPDATE TAB_ANIMALES
        SET ESTADO_ANIMAL = 'ACTIVO',
            FECHA_SALIDA_ANIMAL = NULL,
            USUARIO_MODIFICACION = COALESCE(NEW.USUARIO_MODIFICACION, NEW.USUARIO_CREACION)
        WHERE ID_ANIMAL = NEW.ID_ANIMAL AND ESTADO_ANIMAL IN ('VENDIDO', 'MUERTO', 'TRASLADADO');
    END IF;
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;



