) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ORDENO INTEGER;
    jID_ANIMAL INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_ORDENO INTO jID_ORDENO FROM TAB_ORDENOS WHERE UUID_ORDENO = jUUID_ORDENO;
    IF jID_ORDENO IS NOT NULL THEN
