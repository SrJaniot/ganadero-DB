    FROM TAB_VACUNACIONES E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_VACUNACION = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

