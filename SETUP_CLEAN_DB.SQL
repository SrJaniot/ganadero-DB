    jSEXO VARCHAR;
    jDIAS_MINIMOS INTEGER;
    jPARTO_CERCANO TIMESTAMP;
BEGIN
    SELECT SEXO_ANIMAL INTO jSEXO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;
    jDIAS_MINIMOS := COALESCE(FUN_CONFIGURACION_NUMERO('DIAS_MINIMOS_ENTRE_PARTOS'), 240)::INTEGER;
    SELECT FECHA_EVENTO INTO jPARTO_CERCANO FROM TAB_PARTOS
    WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PARTO = 'ACTIVO'
      AND abs(FECHA_EVENTO::DATE - jFECHA_EVENTO::DATE) < jDIAS_MINIMOS
    LIMIT 1;

    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA)
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;

    --LA MADRE
    ELSIF jSEXO <> 'H' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El parto se registra a una hembra');
        RETURN RETORNO;
    ELSIF FUN_CATEGORIA_ANIMAL(jID_ANIMAL, jFECHA_EVENTO::DATE) = 'TERNERA' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'En esa fecha era una ternera: no pudo parir');
        RETURN RETORNO;
    ELSIF jPARTO_CERCANO IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', upper(left(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 1)) || substr(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 2)
            || ' ya tiene un parto el ' || to_char(jPARTO_CERCANO, 'DD/MM/YYYY') || ': dos partos deben estar separados al menos ' || jDIAS_MINIMOS || ' días');
        RETURN RETORNO;

    --VALIDACION VARIABLE TIPO_PARTO Y CRIA_VIVA
    ELSIF jTIPO_PARTO IS NULL OR jTIPO_PARTO NOT IN ('NORMAL', 'ASISTIDO', 'CESAREA', 'ABORTO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige cómo fue: normal, asistido, cesárea o aborto');
        RETURN RETORNO;
    ELSIF jCRIA_VIVA IS NULL OR jCRIA_VIVA NOT IN ('SI', 'NO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Indica si la cría nació viva');
        RETURN RETORNO;
    ELSIF jTIPO_PARTO = 'ABORTO' AND jCRIA_VIVA = 'SI' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'En un aborto no hay cría viva');
        RETURN RETORNO;
    ELSIF jSEXO_CRIA IS NOT NULL AND jSEXO_CRIA NOT IN ('H', 'M') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El sexo de la cría debe ser hembra o macho');
        RETURN RETORNO;

    --LA CRIA VIVA: UUID, SEXO, CHAPETA OPCIONAL Y UNICA, PESO AL NACER OPCIONAL
    ELSIF jCRIA_VIVA = 'SI' AND jUUID_CRIA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID de la cría');
        RETURN RETORNO;
    ELSIF jCRIA_VIVA = 'SI' AND EXISTS (SELECT 1 FROM TAB_ANIMALES WHERE UUID_ANIMAL = jUUID_CRIA) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya existe un animal con el UUID de la cría');
        RETURN RETORNO;
    ELSIF jCRIA_VIVA = 'SI' AND jSEXO_CRIA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige si la cría es ternera o ternero');
        RETURN RETORNO;
    ELSIF jCRIA_VIVA = 'SI' AND COALESCE(TRIM(jCHAPETA_CRIA), '') <> '' AND NOT TRIM(jCHAPETA_CRIA) ~ '^[A-Za-z0-9-]{1,20}$' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La chapeta solo puede tener letras, números y guiones (máximo 20)');
        RETURN RETORNO;
    ELSIF jCRIA_VIVA = 'SI' AND COALESCE(TRIM(jCHAPETA_CRIA), '') <> '' AND EXISTS (SELECT 1 FROM TAB_ANIMALES
                  WHERE ID_FINCA = jID_FINCA AND CHAPETA_ANIMAL = UPPER(TRIM(jCHAPETA_CRIA)) AND ESTADO_ANIMAL <> 'ANULADO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La chapeta ' || UPPER(TRIM(jCHAPETA_CRIA)) || ' ya la tiene otro animal de la finca');
        RETURN RETORNO;
    ELSIF jCRIA_VIVA = 'SI' AND LENGTH(TRIM(COALESCE(jNOM_CRIA, ''))) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El nombre de la cría es demasiado largo (máximo 60 caracteres)');
        RETURN RETORNO;
    ELSIF jCRIA_VIVA = 'SI' AND jPESO_CRIA_KG IS NOT NULL AND (jPESO_CRIA_KG < 5 OR jPESO_CRIA_KG > 80) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El peso al nacer debe estar entre 5 y 80 kilos');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBSERVACION (OPCIONAL)
    ELSIF LENGTH(COALESCE(jOBSERVACION, '')) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La nota es demasiado larga (máximo 300 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA REGISTRAR UN PARTO. CON CRIA VIVA CREA LA CRIA Y SU PESO AL NACER
-- HASTA TRES DML (CRIA, PARTO, PESAJE): BLOQUE BEGIN ... EXCEPTION CON RAISE EXCEPTION (ROLLBACK REAL)
-- IDEMPOTENTE: SI EL UUID DEL PARTO YA EXISTE RESPONDE 200 CON YA_EXISTIA Y NO DUPLICA
CREATE OR REPLACE FUNCTION FUN_CREAR_PARTO_JSON(
    jUUID_PARTO TAB_PARTOS.UUID_PARTO%TYPE,
    jID_FINCA TAB_PARTOS.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jTIPO_PARTO TAB_PARTOS.TIPO_PARTO%TYPE,
    jCRIA_VIVA TAB_PARTOS.CRIA_VIVA%TYPE,
    jUUID_CRIA TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jSEXO_CRIA TAB_PARTOS.SEXO_CRIA%TYPE,
    jCHAPETA_CRIA TAB_ANIMALES.CHAPETA_ANIMAL%TYPE,
    jNOM_CRIA TAB_ANIMALES.NOM_ANIMAL%TYPE,
    jPESO_CRIA_KG TAB_PESAJES.PESO_KG%TYPE,
    jFECHA_EVENTO TAB_PARTOS.FECHA_EVENTO%TYPE,
    jOBSERVACION TAB_PARTOS.OBSERVACION_PARTO%TYPE,
    jID_USUARIO TAB_PARTOS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_PARTO INTEGER;
    jID_ANIMAL INTEGER;
    jID_CRIA INTEGER;
    jID_PESAJE INTEGER;
    jID_LOTE INTEGER;
    jID_TORO INTEGER;
    jTORO_EXTERNO VARCHAR;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_PARTO, ID_CRIA INTO jID_PARTO, jID_CRIA FROM TAB_PARTOS WHERE UUID_PARTO = jUUID_PARTO;
    IF jID_PARTO IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El parto ya estaba guardado',
            'DATOS', json_build_object('ID_PARTO', jID_PARTO, 'UUID_PARTO', jUUID_PARTO, 'ID_CRIA', jID_CRIA, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_PARTO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del parto');
        RETURN RETORNO;
    END IF;

    --LLAMAR A LA FUNCION DE VALIDACION
    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    jVALIDACION := FUN_VALIDAR_PARTOS(jID_FINCA, jID_ANIMAL, jFECHA_EVENTO, jTIPO_PARTO, jCRIA_VIVA, jUUID_CRIA, jSEXO_CRIA,
        jCHAPETA_CRIA, jNOM_CRIA, jPESO_CRIA_KG, jOBSERVACION);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --EL PADRE: ULTIMO SERVICIO ACTIVO ANTES DEL PARTO Y DESPUES DEL PARTO ANTERIOR. LA CRIA QUEDA EN EL LOTE DE LA MADRE
    SELECT S.ID_TORO, S.TORO_EXTERNO INTO jID_TORO, jTORO_EXTERNO
    FROM TAB_SERVICIOS S
    WHERE S.ID_ANIMAL = jID_ANIMAL AND S.ESTADO_SERVICIO = 'ACTIVO' AND S.FECHA_EVENTO < jFECHA_EVENTO
      AND S.FECHA_EVENTO > COALESCE((SELECT MAX(P.FECHA_EVENTO) FROM TAB_PARTOS P WHERE P.ID_ANIMAL = jID_ANIMAL AND P.ESTADO_PARTO = 'ACTIVO' AND P.FECHA_EVENTO < jFECHA_EVENTO), '-infinity')
    ORDER BY S.FECHA_EVENTO DESC LIMIT 1;
    SELECT ID_LOTE INTO jID_LOTE FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;

    BEGIN
        --1. LA CRIA VIVA ENTRA AL HATO
        IF jCRIA_VIVA = 'SI' THEN
            jID_CRIA := funcion_Retorna_ultmoid('TAB_ANIMALES', 'ID_ANIMAL');
            INSERT INTO TAB_ANIMALES (ID_ANIMAL, UUID_ANIMAL, ID_FINCA, ID_LOTE, CHAPETA_ANIMAL, NOM_ANIMAL, SEXO_ANIMAL, FECHA_NACIMIENTO,
                ID_MADRE, ID_PADRE, PADRE_EXTERNO, ORIGEN_ANIMAL, FECHA_INGRESO_ANIMAL, USUARIO_CREACION)
            VALUES (jID_CRIA, jUUID_CRIA, jID_FINCA, jID_LOTE, NULLIF(UPPER(TRIM(jCHAPETA_CRIA)), ''), NULLIF(regexp_replace(TRIM(jNOM_CRIA), '\s+', ' ', 'g'), ''),
                jSEXO_CRIA, jFECHA_EVENTO::DATE, jID_ANIMAL, jID_TORO, jTORO_EXTERNO, 'NACIDO', jFECHA_EVENTO::DATE, jID_USUARIO);
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No se pudo registrar la cría';
            END IF;
        END IF;

        --2. EL PARTO
        jID_PARTO := funcion_Retorna_ultmoid('TAB_PARTOS', 'ID_PARTO');
        INSERT INTO TAB_PARTOS (ID_PARTO, UUID_PARTO, ID_FINCA, ID_ANIMAL, FECHA_EVENTO, TIPO_PARTO, CRIA_VIVA, SEXO_CRIA, ID_CRIA, OBSERVACION_PARTO, USUARIO_CREACION)
        VALUES (jID_PARTO, jUUID_PARTO, jID_FINCA, jID_ANIMAL, jFECHA_EVENTO, jTIPO_PARTO, jCRIA_VIVA, jSEXO_CRIA, jID_CRIA, NULLIF(TRIM(jOBSERVACION), ''), jID_USUARIO);
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No se pudo registrar el parto';
        END IF;

        --3. EL PESO AL NACER (SI LO ANOTARON). SU UUID LO GENERA LA BASE: EL CELULAR LO RECIBE AL BAJAR LOS CAMBIOS
        IF jCRIA_VIVA = 'SI' AND jPESO_CRIA_KG IS NOT NULL THEN
            jID_PESAJE := funcion_Retorna_ultmoid('TAB_PESAJES', 'ID_PESAJE');
            INSERT INTO TAB_PESAJES (ID_PESAJE, UUID_PESAJE, ID_FINCA, ID_ANIMAL, FECHA_EVENTO, PESO_KG, OBSERVACION_PESAJE, USUARIO_CREACION)
            VALUES (jID_PESAJE, gen_random_uuid(), jID_FINCA, jID_CRIA, jFECHA_EVENTO, jPESO_CRIA_KG, 'Peso al nacer', jID_USUARIO);
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No se pudo registrar el peso al nacer';
            END IF;
        END IF;

        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE',
            CASE WHEN jCRIA_VIVA = 'SI' THEN 'Parto guardado: ' || CASE WHEN jSEXO_CRIA = 'H' THEN 'la ternera' ELSE 'el ternero' END || ' ya está en el hato'
                 WHEN jTIPO_PARTO = 'ABORTO' THEN 'Aborto registrado'
                 ELSE 'Parto guardado (cría muerta)' END,
            'DATOS', json_build_object('ID_PARTO', jID_PARTO, 'UUID_PARTO', jUUID_PARTO, 'ID_CRIA', jID_CRIA, 'UUID_CRIA', CASE WHEN jCRIA_VIVA = 'SI' THEN jUUID_CRIA END,
                'YA_EXISTIA', false));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



