-- FUNCION PARA ANULAR UN LOTE (SOLO EL DUEÑO). SUS ANIMALES QUEDAN SIN LOTE
-- DOS DML: BLOQUE BEGIN ... EXCEPTION. SI YA ESTABA ANULADO RESPONDE 200 CON YA_EXISTIA (REINTENTO SEGURO)
CREATE OR REPLACE FUNCTION FUN_ANULAR_LOTE_JSON(
    jUUID_LOTE TAB_LOTES.UUID_LOTE%TYPE,
    jID_FINCA TAB_LOTES.ID_FINCA%TYPE,
    jID_USUARIO TAB_LOTES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_LOTE INTEGER;
    jESTADO VARCHAR;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT ID_LOTE, ESTADO_LOTE INTO jID_LOTE, jESTADO FROM TAB_LOTES WHERE UUID_LOTE = jUUID_LOTE AND ID_FINCA = jID_FINCA;
    IF jID_LOTE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El lote no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El lote ya estaba anulado', 'DATOS', json_build_object('YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    BEGIN
        --LOS ANIMALES DEL LOTE QUEDAN SIN LOTE (PUEDE QUE NO HAYA NINGUNO: NO SE REVISA FOUND)
        UPDATE TAB_ANIMALES
        SET ID_LOTE = NULL,
            USUARIO_MODIFICACION = jID_USUARIO,
            FECHA_MODIFICACION = NOW()
        WHERE ID_LOTE = jID_LOTE;

        --ANULAR EL LOTE
        UPDATE TAB_LOTES
        SET ESTADO_LOTE = 'ANULADO',
            USUARIO_MODIFICACION = jID_USUARIO,
            FECHA_MODIFICACION = NOW()
        WHERE ID_LOTE = jID_LOTE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No se pudo anular el lote';
        END IF;

        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Lote anulado: sus animales quedaron sin lote', 'DATOS', json_build_object('YA_EXISTIA', false));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



