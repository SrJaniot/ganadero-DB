-- PESAJES. ESTIMADO_CINTA = SI: EL PESO SE CALCULO CON EL PERIMETRO TORACICO (FUN_PESO_POR_CINTA)
CREATE TABLE IF NOT EXISTS TAB_PESAJES
(
    ID_PESAJE INTEGER NOT NULL,
    UUID_PESAJE UUID NOT NULL UNIQUE,
    ID_FINCA INTEGER NOT NULL REFERENCES TAB_FINCAS(ID_FINCA),
    ID_ANIMAL INTEGER NOT NULL REFERENCES TAB_ANIMALES(ID_ANIMAL),
    FECHA_EVENTO TIMESTAMP WITHOUT TIME ZONE NOT NULL,
    PESO_KG NUMERIC(6,1) NOT NULL,
    ESTIMADO_CINTA VARCHAR(2) NOT NULL DEFAULT 'NO',
    PERIMETRO_CM NUMERIC(5,1),
    OBSERVACION_PESAJE VARCHAR(300),
    ESTADO_PESAJE VARCHAR(10) NOT NULL DEFAULT 'ACTIVO',
    FECHA_CREACION TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
    USUARIO_CREACION VARCHAR NOT NULL,
    FECHA_MODIFICACION TIMESTAMP WITHOUT TIME ZONE,
    USUARIO_MODIFICACION VARCHAR,
    PRIMARY KEY (ID_PESAJE),
    CONSTRAINT CK_PESO_KG CHECK (PESO_KG > 0 AND PESO_KG <= 1500),
    CONSTRAINT CK_ESTIMADO_CINTA CHECK (ESTIMADO_CINTA IN ('SI', 'NO')),
    CONSTRAINT CK_PERIMETRO_CINTA CHECK (ESTIMADO_CINTA = 'NO' OR PERIMETRO_CM IS NOT NULL),
    CONSTRAINT CK_ESTADO_PESAJE CHECK (ESTADO_PESAJE IN ('ACTIVO', 'ANULADO'))
);
CREATE INDEX IF NOT EXISTS IX_PESAJES_SINCRONIZACION ON TAB_PESAJES (ID_FINCA, FECHA_MODIFICACION);
CREATE INDEX IF NOT EXISTS IX_PESAJES_ANIMAL ON TAB_PESAJES (ID_ANIMAL, FECHA_EVENTO);

