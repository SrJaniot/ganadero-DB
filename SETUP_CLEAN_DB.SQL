    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_SERVICIO = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

