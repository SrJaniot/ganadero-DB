-- FUNCIONES DE LA TABLA TAB_VACUNACIONES ------------------------------------------------------------------------------------------------------------
-- VACUNAS, TRATAMIENTOS Y DESPARASITANTES. LA PROXIMA DOSIS Y EL FIN DEL RETIRO DE LECHE SE CALCULAN CON EL CATALOGO Y QUEDAN GUARDADOS
-- (SI EL ADMINISTRADOR CAMBIA EL CATALOGO DESPUES, LO YA REGISTRADO CONSERVA SUS FECHAS)



--FUNCION PARA VALIDAR LOS DATOS DE UNA VACUNACION
CREATE OR REPLACE FUNCTION FUN_VALIDAR_VACUNACIONES(
    jID_ANIMAL TAB_VACUNACIONES.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_VACUNACIONES.FECHA_EVENTO%TYPE,
    jID_VACUNA TAB_VACUNACIONES.ID_VACUNA%TYPE,
    jDOSIS TAB_VACUNACIONES.DOSIS_VACUNACION%TYPE,
    jOBSERVACION TAB_VACUNACIONES.OBSERVACION_VACUNACION%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA)
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;

    --VALIDACION VARIABLE ID_VACUNA
    ELSIF jID_VACUNA IS NULL OR NOT EXISTS (SELECT 1 FROM TAB_VACUNAS WHERE ID_VACUNA = jID_VACUNA AND ESTADO_VACUNA = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige la vacuna o el producto de la lista');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_VACUNACIONES WHERE ID_ANIMAL = jID_ANIMAL AND ID_VACUNA = jID_VACUNA
                  AND FECHA_EVENTO::DATE = jFECHA_EVENTO::DATE AND ESTADO_VACUNACION = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ese producto ya se le registró a ' || FUN_ETIQUETA_ANIMAL(jID_ANIMAL) || ' ese mismo día');
        RETURN RETORNO;

    --VALIDACION VARIABLE DOSIS (OPCIONAL)
    ELSIF LENGTH(TRIM(COALESCE(jDOSIS, ''))) > 40 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La dosis es demasiado larga (máximo 40 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBSERVACION (OPCIONAL)
    ELSIF LENGTH(COALESCE(jOBSERVACION, '')) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La nota es demasiado larga (máximo 300 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA REGISTRAR UNA VACUNACION O TRATAMIENTO
-- IDEMPOTENTE: SI EL UUID YA EXISTE RESPONDE 200 CON YA_EXISTIA Y NO DUPLICA
CREATE OR REPLACE FUNCTION FUN_CREAR_VACUNACION_JSON(
    jUUID_VACUNACION TAB_VACUNACIONES.UUID_VACUNACION%TYPE,
    jID_FINCA TAB_VACUNACIONES.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jID_VACUNA TAB_VACUNACIONES.ID_VACUNA%TYPE,
    jDOSIS TAB_VACUNACIONES.DOSIS_VACUNACION%TYPE,
    jFECHA_EVENTO TAB_VACUNACIONES.FECHA_EVENTO%TYPE,
    jOBSERVACION TAB_VACUNACIONES.OBSERVACION_VACUNACION%TYPE,
    jID_USUARIO TAB_VACUNACIONES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_VACUNACION INTEGER;
    jID_ANIMAL INTEGER;
    jDIAS_REFUERZO INTEGER;
    jDIAS_RETIRO INTEGER;
    jPROXIMA DATE;
    jFIN_RETIRO DATE;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_VACUNACION INTO jID_VACUNACION FROM TAB_VACUNACIONES WHERE UUID_VACUNACION = jUUID_VACUNACION;
    IF jID_VACUNACION IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'La vacunación ya estaba guardada',
            'DATOS', json_build_object('ID_VACUNACION', jID_VACUNACION, 'UUID_VACUNACION', jUUID_VACUNACION, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_VACUNACION IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID de la vacunación');
        RETURN RETORNO;
    END IF;

    --LLAMAR A LA FUNCION DE VALIDACION
    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    jVALIDACION := FUN_VALIDAR_VACUNACIONES(jID_ANIMAL, jFECHA_EVENTO, jID_VACUNA, jDOSIS, jOBSERVACION);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --CALCULAR LA PROXIMA DOSIS Y EL FIN DEL RETIRO DE LECHE CON EL CATALOGO
    SELECT DIAS_REFUERZO, DIAS_RETIRO_LECHE INTO jDIAS_REFUERZO, jDIAS_RETIRO FROM TAB_VACUNAS WHERE ID_VACUNA = jID_VACUNA;
    jPROXIMA := CASE WHEN jDIAS_REFUERZO IS NOT NULL THEN jFECHA_EVENTO::DATE + jDIAS_REFUERZO END;
    jFIN_RETIRO := CASE WHEN jDIAS_RETIRO > 0 THEN jFECHA_EVENTO::DATE + jDIAS_RETIRO END;

    --INSERTAR LA VACUNACION
    jID_VACUNACION := funcion_Retorna_ultmoid('TAB_VACUNACIONES', 'ID_VACUNACION');
    INSERT INTO TAB_VACUNACIONES (ID_VACUNACION, UUID_VACUNACION, ID_FINCA, ID_ANIMAL, FECHA_EVENTO, ID_VACUNA, DOSIS_VACUNACION,
        FECHA_PROXIMA_DOSIS, FECHA_FIN_RETIRO, OBSERVACION_VACUNACION, USUARIO_CREACION)
    VALUES (jID_VACUNACION, jUUID_VACUNACION, jID_FINCA, jID_ANIMAL, jFECHA_EVENTO, jID_VACUNA, NULLIF(TRIM(jDOSIS), ''),
        jPROXIMA, jFIN_RETIRO, NULLIF(TRIM(jOBSERVACION), ''), jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Vacunación guardada'
                || CASE WHEN jFIN_RETIRO IS NOT NULL THEN '. No vender su leche hasta el ' || to_char(jFIN_RETIRO, 'DD/MM/YYYY') ELSE '' END,
            'DATOS', json_build_object('ID_VACUNACION', jID_VACUNACION, 'UUID_VACUNACION', jUUID_VACUNACION,
                'FECHA_PROXIMA_DOSIS', jPROXIMA, 'FECHA_FIN_RETIRO', jFIN_RETIRO, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al guardar la vacunación');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
