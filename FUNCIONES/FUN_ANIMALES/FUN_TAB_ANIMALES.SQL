-- FUNCIONES DE LA TABLA TAB_ANIMALES ----------------------------------------------------------------------------------------------------------------
-- EL CELULAR SE REFIERE A TODO POR UUID (ANIMAL, LOTE, MADRE, PADRE); LA BASE TRADUCE A LOS ID ENTEROS
-- CREAR: DUEÑO Y VAQUERO. EDITAR, CAMBIAR FOTO Y ANULAR: SOLO EL DUEÑO (EL VAQUERO REGISTRA PERO NO CORRIGE NI ANULA)
-- EDITAR ES "GANA EL ULTIMO QUE SINCRONIZA": SI DOS PERSONAS CAMBIAN LA FICHA, QUEDA LA ULTIMA QUE LLEGA



-- FUNCION QUE ARMA EL JSON DE UN ANIMAL (NULL SI NO EXISTE). LA USAN LA LISTA, LA FICHA Y LA SINCRONIZACION
-- VA CON LOS UUID DE LOTE, MADRE Y PADRE PORQUE EL CELULAR GUARDA TODO POR UUID
CREATE OR REPLACE FUNCTION FUN_DATOS_ANIMAL(
    jID_ANIMAL TAB_ANIMALES.ID_ANIMAL%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    SELECT json_build_object(
        'ID_ANIMAL', A.ID_ANIMAL,
        'UUID_ANIMAL', A.UUID_ANIMAL,
        'UUID_LOTE', L.UUID_LOTE,
        'NOM_LOTE', L.NOM_LOTE,
        'ID_RAZA', A.ID_RAZA,
        'NOM_RAZA', R.NOM_RAZA,
        'CHAPETA_ANIMAL', A.CHAPETA_ANIMAL,
        'NOM_ANIMAL', A.NOM_ANIMAL,
        'SEXO_ANIMAL', A.SEXO_ANIMAL,
        'CATEGORIA_ANIMAL', FUN_CATEGORIA_ANIMAL(A.ID_ANIMAL),
        'FECHA_NACIMIENTO', A.FECHA_NACIMIENTO,
        'FECHA_NACIMIENTO_ESTIMADA', A.FECHA_NACIMIENTO_ESTIMADA,
        'UUID_MADRE', M.UUID_ANIMAL,
        'CHAPETA_MADRE', M.CHAPETA_ANIMAL,
        'UUID_PADRE', P.UUID_ANIMAL,
        'CHAPETA_PADRE', P.CHAPETA_ANIMAL,
        'PADRE_EXTERNO', A.PADRE_EXTERNO,
        'ORIGEN_ANIMAL', A.ORIGEN_ANIMAL,
        'FECHA_INGRESO_ANIMAL', A.FECHA_INGRESO_ANIMAL,
        'FOTO_ANIMAL', A.FOTO_ANIMAL,
        'PESO_ACTUAL_KG', A.PESO_ACTUAL_KG,
        'FECHA_ULTIMO_PESAJE', A.FECHA_ULTIMO_PESAJE,
        'FECHA_SALIDA_ANIMAL', A.FECHA_SALIDA_ANIMAL,
        'ESTADO_ANIMAL', A.ESTADO_ANIMAL,
        'FECHA_MODIFICACION', A.FECHA_MODIFICACION
    ) INTO RETORNO
    FROM TAB_ANIMALES A
    LEFT JOIN TAB_LOTES L ON L.ID_LOTE = A.ID_LOTE
    LEFT JOIN TAB_RAZAS R ON R.ID_RAZA = A.ID_RAZA
    LEFT JOIN TAB_ANIMALES M ON M.ID_ANIMAL = A.ID_MADRE
    LEFT JOIN TAB_ANIMALES P ON P.ID_ANIMAL = A.ID_PADRE
    WHERE A.ID_ANIMAL = jID_ANIMAL;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



--FUNCION PARA VALIDAR LOS DATOS DE UN ANIMAL (jID_ANIMAL NULL AL CREAR)
--LA MADRE Y EL PADRE LLEGAN YA TRADUCIDOS A ID (NULL = NO TIENE). EL ORDEN DE LAS VALIDACIONES ES EL DEL FORMULARIO
CREATE OR REPLACE FUNCTION FUN_VALIDAR_ANIMALES(
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jID_ANIMAL TAB_ANIMALES.ID_ANIMAL%TYPE,
    jID_RAZA TAB_ANIMALES.ID_RAZA%TYPE,
    jCHAPETA TAB_ANIMALES.CHAPETA_ANIMAL%TYPE,
    jNOM_ANIMAL TAB_ANIMALES.NOM_ANIMAL%TYPE,
    jSEXO TAB_ANIMALES.SEXO_ANIMAL%TYPE,
    jFECHA_NACIMIENTO TAB_ANIMALES.FECHA_NACIMIENTO%TYPE,
    jFECHA_NACIMIENTO_ESTIMADA TAB_ANIMALES.FECHA_NACIMIENTO_ESTIMADA%TYPE,
    jID_MADRE TAB_ANIMALES.ID_MADRE%TYPE,
    jID_PADRE TAB_ANIMALES.ID_PADRE%TYPE,
    jPADRE_EXTERNO TAB_ANIMALES.PADRE_EXTERNO%TYPE,
    jORIGEN TAB_ANIMALES.ORIGEN_ANIMAL%TYPE,
    jFECHA_INGRESO TAB_ANIMALES.FECHA_INGRESO_ANIMAL%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jSEXO_MADRE VARCHAR;
    jNACIMIENTO_MADRE DATE;
    jSEXO_PADRE VARCHAR;
BEGIN
    SELECT SEXO_ANIMAL, FECHA_NACIMIENTO INTO jSEXO_MADRE, jNACIMIENTO_MADRE FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_MADRE AND ESTADO_ANIMAL <> 'ANULADO';
    SELECT SEXO_ANIMAL INTO jSEXO_PADRE FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_PADRE AND ESTADO_ANIMAL <> 'ANULADO';

    --VALIDACION VARIABLE ID_RAZA (OPCIONAL)
    IF jID_RAZA IS NOT NULL AND NOT EXISTS (SELECT 1 FROM TAB_RAZAS WHERE ID_RAZA = jID_RAZA) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige una raza de la lista');
        RETURN RETORNO;

    --VALIDACION VARIABLE CHAPETA_ANIMAL (OPCIONAL, UNICA EN LA FINCA)
    ELSIF COALESCE(TRIM(jCHAPETA), '') <> '' AND NOT TRIM(jCHAPETA) ~ '^[A-Za-z0-9-]{1,20}$' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La chapeta solo puede tener letras, números y guiones (máximo 20)');
        RETURN RETORNO;
    ELSIF COALESCE(TRIM(jCHAPETA), '') <> '' AND EXISTS (SELECT 1 FROM TAB_ANIMALES WHERE ID_FINCA = jID_FINCA AND CHAPETA_ANIMAL = UPPER(TRIM(jCHAPETA))
                  AND ESTADO_ANIMAL <> 'ANULADO' AND ID_ANIMAL IS DISTINCT FROM jID_ANIMAL) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La chapeta ' || UPPER(TRIM(jCHAPETA)) || ' ya la tiene otro animal de la finca');
        RETURN RETORNO;

    --VALIDACION VARIABLE NOM_ANIMAL (OPCIONAL)
    ELSIF LENGTH(TRIM(COALESCE(jNOM_ANIMAL, ''))) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El nombre es demasiado largo (máximo 60 caracteres)');
        RETURN RETORNO;
    ELSIF COALESCE(TRIM(jCHAPETA), '') = '' AND COALESCE(TRIM(jNOM_ANIMAL), '') = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe la chapeta o un nombre para reconocer al animal');
        RETURN RETORNO;

    --VALIDACION VARIABLE SEXO_ANIMAL
    ELSIF jSEXO IS NULL OR jSEXO NOT IN ('H', 'M') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige si es hembra o macho');
        RETURN RETORNO;

    --VALIDACION VARIABLE FECHA_NACIMIENTO
    ELSIF jFECHA_NACIMIENTO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe la fecha de nacimiento (si no la sabes, una aproximada)');
        RETURN RETORNO;
    ELSIF jFECHA_NACIMIENTO > CURRENT_DATE THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha de nacimiento no puede ser futura');
        RETURN RETORNO;
    ELSIF jFECHA_NACIMIENTO < CURRENT_DATE - INTERVAL '25 years' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Revisa la fecha de nacimiento: el animal tendría más de 25 años');
        RETURN RETORNO;
    ELSIF jFECHA_NACIMIENTO_ESTIMADA IS NULL OR jFECHA_NACIMIENTO_ESTIMADA NOT IN ('SI', 'NO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Indica si la fecha de nacimiento es aproximada (SI o NO)');
        RETURN RETORNO;

    --VALIDACION DE LA MADRE (HEMBRA DE LA FINCA, AL MENOS 15 MESES MAYOR)
    ELSIF jID_MADRE IS NOT NULL AND jSEXO_MADRE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La madre no existe en esta finca');
        RETURN RETORNO;
    ELSIF jID_MADRE IS NOT NULL AND jSEXO_MADRE <> 'H' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La madre debe ser una hembra');
        RETURN RETORNO;
    ELSIF jID_MADRE IS NOT NULL AND jNACIMIENTO_MADRE > jFECHA_NACIMIENTO - INTERVAL '15 months' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La madre es demasiado joven para ser la madre de este animal');
        RETURN RETORNO;
    ELSIF jID_MADRE IS NOT NULL AND jID_MADRE = jID_ANIMAL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Un animal no puede ser su propia madre');
        RETURN RETORNO;

    --VALIDACION DEL PADRE (MACHO DE LA FINCA O TEXTO LIBRE, NO LOS DOS)
    ELSIF jID_PADRE IS NOT NULL AND jSEXO_PADRE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El padre no existe en esta finca');
        RETURN RETORNO;
    ELSIF jID_PADRE IS NOT NULL AND jSEXO_PADRE <> 'M' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El padre debe ser un macho');
        RETURN RETORNO;
    ELSIF jID_PADRE IS NOT NULL AND jID_PADRE = jID_ANIMAL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Un animal no puede ser su propio padre');
        RETURN RETORNO;
    ELSIF jID_PADRE IS NOT NULL AND COALESCE(TRIM(jPADRE_EXTERNO), '') <> '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige el padre de la finca o escribe el de afuera, no los dos');
        RETURN RETORNO;
    ELSIF LENGTH(TRIM(COALESCE(jPADRE_EXTERNO, ''))) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El padre de afuera es demasiado largo (máximo 80 caracteres)');
        RETURN RETORNO;

    --VALIDACION DEL ORIGEN Y LA FECHA DE INGRESO
    ELSIF jORIGEN IS NULL OR jORIGEN NOT IN ('NACIDO', 'COMPRADO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Indica si nació en la finca o fue comprado');
        RETURN RETORNO;
    ELSIF jORIGEN = 'COMPRADO' AND jFECHA_INGRESO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe la fecha en que llegó a la finca');
        RETURN RETORNO;
    ELSIF jORIGEN = 'COMPRADO' AND (jFECHA_INGRESO < jFECHA_NACIMIENTO OR jFECHA_INGRESO > CURRENT_DATE) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha de llegada debe estar entre el nacimiento y hoy');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CREAR UN ANIMAL (NACIDO EN LA FINCA SIN PARTO REGISTRADO, O COMPRADO). LAS CRIAS DE UN PARTO LAS CREA FUN_CREAR_PARTO_JSON
-- IDEMPOTENTE: SI EL UUID YA EXISTE RESPONDE 200 CON YA_EXISTIA Y NO DUPLICA
CREATE OR REPLACE FUNCTION FUN_CREAR_ANIMAL_JSON(
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jUUID_LOTE TAB_LOTES.UUID_LOTE%TYPE,
    jID_RAZA TAB_ANIMALES.ID_RAZA%TYPE,
    jCHAPETA TAB_ANIMALES.CHAPETA_ANIMAL%TYPE,
    jNOM_ANIMAL TAB_ANIMALES.NOM_ANIMAL%TYPE,
    jSEXO TAB_ANIMALES.SEXO_ANIMAL%TYPE,
    jFECHA_NACIMIENTO TAB_ANIMALES.FECHA_NACIMIENTO%TYPE,
    jFECHA_NACIMIENTO_ESTIMADA TAB_ANIMALES.FECHA_NACIMIENTO_ESTIMADA%TYPE,
    jUUID_MADRE TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jUUID_PADRE TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jPADRE_EXTERNO TAB_ANIMALES.PADRE_EXTERNO%TYPE,
    jORIGEN TAB_ANIMALES.ORIGEN_ANIMAL%TYPE,
    jFECHA_INGRESO TAB_ANIMALES.FECHA_INGRESO_ANIMAL%TYPE,
    jID_USUARIO TAB_ANIMALES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ANIMAL INTEGER;
    jID_LOTE INTEGER;
    jID_MADRE INTEGER;
    jID_PADRE INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_ANIMAL INTO jID_ANIMAL FROM TAB_ANIMALES WHERE UUID_ANIMAL = jUUID_ANIMAL;
    IF jID_ANIMAL IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El animal ya estaba guardado',
            'DATOS', json_build_object('ID_ANIMAL', jID_ANIMAL, 'UUID_ANIMAL', jUUID_ANIMAL, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO', 'VAQUERO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_ANIMAL IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del animal');
        RETURN RETORNO;
    END IF;

    --TRADUCIR LOS UUID A ID
    jID_LOTE := FUN_ID_LOTE_POR_UUID(jID_FINCA, jUUID_LOTE);
    jID_MADRE := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_MADRE);
    jID_PADRE := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_PADRE);
    IF jUUID_LOTE IS NOT NULL AND jID_LOTE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El lote no existe en esta finca');
        RETURN RETORNO;
    ELSIF jUUID_MADRE IS NOT NULL AND jID_MADRE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La madre no existe en esta finca');
        RETURN RETORNO;
    ELSIF jUUID_PADRE IS NOT NULL AND jID_PADRE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El padre no existe en esta finca');
        RETURN RETORNO;
    END IF;

    --LLAMAR A LA FUNCION DE VALIDACION
    jVALIDACION := FUN_VALIDAR_ANIMALES(jID_FINCA, NULL, jID_RAZA, jCHAPETA, jNOM_ANIMAL, jSEXO, jFECHA_NACIMIENTO, COALESCE(jFECHA_NACIMIENTO_ESTIMADA, 'NO'),
        jID_MADRE, jID_PADRE, jPADRE_EXTERNO, jORIGEN, jFECHA_INGRESO);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --INSERTAR EL ANIMAL (NACIDO EN LA FINCA: INGRESA EL DIA QUE NACE)
    jID_ANIMAL := funcion_Retorna_ultmoid('TAB_ANIMALES', 'ID_ANIMAL');
    INSERT INTO TAB_ANIMALES (ID_ANIMAL, UUID_ANIMAL, ID_FINCA, ID_LOTE, ID_RAZA, CHAPETA_ANIMAL, NOM_ANIMAL, SEXO_ANIMAL, FECHA_NACIMIENTO,
        FECHA_NACIMIENTO_ESTIMADA, ID_MADRE, ID_PADRE, PADRE_EXTERNO, ORIGEN_ANIMAL, FECHA_INGRESO_ANIMAL, USUARIO_CREACION)
    VALUES (jID_ANIMAL, jUUID_ANIMAL, jID_FINCA, jID_LOTE, jID_RAZA, NULLIF(UPPER(TRIM(jCHAPETA)), ''), NULLIF(regexp_replace(TRIM(jNOM_ANIMAL), '\s+', ' ', 'g'), ''),
        jSEXO, jFECHA_NACIMIENTO, COALESCE(jFECHA_NACIMIENTO_ESTIMADA, 'NO'), jID_MADRE, jID_PADRE, NULLIF(TRIM(jPADRE_EXTERNO), ''), jORIGEN,
        CASE WHEN jORIGEN = 'NACIDO' THEN jFECHA_NACIMIENTO ELSE jFECHA_INGRESO END, jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Animal registrado',
            'DATOS', json_build_object('ID_ANIMAL', jID_ANIMAL, 'UUID_ANIMAL', jUUID_ANIMAL, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al registrar el animal');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ACTUALIZAR LA FICHA DE UN ANIMAL (SOLO EL DUEÑO). NO CAMBIA EL ESTADO: ESO LO HACEN LA SALIDA Y LA ANULACION
CREATE OR REPLACE FUNCTION FUN_ACTUALIZAR_ANIMAL_JSON(
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jUUID_LOTE TAB_LOTES.UUID_LOTE%TYPE,
    jID_RAZA TAB_ANIMALES.ID_RAZA%TYPE,
    jCHAPETA TAB_ANIMALES.CHAPETA_ANIMAL%TYPE,
    jNOM_ANIMAL TAB_ANIMALES.NOM_ANIMAL%TYPE,
    jSEXO TAB_ANIMALES.SEXO_ANIMAL%TYPE,
    jFECHA_NACIMIENTO TAB_ANIMALES.FECHA_NACIMIENTO%TYPE,
    jFECHA_NACIMIENTO_ESTIMADA TAB_ANIMALES.FECHA_NACIMIENTO_ESTIMADA%TYPE,
    jUUID_MADRE TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jUUID_PADRE TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jPADRE_EXTERNO TAB_ANIMALES.PADRE_EXTERNO%TYPE,
    jORIGEN TAB_ANIMALES.ORIGEN_ANIMAL%TYPE,
    jFECHA_INGRESO TAB_ANIMALES.FECHA_INGRESO_ANIMAL%TYPE,
    jID_USUARIO TAB_ANIMALES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ANIMAL INTEGER;
    jESTADO VARCHAR;
    jID_LOTE INTEGER;
    jID_MADRE INTEGER;
    jID_PADRE INTEGER;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    SELECT ESTADO_ANIMAL INTO jESTADO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;
    IF jID_ANIMAL IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El animal no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ese animal fue anulado: no se puede editar');
        RETURN RETORNO;
    END IF;

    --TRADUCIR LOS UUID A ID
    jID_LOTE := FUN_ID_LOTE_POR_UUID(jID_FINCA, jUUID_LOTE);
    jID_MADRE := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_MADRE);
    jID_PADRE := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_PADRE);
    IF jUUID_LOTE IS NOT NULL AND jID_LOTE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El lote no existe en esta finca');
        RETURN RETORNO;
    ELSIF jUUID_MADRE IS NOT NULL AND jID_MADRE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La madre no existe en esta finca');
        RETURN RETORNO;
    ELSIF jUUID_PADRE IS NOT NULL AND jID_PADRE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El padre no existe en esta finca');
        RETURN RETORNO;
    END IF;

    --LLAMAR A LA FUNCION DE VALIDACION
    jVALIDACION := FUN_VALIDAR_ANIMALES(jID_FINCA, jID_ANIMAL, jID_RAZA, jCHAPETA, jNOM_ANIMAL, jSEXO, jFECHA_NACIMIENTO, COALESCE(jFECHA_NACIMIENTO_ESTIMADA, 'NO'),
        jID_MADRE, jID_PADRE, jPADRE_EXTERNO, jORIGEN, jFECHA_INGRESO);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jSEXO = 'M' AND EXISTS (SELECT 1 FROM TAB_PARTOS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PARTO = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'No se puede cambiar a macho: tiene partos registrados');
        RETURN RETORNO;
    END IF;

    --ACTUALIZAR EL ANIMAL
    UPDATE TAB_ANIMALES
    SET ID_LOTE = jID_LOTE,
        ID_RAZA = jID_RAZA,
        CHAPETA_ANIMAL = NULLIF(UPPER(TRIM(jCHAPETA)), ''),
        NOM_ANIMAL = NULLIF(regexp_replace(TRIM(jNOM_ANIMAL), '\s+', ' ', 'g'), ''),
        SEXO_ANIMAL = jSEXO,
        FECHA_NACIMIENTO = jFECHA_NACIMIENTO,
        FECHA_NACIMIENTO_ESTIMADA = COALESCE(jFECHA_NACIMIENTO_ESTIMADA, 'NO'),
        ID_MADRE = jID_MADRE,
        ID_PADRE = jID_PADRE,
        PADRE_EXTERNO = NULLIF(TRIM(jPADRE_EXTERNO), ''),
        ORIGEN_ANIMAL = jORIGEN,
        FECHA_INGRESO_ANIMAL = CASE WHEN jORIGEN = 'NACIDO' THEN jFECHA_NACIMIENTO ELSE jFECHA_INGRESO END,
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_ANIMAL = jID_ANIMAL;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ficha del animal actualizada');
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al actualizar el animal');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CAMBIAR LA FOTO DE UN ANIMAL (SOLO EL DUEÑO). LAS FOTOS SUBEN APARTE Y DESPUES DE LOS DATOS; AQUI SOLO SE GUARDA EL NOMBRE DEL ARCHIVO
CREATE OR REPLACE FUNCTION FUN_ACTUALIZAR_FOTO_ANIMAL_JSON(
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jFOTO TAB_ANIMALES.FOTO_ANIMAL%TYPE,
    jID_USUARIO TAB_ANIMALES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ANIMAL INTEGER;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    IF jID_ANIMAL IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El animal no existe en esta finca');
        RETURN RETORNO;
    ELSIF COALESCE(TRIM(jFOTO), '') <> '' AND NOT TRIM(jFOTO) ~ '^[A-Za-z0-9._-]{1,200}$' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Nombre de archivo de foto no válido');
        RETURN RETORNO;
    END IF;

    UPDATE TAB_ANIMALES
    SET FOTO_ANIMAL = NULLIF(TRIM(jFOTO), ''),
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_ANIMAL = jID_ANIMAL;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', CASE WHEN COALESCE(TRIM(jFOTO), '') = '' THEN 'Foto quitada' ELSE 'Foto guardada' END);
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al guardar la foto');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ANULAR UN ANIMAL REGISTRADO POR ERROR (SOLO EL DUEÑO)
-- NO SE ANULA SI TIENE EVENTOS ACTIVOS, CRIAS O SI NACIO DE UN PARTO (EN ESE CASO SE ANULA EL PARTO). PARA LO QUE SE VENDIO O MURIO ESTA LA SALIDA
CREATE OR REPLACE FUNCTION FUN_ANULAR_ANIMAL_JSON(
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jID_USUARIO TAB_ANIMALES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ANIMAL INTEGER;
    jESTADO VARCHAR;
    jEVENTOS INTEGER;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    SELECT ESTADO_ANIMAL INTO jESTADO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;

    --EVENTOS ACTIVOS DEL ANIMAL (COMO PROTAGONISTA O COMO TORO DE UN SERVICIO)
    SELECT (SELECT COUNT(*) FROM TAB_PESAJES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PESAJE = 'ACTIVO')
         + (SELECT COUNT(*) FROM TAB_VACUNACIONES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_VACUNACION = 'ACTIVO')
         + (SELECT COUNT(*) FROM TAB_SERVICIOS WHERE (ID_ANIMAL = jID_ANIMAL OR ID_TORO = jID_ANIMAL) AND ESTADO_SERVICIO = 'ACTIVO')
         + (SELECT COUNT(*) FROM TAB_PALPACIONES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PALPACION = 'ACTIVO')
         + (SELECT COUNT(*) FROM TAB_PARTOS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PARTO = 'ACTIVO')
         + (SELECT COUNT(*) FROM TAB_ORDENOS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_ORDENO = 'ACTIVO')
         + (SELECT COUNT(*) FROM TAB_SALIDAS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_SALIDA = 'ACTIVO')
    INTO jEVENTOS;

    --VALIDACIONES
    IF jID_ANIMAL IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El animal no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El animal ya estaba anulado', 'DATOS', json_build_object('YA_EXISTIA', true));
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_PARTOS WHERE ID_CRIA = jID_ANIMAL AND ESTADO_PARTO = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Este animal nació de un parto registrado: anula el parto y se anula la cría');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_ANIMALES WHERE (ID_MADRE = jID_ANIMAL OR ID_PADRE = jID_ANIMAL) AND ESTADO_ANIMAL <> 'ANULADO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'No se puede anular: es madre o padre de otros animales');
        RETURN RETORNO;
    ELSIF jEVENTOS > 0 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'No se puede anular: tiene ' || jEVENTOS || ' registros en su línea de tiempo. Si se vendió o murió, registra la salida');
        RETURN RETORNO;
    END IF;

    UPDATE TAB_ANIMALES
    SET ESTADO_ANIMAL = 'ANULADO',
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_ANIMAL = jID_ANIMAL;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Animal anulado', 'DATOS', json_build_object('YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al anular el animal');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LOS ANIMALES DE LA FINCA (jESTADO: 'ACTIVO' = EL HATO DE HOY, 'TODOS' = TAMBIEN LOS VENDIDOS, MUERTOS Y TRASLADADOS)
CREATE OR REPLACE FUNCTION FUN_OBTENER_ANIMALES_JSON(
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jESTADO VARCHAR,
    jID_USUARIO TAB_ANIMALES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    LISTA_ANIMALES JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT json_agg(FUN_DATOS_ANIMAL(ID_ANIMAL) ORDER BY ESTADO_ANIMAL, CHAPETA_ANIMAL NULLS LAST, NOM_ANIMAL) INTO LISTA_ANIMALES
    FROM TAB_ANIMALES
    WHERE ID_FINCA = jID_FINCA
      AND ESTADO_ANIMAL <> 'ANULADO'
      AND (COALESCE(jESTADO, 'ACTIVO') = 'TODOS' OR ESTADO_ANIMAL = 'ACTIVO');

    IF LISTA_ANIMALES IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Todavía no hay animales registrados');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Animales de la finca', 'DATOS', LISTA_ANIMALES);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LA FICHA DE UN ANIMAL CON SUS CRIAS
CREATE OR REPLACE FUNCTION FUN_OBTENER_ANIMAL_POR_UUID_JSON(
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jID_USUARIO TAB_ANIMALES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ANIMAL INTEGER;
    LISTA_CRIAS JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    IF jID_ANIMAL IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El animal no existe en esta finca');
        RETURN RETORNO;
    END IF;

    SELECT json_agg(json_build_object(
        'UUID_ANIMAL', UUID_ANIMAL,
        'CHAPETA_ANIMAL', CHAPETA_ANIMAL,
        'NOM_ANIMAL', NOM_ANIMAL,
        'SEXO_ANIMAL', SEXO_ANIMAL,
        'FECHA_NACIMIENTO', FECHA_NACIMIENTO,
        'ESTADO_ANIMAL', ESTADO_ANIMAL
    ) ORDER BY FECHA_NACIMIENTO DESC) INTO LISTA_CRIAS
    FROM TAB_ANIMALES
    WHERE (ID_MADRE = jID_ANIMAL OR ID_PADRE = jID_ANIMAL) AND ESTADO_ANIMAL <> 'ANULADO';

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ficha del animal',
        'DATOS', json_build_object('ANIMAL', FUN_DATOS_ANIMAL(jID_ANIMAL), 'CRIAS', LISTA_CRIAS));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LA LINEA DE TIEMPO DE UN ANIMAL: TODOS SUS EVENTOS ACTIVOS, DEL MAS NUEVO AL MAS VIEJO, MAS SU NACIMIENTO O LLEGADA
-- SE ARMA CON UNION ALL SOBRE LAS TABLAS DE EVENTOS (SIN CTE). DESCRIPCION_EVENTO YA VIENE EN PALABRAS DEL CAMPO PARA MOSTRARLA TAL CUAL
CREATE OR REPLACE FUNCTION FUN_OBTENER_LINEA_TIEMPO_JSON(
    jID_FINCA TAB_ANIMALES.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jID_USUARIO TAB_ANIMALES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ANIMAL INTEGER;
    LISTA_EVENTOS JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    IF jID_ANIMAL IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El animal no existe en esta finca');
        RETURN RETORNO;
    END IF;

    SELECT json_agg(json_build_object(
        'TIPO_EVENTO', E.TIPO_EVENTO,
        'UUID_EVENTO', E.UUID_EVENTO,
        'FECHA_EVENTO', E.FECHA_EVENTO,
        'DESCRIPCION_EVENTO', E.DESCRIPCION_EVENTO,
        'OBSERVACION_EVENTO', E.OBSERVACION_EVENTO,
        'USUARIO_CREACION', E.USUARIO_CREACION
    ) ORDER BY E.FECHA_EVENTO DESC, E.ORDEN DESC) INTO LISTA_EVENTOS
    FROM (
        SELECT 'NACIMIENTO' AS TIPO_EVENTO, A.UUID_ANIMAL AS UUID_EVENTO, A.FECHA_INGRESO_ANIMAL::TIMESTAMP AS FECHA_EVENTO, 0 AS ORDEN,
            CASE WHEN A.ORIGEN_ANIMAL = 'COMPRADO' THEN 'Llegó a la finca (comprado)' ELSE 'Nació en la finca' END AS DESCRIPCION_EVENTO,
            NULL::VARCHAR AS OBSERVACION_EVENTO, A.USUARIO_CREACION
        FROM TAB_ANIMALES A WHERE A.ID_ANIMAL = jID_ANIMAL
        UNION ALL
        SELECT 'PESAJE', UUID_PESAJE, FECHA_EVENTO, 1,
            'Pesó ' || trim(to_char(PESO_KG, 'FM9990.0')) || ' kg' || CASE WHEN ESTIMADO_CINTA = 'SI' THEN ' (estimado con cinta)' ELSE '' END,
            OBSERVACION_PESAJE, USUARIO_CREACION
        FROM TAB_PESAJES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PESAJE = 'ACTIVO'
        UNION ALL
        SELECT 'VACUNACION', VC.UUID_VACUNACION, VC.FECHA_EVENTO, 1,
            CASE V.TIPO_VACUNA WHEN 'VACUNA' THEN 'Vacunada: ' WHEN 'DESPARASITANTE' THEN 'Desparasitada: ' ELSE 'Tratamiento: ' END || V.NOM_VACUNA
                || CASE WHEN VC.FECHA_FIN_RETIRO > VC.FECHA_EVENTO::DATE THEN ' · sin vender leche hasta el ' || to_char(VC.FECHA_FIN_RETIRO, 'DD/MM/YYYY') ELSE '' END,
            VC.OBSERVACION_VACUNACION, VC.USUARIO_CREACION
        FROM TAB_VACUNACIONES VC JOIN TAB_VACUNAS V ON V.ID_VACUNA = VC.ID_VACUNA
        WHERE VC.ID_ANIMAL = jID_ANIMAL AND VC.ESTADO_VACUNACION = 'ACTIVO'
        UNION ALL
        SELECT 'SERVICIO', S.UUID_SERVICIO, S.FECHA_EVENTO, 2,
            CASE WHEN S.TIPO_SERVICIO = 'MONTA' THEN 'Monta' ELSE 'Inseminación' END
                || COALESCE(' con ' || COALESCE(T.CHAPETA_ANIMAL, T.NOM_ANIMAL), ' con ' || S.TORO_EXTERNO, ''),
            S.OBSERVACION_SERVICIO, S.USUARIO_CREACION
        FROM TAB_SERVICIOS S LEFT JOIN TAB_ANIMALES T ON T.ID_ANIMAL = S.ID_TORO
        WHERE S.ID_ANIMAL = jID_ANIMAL AND S.ESTADO_SERVICIO = 'ACTIVO'
        UNION ALL
        SELECT 'PALPACION', UUID_PALPACION, FECHA_EVENTO, 3,
            CASE WHEN RESULTADO_PALPACION = 'PRENIADA' THEN 'Palpada: preñada de ' || MESES_GESTACION || CASE WHEN MESES_GESTACION = 1 THEN ' mes' ELSE ' meses' END ELSE 'Palpada: vacía' END,
            OBSERVACION_PALPACION, USUARIO_CREACION
        FROM TAB_PALPACIONES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PALPACION = 'ACTIVO'
        UNION ALL
        SELECT 'PARTO', P.UUID_PARTO, P.FECHA_EVENTO, 4,
            CASE WHEN P.TIPO_PARTO = 'ABORTO' THEN 'Abortó'
                 ELSE 'Parió' || CASE WHEN P.SEXO_CRIA = 'H' THEN ' una ternera' WHEN P.SEXO_CRIA = 'M' THEN ' un ternero' ELSE '' END
                      || CASE WHEN P.CRIA_VIVA = 'NO' THEN ' muerta' ELSE '' END
                      || COALESCE(' (' || C.CHAPETA_ANIMAL || ')', '')
                      || CASE WHEN P.TIPO_PARTO IN ('ASISTIDO', 'CESAREA') THEN ' · parto ' || LOWER(P.TIPO_PARTO) ELSE '' END END,
            P.OBSERVACION_PARTO, P.USUARIO_CREACION
        FROM TAB_PARTOS P LEFT JOIN TAB_ANIMALES C ON C.ID_ANIMAL = P.ID_CRIA
        WHERE P.ID_ANIMAL = jID_ANIMAL AND P.ESTADO_PARTO = 'ACTIVO'
        UNION ALL
        SELECT 'ORDENO', UUID_ORDENO, FECHA_EVENTO, 1,
            'Ordeño de la ' || CASE WHEN JORNADA_ORDENO = 'MANANA' THEN 'mañana' ELSE 'tarde' END || ': ' || trim(to_char(LITROS_ORDENO, 'FM990.0')) || ' litros',
            OBSERVACION_ORDENO, USUARIO_CREACION
        FROM TAB_ORDENOS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_ORDENO = 'ACTIVO'
        UNION ALL
        SELECT 'SALIDA', UUID_SALIDA, FECHA_EVENTO, 9,
            CASE TIPO_SALIDA WHEN 'VENTA' THEN 'Se vendió' || COALESCE(' por $' || trim(to_char(VALOR_SALIDA, 'FM999G999G999G990')), '')
                             WHEN 'MUERTE' THEN 'Murió' || COALESCE(': ' || CAUSA_SALIDA, '')
                             ELSE 'Salió de la finca (traslado)' END,
            OBSERVACION_SALIDA, USUARIO_CREACION
        FROM TAB_SALIDAS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_SALIDA = 'ACTIVO'
    ) E;

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Línea de tiempo', 'DATOS', LISTA_EVENTOS);
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
