-- FUNCION QUE DEVUELVE LAS RAZAS ACTIVAS
CREATE OR REPLACE FUNCTION FUN_OBTENER_RAZAS_JSON(
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    LISTA_RAZAS JSON;
BEGIN
    SELECT json_agg(json_build_object('ID_RAZA', ID_RAZA, 'NOM_RAZA', NOM_RAZA) ORDER BY NOM_RAZA) INTO LISTA_RAZAS
    FROM TAB_RAZAS WHERE ESTADO_RAZA = 'ACTIVO';

    IF LISTA_RAZAS IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'No hay razas registradas');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Razas', 'DATOS', LISTA_RAZAS);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CREAR UNA RAZA (ADMINISTRADOR)
CREATE OR REPLACE FUNCTION FUN_CREAR_RAZA_JSON(
    jNOM_RAZA TAB_RAZAS.NOM_RAZA%TYPE,
    jUSUARIO TAB_RAZAS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jID_RAZA INTEGER;
BEGIN
    --VALIDACIONES
    IF jNOM_RAZA IS NULL OR TRIM(jNOM_RAZA) = '' OR LENGTH(TRIM(jNOM_RAZA)) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre de la raza (máximo 60 caracteres)');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_RAZAS WHERE LOWER(NOM_RAZA) = LOWER(TRIM(jNOM_RAZA))) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Esa raza ya existe');
        RETURN RETORNO;
    END IF;

    jID_RAZA := funcion_Retorna_ultmoid('TAB_RAZAS', 'ID_RAZA');
    INSERT INTO TAB_RAZAS (ID_RAZA, NOM_RAZA, USUARIO_CREACION)
    VALUES (jID_RAZA, regexp_replace(TRIM(jNOM_RAZA), '\s+', ' ', 'g'), jUSUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Raza creada', 'DATOS', json_build_object('ID_RAZA', jID_RAZA));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al crear la raza');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LAS VACUNAS Y TRATAMIENTOS (jSOLO_ACTIVAS = 'SI' PARA LOS FORMULARIOS, 'NO' PARA LA PANTALLA DE CONFIGURACION)
CREATE OR REPLACE FUNCTION FUN_OBTENER_VACUNAS_JSON(
    jSOLO_ACTIVAS VARCHAR
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    LISTA_VACUNAS JSON;
BEGIN
    SELECT json_agg(json_build_object(
        'ID_VACUNA', ID_VACUNA,
        'NOM_VACUNA', NOM_VACUNA,
        'TIPO_VACUNA', TIPO_VACUNA,
        'DIAS_REFUERZO', DIAS_REFUERZO,
        'DIAS_RETIRO_LECHE', DIAS_RETIRO_LECHE,
        'OBLIGATORIA_ICA', OBLIGATORIA_ICA,
        'ESTADO_VACUNA', ESTADO_VACUNA
    ) ORDER BY TIPO_VACUNA, NOM_VACUNA) INTO LISTA_VACUNAS
    FROM TAB_VACUNAS
    WHERE COALESCE(jSOLO_ACTIVAS, 'SI') = 'NO' OR ESTADO_VACUNA = 'ACTIVO';

    IF LISTA_VACUNAS IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'No hay vacunas registradas');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Vacunas y tratamientos', 'DATOS', LISTA_VACUNAS);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



--FUNCION PARA VALIDAR LOS DATOS DE UNA VACUNA (jID_VACUNA NULL AL CREAR)
CREATE OR REPLACE FUNCTION FUN_VALIDAR_VACUNAS(
    jID_VACUNA TAB_VACUNAS.ID_VACUNA%TYPE,
    jNOM_VACUNA TAB_VACUNAS.NOM_VACUNA%TYPE,
    jTIPO_VACUNA TAB_VACUNAS.TIPO_VACUNA%TYPE,
    jDIAS_REFUERZO TAB_VACUNAS.DIAS_REFUERZO%TYPE,
    jDIAS_RETIRO_LECHE TAB_VACUNAS.DIAS_RETIRO_LECHE%TYPE,
    jOBLIGATORIA_ICA TAB_VACUNAS.OBLIGATORIA_ICA%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    --VALIDACION VARIABLE ID_VACUNA (SOLO AL ACTUALIZAR)
    IF jID_VACUNA IS NOT NULL AND NOT EXISTS (SELECT 1 FROM TAB_VACUNAS WHERE ID_VACUNA = jID_VACUNA) THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'La vacuna no existe');
        RETURN RETORNO;

    --VALIDACION VARIABLE NOM_VACUNA (OBLIGATORIO, UNICO)
    ELSIF jNOM_VACUNA IS NULL OR TRIM(jNOM_VACUNA) = '' OR LENGTH(TRIM(jNOM_VACUNA)) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre del producto (máximo 80 caracteres)');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_VACUNAS WHERE LOWER(NOM_VACUNA) = LOWER(TRIM(jNOM_VACUNA)) AND ID_VACUNA IS DISTINCT FROM jID_VACUNA) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya hay un producto con ese nombre');
        RETURN RETORNO;

    --VALIDACION VARIABLE TIPO_VACUNA
    ELSIF jTIPO_VACUNA IS NULL OR jTIPO_VACUNA NOT IN ('VACUNA', 'TRATAMIENTO', 'DESPARASITANTE', 'VITAMINA') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige el tipo: vacuna, tratamiento, desparasitante o vitamina');
        RETURN RETORNO;

    --VALIDACION VARIABLES DE DIAS
    ELSIF jDIAS_REFUERZO IS NOT NULL AND (jDIAS_REFUERZO < 1 OR jDIAS_REFUERZO > 1095) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Los días del refuerzo van de 1 a 1095 (o vacío si es dosis única)');
        RETURN RETORNO;
    ELSIF jDIAS_RETIRO_LECHE IS NULL OR jDIAS_RETIRO_LECHE < 0 OR jDIAS_RETIRO_LECHE > 120 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Los días de retiro de leche van de 0 a 120 (mira la etiqueta del producto)');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBLIGATORIA_ICA
    ELSIF jOBLIGATORIA_ICA IS NULL OR jOBLIGATORIA_ICA NOT IN ('SI', 'NO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Indica si es obligatoria del ICA (SI o NO)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CREAR UNA VACUNA O TRATAMIENTO (ADMINISTRADOR)
CREATE OR REPLACE FUNCTION FUN_CREAR_VACUNA_JSON(
    jNOM_VACUNA TAB_VACUNAS.NOM_VACUNA%TYPE,
    jTIPO_VACUNA TAB_VACUNAS.TIPO_VACUNA%TYPE,
    jDIAS_REFUERZO TAB_VACUNAS.DIAS_REFUERZO%TYPE,
    jDIAS_RETIRO_LECHE TAB_VACUNAS.DIAS_RETIRO_LECHE%TYPE,
    jOBLIGATORIA_ICA TAB_VACUNAS.OBLIGATORIA_ICA%TYPE,
    jUSUARIO TAB_VACUNAS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_VACUNA INTEGER;
BEGIN
    jVALIDACION := FUN_VALIDAR_VACUNAS(NULL, jNOM_VACUNA, jTIPO_VACUNA, jDIAS_REFUERZO, jDIAS_RETIRO_LECHE, jOBLIGATORIA_ICA);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_VACUNA := funcion_Retorna_ultmoid('TAB_VACUNAS', 'ID_VACUNA');
    INSERT INTO TAB_VACUNAS (ID_VACUNA, NOM_VACUNA, TIPO_VACUNA, DIAS_REFUERZO, DIAS_RETIRO_LECHE, OBLIGATORIA_ICA, USUARIO_CREACION)
    VALUES (jID_VACUNA, regexp_replace(TRIM(jNOM_VACUNA), '\s+', ' ', 'g'), jTIPO_VACUNA, jDIAS_REFUERZO, jDIAS_RETIRO_LECHE, jOBLIGATORIA_ICA, jUSUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Producto creado', 'DATOS', json_build_object('ID_VACUNA', jID_VACUNA));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al crear el producto');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ACTUALIZAR UNA VACUNA O TRATAMIENTO (ADMINISTRADOR). INACTIVO = YA NO SALE EN LOS FORMULARIOS (LO REGISTRADO SE CONSERVA)
CREATE OR REPLACE FUNCTION FUN_ACTUALIZAR_VACUNA_JSON(
    jID_VACUNA TAB_VACUNAS.ID_VACUNA%TYPE,
    jNOM_VACUNA TAB_VACUNAS.NOM_VACUNA%TYPE,
    jTIPO_VACUNA TAB_VACUNAS.TIPO_VACUNA%TYPE,
    jDIAS_REFUERZO TAB_VACUNAS.DIAS_REFUERZO%TYPE,
    jDIAS_RETIRO_LECHE TAB_VACUNAS.DIAS_RETIRO_LECHE%TYPE,
    jOBLIGATORIA_ICA TAB_VACUNAS.OBLIGATORIA_ICA%TYPE,
    jESTADO_VACUNA TAB_VACUNAS.ESTADO_VACUNA%TYPE,
    jUSUARIO TAB_VACUNAS.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
BEGIN
    IF jID_VACUNA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'ID_VACUNA no puede ser nulo');
        RETURN RETORNO;
    ELSIF jESTADO_VACUNA IS NULL OR jESTADO_VACUNA NOT IN ('ACTIVO', 'INACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El estado debe ser ACTIVO o INACTIVO');
        RETURN RETORNO;
    END IF;
    jVALIDACION := FUN_VALIDAR_VACUNAS(jID_VACUNA, jNOM_VACUNA, jTIPO_VACUNA, jDIAS_REFUERZO, jDIAS_RETIRO_LECHE, jOBLIGATORIA_ICA);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    UPDATE TAB_VACUNAS
    SET NOM_VACUNA = regexp_replace(TRIM(jNOM_VACUNA), '\s+', ' ', 'g'),
        TIPO_VACUNA = jTIPO_VACUNA,
        DIAS_REFUERZO = jDIAS_REFUERZO,
        DIAS_RETIRO_LECHE = jDIAS_RETIRO_LECHE,
        OBLIGATORIA_ICA = jOBLIGATORIA_ICA,
        ESTADO_VACUNA = jESTADO_VACUNA,
        USUARIO_MODIFICACION = jUSUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_VACUNA = jID_VACUNA;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Producto actualizado. Lo ya registrado conserva sus fechas');
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al actualizar el producto');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LOS CICLOS DEL ICA ACTIVOS (LOS MAS RECIENTES PRIMERO)
CREATE OR REPLACE FUNCTION FUN_OBTENER_CICLOS_ICA_JSON(
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    LISTA_CICLOS JSON;
BEGIN
    SELECT json_agg(json_build_object(
        'ID_CICLO', C.ID_CICLO,
        'ID_VACUNA', C.ID_VACUNA,
        'NOM_VACUNA', V.NOM_VACUNA,
        'NOM_CICLO', C.NOM_CICLO,
        'FECHA_INICIO_CICLO', C.FECHA_INICIO_CICLO,
        'FECHA_FIN_CICLO', C.FECHA_FIN_CICLO,
        'VIGENTE', CURRENT_DATE BETWEEN C.FECHA_INICIO_CICLO AND C.FECHA_FIN_CICLO
    ) ORDER BY C.FECHA_INICIO_CICLO DESC) INTO LISTA_CICLOS
    FROM TAB_CICLOS_ICA C
    JOIN TAB_VACUNAS V ON V.ID_VACUNA = C.ID_VACUNA
    WHERE C.ESTADO_CICLO = 'ACTIVO';

    IF LISTA_CICLOS IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'No hay ciclos del ICA registrados');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ciclos del ICA', 'DATOS', LISTA_CICLOS);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CREAR UN CICLO DEL ICA (ADMINISTRADOR). SOLO PARA VACUNAS OBLIGATORIAS DEL ICA Y SIN CRUZARSE CON OTRO CICLO DE LA MISMA VACUNA
CREATE OR REPLACE FUNCTION FUN_CREAR_CICLO_ICA_JSON(
    jID_VACUNA TAB_CICLOS_ICA.ID_VACUNA%TYPE,
    jNOM_CICLO TAB_CICLOS_ICA.NOM_CICLO%TYPE,
    jFECHA_INICIO TAB_CICLOS_ICA.FECHA_INICIO_CICLO%TYPE,
    jFECHA_FIN TAB_CICLOS_ICA.FECHA_FIN_CICLO%TYPE,
    jUSUARIO TAB_CICLOS_ICA.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jID_CICLO INTEGER;
BEGIN
    --VALIDACIONES
    IF NOT EXISTS (SELECT 1 FROM TAB_VACUNAS WHERE ID_VACUNA = jID_VACUNA AND OBLIGATORIA_ICA = 'SI' AND ESTADO_VACUNA = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige una vacuna obligatoria del ICA');
        RETURN RETORNO;
    ELSIF jNOM_CICLO IS NULL OR TRIM(jNOM_CICLO) = '' OR LENGTH(TRIM(jNOM_CICLO)) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre del ciclo, por ejemplo "Primer ciclo 2027"');
        RETURN RETORNO;
    ELSIF jFECHA_INICIO IS NULL OR jFECHA_FIN IS NULL OR jFECHA_FIN < jFECHA_INICIO THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha final debe ser igual o posterior a la inicial');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_CICLOS_ICA WHERE ID_VACUNA = jID_VACUNA AND ESTADO_CICLO = 'ACTIVO'
                  AND FECHA_INICIO_CICLO <= jFECHA_FIN AND FECHA_FIN_CICLO >= jFECHA_INICIO) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ese ciclo se cruza con otro de la misma vacuna');
        RETURN RETORNO;
    END IF;

    jID_CICLO := funcion_Retorna_ultmoid('TAB_CICLOS_ICA', 'ID_CICLO');
    INSERT INTO TAB_CICLOS_ICA (ID_CICLO, ID_VACUNA, NOM_CICLO, FECHA_INICIO_CICLO, FECHA_FIN_CICLO, USUARIO_CREACION)
    VALUES (jID_CICLO, jID_VACUNA, regexp_replace(TRIM(jNOM_CICLO), '\s+', ' ', 'g'), jFECHA_INICIO, jFECHA_FIN, jUSUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ciclo creado', 'DATOS', json_build_object('ID_CICLO', jID_CICLO));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al crear el ciclo');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ANULAR UN CICLO DEL ICA (ADMINISTRADOR)
CREATE OR REPLACE FUNCTION FUN_ANULAR_CICLO_ICA_JSON(
    jID_CICLO TAB_CICLOS_ICA.ID_CICLO%TYPE,
    jUSUARIO TAB_CICLOS_ICA.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    UPDATE TAB_CICLOS_ICA
    SET ESTADO_CICLO = 'ANULADO',
        USUARIO_MODIFICACION = jUSUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_CICLO = jID_CICLO AND ESTADO_CICLO = 'ACTIVO';

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ciclo anulado');
    ELSE
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El ciclo no existe o ya estaba anulado');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
