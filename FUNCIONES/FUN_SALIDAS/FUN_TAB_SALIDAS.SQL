-- FUNCIONES DE LA TABLA TAB_SALIDAS -----------------------------------------------------------------------------------------------------------------
-- VENTA, MUERTE O TRASLADO. EL ESTADO DEL ANIMAL LO CAMBIA EL TRIGGER TRG_SALIDA_ANIMAL (Y LO DEVUELVE A ACTIVO SI SE ANULA LA SALIDA)
-- UNA SOLA SALIDA ACTIVA POR ANIMAL (INDICE UQ_SALIDAS_ANIMAL)



--FUNCION PARA VALIDAR LOS DATOS DE UNA SALIDA
CREATE OR REPLACE FUNCTION FUN_VALIDAR_SALIDAS(
    jID_ANIMAL TAB_SALIDAS.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_SALIDAS.FECHA_EVENTO%TYPE,
    jTIPO_SALIDA TAB_SALIDAS.TIPO_SALIDA%TYPE,
    jVALOR TAB_SALIDAS.VALOR_SALIDA%TYPE,
    jPESO_KG TAB_SALIDAS.PESO_SALIDA_KG%TYPE,
    jCAUSA TAB_SALIDAS.CAUSA_SALIDA%TYPE,
    jOBSERVACION TAB_SALIDAS.OBSERVACION_SALIDA%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jULTIMO_EVENTO TIMESTAMP;
BEGIN
    --EL EVENTO MAS RECIENTE DEL ANIMAL: LA SALIDA NO PUEDE QUEDAR ANTES DE ALGO YA REGISTRADO
    SELECT MAX(F) INTO jULTIMO_EVENTO FROM (
        SELECT MAX(FECHA_EVENTO) AS F FROM TAB_PESAJES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PESAJE = 'ACTIVO'
        UNION ALL SELECT MAX(FECHA_EVENTO) FROM TAB_VACUNACIONES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_VACUNACION = 'ACTIVO'
        UNION ALL SELECT MAX(FECHA_EVENTO) FROM TAB_SERVICIOS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_SERVICIO = 'ACTIVO'
        UNION ALL SELECT MAX(FECHA_EVENTO) FROM TAB_PALPACIONES WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PALPACION = 'ACTIVO'
        UNION ALL SELECT MAX(FECHA_EVENTO) FROM TAB_PARTOS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PARTO = 'ACTIVO'
        UNION ALL SELECT MAX(FECHA_EVENTO) FROM TAB_ORDENOS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_ORDENO = 'ACTIVO'
    ) T;

    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA). SI YA TIENE UNA SALIDA ACTIVA, AQUI SE VE CUANDO LA FECHA ES POSTERIOR
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_SALIDAS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_SALIDA = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', upper(left(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 1)) || substr(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 2)
            || ' ya tiene registrada su salida. Si está mal, anúlala primero');
        RETURN RETORNO;
    ELSIF jULTIMO_EVENTO IS NOT NULL AND jFECHA_EVENTO < jULTIMO_EVENTO THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Tiene registros hasta el ' || to_char(jULTIMO_EVENTO, 'DD/MM/YYYY') || ': la salida no puede ser antes');
        RETURN RETORNO;

    --VALIDACION VARIABLE TIPO_SALIDA Y LO QUE PIDE CADA UNA
    ELSIF jTIPO_SALIDA IS NULL OR jTIPO_SALIDA NOT IN ('VENTA', 'MUERTE', 'TRASLADO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige el tipo de salida: venta, muerte o traslado');
        RETURN RETORNO;
    ELSIF jTIPO_SALIDA = 'VENTA' AND (jVALOR IS NULL OR jVALOR <= 0) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe en cuánto se vendió');
        RETURN RETORNO;
    ELSIF jVALOR IS NOT NULL AND jVALOR > 99999999999 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Revisa el valor de la venta');
        RETURN RETORNO;
    ELSIF jTIPO_SALIDA = 'MUERTE' AND COALESCE(TRIM(jCAUSA), '') = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe la causa de la muerte (si no se sabe, "desconocida")');
        RETURN RETORNO;
    ELSIF LENGTH(TRIM(COALESCE(jCAUSA, ''))) > 200 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La causa es demasiado larga (máximo 200 caracteres)');
        RETURN RETORNO;
    ELSIF jPESO_KG IS NOT NULL AND (jPESO_KG <= 0 OR jPESO_KG > 1500) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El peso de salida debe estar entre 1 y 1500 kilos');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBSERVACION (OPCIONAL)
    ELSIF LENGTH(COALESCE(jOBSERVACION, '')) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La nota es demasiado larga (máximo 300 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA REGISTRAR LA SALIDA DE UN ANIMAL (VENTA, MUERTE O TRASLADO)
-- IDEMPOTENTE: SI EL UUID YA EXISTE RESPONDE 200 CON YA_EXISTIA Y NO DUPLICA
CREATE OR REPLACE FUNCTION FUN_CREAR_SALIDA_JSON(
    jUUID_SALIDA TAB_SALIDAS.UUID_SALIDA%TYPE,
    jID_FINCA TAB_SALIDAS.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jTIPO_SALIDA TAB_SALIDAS.TIPO_SALIDA%TYPE,
    jVALOR TAB_SALIDAS.VALOR_SALIDA%TYPE,
    jPESO_KG TAB_SALIDAS.PESO_SALIDA_KG%TYPE,
    jCAUSA TAB_SALIDAS.CAUSA_SALIDA%TYPE,
    jFECHA_EVENTO TAB_SALIDAS.FECHA_EVENTO%TYPE,
    jOBSERVACION TAB_SALIDAS.OBSERVACION_SALIDA%TYPE,
    jID_USUARIO TAB_SALIDAS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_SALIDA INTEGER;
    jID_ANIMAL INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_SALIDA INTO jID_SALIDA FROM TAB_SALIDAS WHERE UUID_SALIDA = jUUID_SALIDA;
    IF jID_SALIDA IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'La salida ya estaba guardada',
            'DATOS', json_build_object('ID_SALIDA', jID_SALIDA, 'UUID_SALIDA', jUUID_SALIDA, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_SALIDA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID de la salida');
        RETURN RETORNO;
    END IF;

    --LLAMAR A LA FUNCION DE VALIDACION
    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    jVALIDACION := FUN_VALIDAR_SALIDAS(jID_ANIMAL, jFECHA_EVENTO, jTIPO_SALIDA, jVALOR, jPESO_KG, jCAUSA, jOBSERVACION);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --INSERTAR LA SALIDA (EL TRIGGER TRG_SALIDA_ANIMAL CAMBIA EL ESTADO DEL ANIMAL)
    jID_SALIDA := funcion_Retorna_ultmoid('TAB_SALIDAS', 'ID_SALIDA');
    INSERT INTO TAB_SALIDAS (ID_SALIDA, UUID_SALIDA, ID_FINCA, ID_ANIMAL, FECHA_EVENTO, TIPO_SALIDA, VALOR_SALIDA, PESO_SALIDA_KG, CAUSA_SALIDA,
        OBSERVACION_SALIDA, USUARIO_CREACION)
    VALUES (jID_SALIDA, jUUID_SALIDA, jID_FINCA, jID_ANIMAL, jFECHA_EVENTO, jTIPO_SALIDA, jVALOR, jPESO_KG, NULLIF(TRIM(jCAUSA), ''),
        NULLIF(TRIM(jOBSERVACION), ''), jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE',
            CASE jTIPO_SALIDA WHEN 'VENTA' THEN 'Venta registrada' WHEN 'MUERTE' THEN 'Muerte registrada' ELSE 'Traslado registrado' END,
            'DATOS', json_build_object('ID_SALIDA', jID_SALIDA, 'UUID_SALIDA', jUUID_SALIDA, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al registrar la salida');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
