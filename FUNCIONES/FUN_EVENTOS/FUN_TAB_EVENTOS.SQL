-- FUNCIONES COMUNES A TODOS LOS EVENTOS -------------------------------------------------------------------------------------------------------------
-- ANULAR ES IGUAL PARA LOS SIETE EVENTOS: SE CAMBIA EL ESTADO A ANULADO, SALE DE LA LINEA DE TIEMPO Y DE LOS CALCULOS Y BAJA A TODOS LOS CELULARES
-- SOLO EL DUEÑO ANULA (EL VAQUERO Y EL VETERINARIO REGISTRAN PERO NO CORRIGEN NI ANULAN, COMO EN menurol)



-- FUNCION PARA ANULAR UN EVENTO. jTIPO: PESAJE, VACUNACION, SERVICIO, PALPACION, PARTO, ORDENO, SALIDA
-- PARTO CON CRIA: SE ANULAN TAMBIEN LA CRIA Y SUS PESAJES (BLOQUE BEGIN ... EXCEPTION), SI LA CRIA NO TIENE OTROS REGISTROS NI CRIAS
-- SALIDA: AL ANULARLA, EL TRIGGER TRG_SALIDA_ANIMAL DEVUELVE EL ANIMAL A ACTIVO
-- SI YA ESTABA ANULADO RESPONDE 200 CON YA_EXISTIA (REINTENTO SEGURO DESDE LA SINCRONIZACION)
CREATE OR REPLACE FUNCTION FUN_ANULAR_EVENTO_JSON(
    jTIPO VARCHAR,
    jUUID UUID,
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jTABLA JSON;
    jID_EVENTO INTEGER;
    jESTADO VARCHAR;
    jID_CRIA INTEGER;
    jFILAS INTEGER;
BEGIN
    --EL TIPO SALE DE LA LISTA BLANCA (LOTES Y ANIMALES TIENEN SU PROPIA FUNCION DE ANULAR)
    jTABLA := FUN_TABLA_POR_TIPO(jTIPO);
    IF jTABLA IS NULL OR UPPER(TRIM(jTIPO)) IN ('LOTE', 'ANIMAL') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Tipo de evento no válido');
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (SOLO EL DUEÑO)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --BUSCAR EL EVENTO EN SU TABLA (LOS NOMBRES VIENEN DE FUN_TABLA_POR_TIPO, NUNCA DE AFUERA)
    EXECUTE format('SELECT %s, %s FROM %s WHERE %s = $1 AND ID_FINCA = $2',
            jTABLA ->> 'ID', jTABLA ->> 'ESTADO', jTABLA ->> 'TABLA', jTABLA ->> 'UUID')
        INTO jID_EVENTO, jESTADO USING jUUID, jID_FINCA;

    IF jID_EVENTO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Ese registro no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ya estaba anulado', 'DATOS', json_build_object('YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --PARTO CON CRIA: LA CRIA NO PUEDE TENER OTROS REGISTROS (FUERA DE SUS PESAJES) NI CRIAS
    IF UPPER(TRIM(jTIPO)) = 'PARTO' THEN
        SELECT ID_CRIA INTO jID_CRIA FROM TAB_PARTOS WHERE ID_PARTO = jID_EVENTO;
        IF jID_CRIA IS NOT NULL AND (
               EXISTS (SELECT 1 FROM TAB_VACUNACIONES WHERE ID_ANIMAL = jID_CRIA AND ESTADO_VACUNACION = 'ACTIVO')
            OR EXISTS (SELECT 1 FROM TAB_SERVICIOS WHERE (ID_ANIMAL = jID_CRIA OR ID_TORO = jID_CRIA) AND ESTADO_SERVICIO = 'ACTIVO')
            OR EXISTS (SELECT 1 FROM TAB_PALPACIONES WHERE ID_ANIMAL = jID_CRIA AND ESTADO_PALPACION = 'ACTIVO')
            OR EXISTS (SELECT 1 FROM TAB_PARTOS WHERE ID_ANIMAL = jID_CRIA AND ESTADO_PARTO = 'ACTIVO')
            OR EXISTS (SELECT 1 FROM TAB_ORDENOS WHERE ID_ANIMAL = jID_CRIA AND ESTADO_ORDENO = 'ACTIVO')
            OR EXISTS (SELECT 1 FROM TAB_SALIDAS WHERE ID_ANIMAL = jID_CRIA AND ESTADO_SALIDA = 'ACTIVO')
            OR EXISTS (SELECT 1 FROM TAB_ANIMALES WHERE (ID_MADRE = jID_CRIA OR ID_PADRE = jID_CRIA) AND ESTADO_ANIMAL <> 'ANULADO')) THEN
            RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La cría de este parto ya tiene registros propios: anúlalos primero');
            RETURN RETORNO;
        END IF;
    END IF;

    BEGIN
        --ANULAR EL EVENTO (EXECUTE NO CAMBIA FOUND: SE REVISA CON ROW_COUNT)
        EXECUTE format('UPDATE %s SET %s = ''ANULADO'', USUARIO_MODIFICACION = $1, FECHA_MODIFICACION = NOW() WHERE %s = $2',
                jTABLA ->> 'TABLA', jTABLA ->> 'ESTADO', jTABLA ->> 'ID')
            USING jID_USUARIO, jID_EVENTO;
        GET DIAGNOSTICS jFILAS = ROW_COUNT;
        IF jFILAS = 0 THEN
            RAISE EXCEPTION 'No se pudo anular el registro';
        END IF;

        --PARTO CON CRIA: SUS PESAJES Y LA CRIA (PUEDE QUE NO TENGA PESAJES: ESE UPDATE NO SE REVISA)
        IF jID_CRIA IS NOT NULL THEN
            UPDATE TAB_PESAJES
            SET ESTADO_PESAJE = 'ANULADO',
                USUARIO_MODIFICACION = jID_USUARIO,
                FECHA_MODIFICACION = NOW()
            WHERE ID_ANIMAL = jID_CRIA AND ESTADO_PESAJE = 'ACTIVO';

            UPDATE TAB_ANIMALES
            SET ESTADO_ANIMAL = 'ANULADO',
                USUARIO_MODIFICACION = jID_USUARIO,
                FECHA_MODIFICACION = NOW()
            WHERE ID_ANIMAL = jID_CRIA;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No se pudo anular la cría del parto';
            END IF;
        END IF;

        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE',
            CASE WHEN jID_CRIA IS NOT NULL THEN 'Parto anulado junto con su cría' ELSE 'Registro anulado' END,
            'DATOS', json_build_object('YA_EXISTIA', false));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
