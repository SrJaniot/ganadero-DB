-- FUNCIONES DE LA TABLA TAB_PALPACIONES -------------------------------------------------------------------------------------------------------------
-- PRENIADA (CON LOS MESES ESTIMADOS) O VACIA. LA PALPACION SE ENLAZA SOLA CON EL ULTIMO SERVICIO ACTIVO ANTERIOR (SI HAY)



--FUNCION PARA VALIDAR LOS DATOS DE UNA PALPACION
CREATE OR REPLACE FUNCTION FUN_VALIDAR_PALPACIONES(
    jID_ANIMAL TAB_PALPACIONES.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_PALPACIONES.FECHA_EVENTO%TYPE,
    jRESULTADO TAB_PALPACIONES.RESULTADO_PALPACION%TYPE,
    jMESES TAB_PALPACIONES.MESES_GESTACION%TYPE,
    jOBSERVACION TAB_PALPACIONES.OBSERVACION_PALPACION%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jSEXO VARCHAR;
BEGIN
    SELECT SEXO_ANIMAL INTO jSEXO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;

    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA)
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;
    ELSIF jSEXO <> 'H' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La palpación se registra a una hembra');
        RETURN RETORNO;
    ELSIF FUN_CATEGORIA_ANIMAL(jID_ANIMAL, jFECHA_EVENTO::DATE) = 'TERNERA' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'En esa fecha era una ternera: no se puede palpar');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_PALPACIONES WHERE ID_ANIMAL = jID_ANIMAL AND FECHA_EVENTO::DATE = jFECHA_EVENTO::DATE AND ESTADO_PALPACION = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya hay una palpación de ' || FUN_ETIQUETA_ANIMAL(jID_ANIMAL) || ' ese mismo día');
        RETURN RETORNO;

    --VALIDACION VARIABLE RESULTADO Y MESES
    ELSIF jRESULTADO IS NULL OR jRESULTADO NOT IN ('PRENIADA', 'VACIA') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige el resultado: preñada o vacía');
        RETURN RETORNO;
    ELSIF jRESULTADO = 'PRENIADA' AND (jMESES IS NULL OR jMESES < 1 OR jMESES > 9) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe de cuántos meses está preñada (de 1 a 9)');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBSERVACION (OPCIONAL)
    ELSIF LENGTH(COALESCE(jOBSERVACION, '')) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La nota es demasiado larga (máximo 300 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA REGISTRAR UNA PALPACION
-- IDEMPOTENTE: SI EL UUID YA EXISTE RESPONDE 200 CON YA_EXISTIA Y NO DUPLICA
CREATE OR REPLACE FUNCTION FUN_CREAR_PALPACION_JSON(
    jUUID_PALPACION TAB_PALPACIONES.UUID_PALPACION%TYPE,
    jID_FINCA TAB_PALPACIONES.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jRESULTADO TAB_PALPACIONES.RESULTADO_PALPACION%TYPE,
    jMESES TAB_PALPACIONES.MESES_GESTACION%TYPE,
    jFECHA_EVENTO TAB_PALPACIONES.FECHA_EVENTO%TYPE,
    jOBSERVACION TAB_PALPACIONES.OBSERVACION_PALPACION%TYPE,
    jID_USUARIO TAB_PALPACIONES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_PALPACION INTEGER;
    jID_ANIMAL INTEGER;
    jID_SERVICIO INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_PALPACION INTO jID_PALPACION FROM TAB_PALPACIONES WHERE UUID_PALPACION = jUUID_PALPACION;
    IF jID_PALPACION IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'La palpación ya estaba guardada',
            'DATOS', json_build_object('ID_PALPACION', jID_PALPACION, 'UUID_PALPACION', jUUID_PALPACION, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_PALPACION IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID de la palpación');
        RETURN RETORNO;
    END IF;

    --LLAMAR A LA FUNCION DE VALIDACION
    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    jVALIDACION := FUN_VALIDAR_PALPACIONES(jID_ANIMAL, jFECHA_EVENTO, jRESULTADO, jMESES, jOBSERVACION);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --ULTIMO SERVICIO ACTIVO ANTES DE LA PALPACION
    SELECT ID_SERVICIO INTO jID_SERVICIO FROM TAB_SERVICIOS
    WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_SERVICIO = 'ACTIVO' AND FECHA_EVENTO <= jFECHA_EVENTO
    ORDER BY FECHA_EVENTO DESC LIMIT 1;

    --INSERTAR LA PALPACION
    jID_PALPACION := funcion_Retorna_ultmoid('TAB_PALPACIONES', 'ID_PALPACION');
    INSERT INTO TAB_PALPACIONES (ID_PALPACION, UUID_PALPACION, ID_FINCA, ID_ANIMAL, FECHA_EVENTO, ID_SERVICIO, RESULTADO_PALPACION, MESES_GESTACION,
        OBSERVACION_PALPACION, USUARIO_CREACION)
    VALUES (jID_PALPACION, jUUID_PALPACION, jID_FINCA, jID_ANIMAL, jFECHA_EVENTO, jID_SERVICIO, jRESULTADO,
        CASE WHEN jRESULTADO = 'PRENIADA' THEN jMESES END, NULLIF(TRIM(jOBSERVACION), ''), jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', CASE WHEN jRESULTADO = 'PRENIADA' THEN 'Palpación guardada: preñada' ELSE 'Palpación guardada: vacía' END,
            'DATOS', json_build_object('ID_PALPACION', jID_PALPACION, 'UUID_PALPACION', jUUID_PALPACION, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al guardar la palpación');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
