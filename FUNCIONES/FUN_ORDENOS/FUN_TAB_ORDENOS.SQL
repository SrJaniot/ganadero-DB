-- ORDEÑO POR JORNADA (MAÑANA Y TARDE). EN LA PANTALLA SE PASAN LAS VACAS UNA POR UNA Y SOLO SE ESCRIBEN LOS LITROS (CADA VACA ES UN REGISTRO)
-- UNA JORNADA ACTIVA POR VACA Y DIA (INDICE UQ_ORDENOS_JORNADA): SI DOS CELULARES ORDEÑAN LA MISMA VACA, EL SEGUNDO SE RECHAZA CON MENSAJE



--FUNCION PARA VALIDAR LOS DATOS DE UN ORDEÑO
CREATE OR REPLACE FUNCTION FUN_VALIDAR_ORDENOS(
    jID_ANIMAL TAB_ORDENOS.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_ORDENOS.FECHA_EVENTO%TYPE,
    jJORNADA TAB_ORDENOS.JORNADA_ORDENO%TYPE,
    jLITROS TAB_ORDENOS.LITROS_ORDENO%TYPE,
    jOBSERVACION TAB_ORDENOS.OBSERVACION_ORDENO%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jSEXO VARCHAR;
BEGIN
    SELECT SEXO_ANIMAL INTO jSEXO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;

    --LO COMUN A TODOS LOS EVENTOS (ANIMAL Y FECHA)
    RETORNO := FUN_VALIDAR_EVENTO_ANIMAL(jID_ANIMAL, jFECHA_EVENTO);
    IF (RETORNO ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN RETORNO;
    ELSIF jSEXO <> 'H' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El ordeño se registra a una vaca');
        RETURN RETORNO;
    ELSIF FUN_CATEGORIA_ANIMAL(jID_ANIMAL, jFECHA_EVENTO::DATE) = 'TERNERA' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'En esa fecha era una ternera: no se ordeña');
        RETURN RETORNO;

    --VALIDACION VARIABLE JORNADA (UNA POR VACA Y DIA)
    ELSIF jJORNADA IS NULL OR jJORNADA NOT IN ('MANANA', 'TARDE') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige la jornada: mañana o tarde');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_ORDENOS WHERE ID_ANIMAL = jID_ANIMAL AND FECHA_EVENTO::DATE = jFECHA_EVENTO::DATE
                  AND JORNADA_ORDENO = jJORNADA AND ESTADO_ORDENO = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya se registró el ordeño de la ' || CASE WHEN jJORNADA = 'MANANA' THEN 'mañana' ELSE 'tarde' END
            || ' del ' || to_char(jFECHA_EVENTO, 'DD/MM/YYYY') || ' de ' || FUN_ETIQUETA_ANIMAL(jID_ANIMAL));
        RETURN RETORNO;

    --VALIDACION VARIABLE LITROS
    ELSIF jLITROS IS NULL OR jLITROS < 0 OR jLITROS > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe los litros (de 0 a 60)');
        RETURN RETORNO;

    --VALIDACION VARIABLE OBSERVACION (OPCIONAL)
    ELSIF LENGTH(COALESCE(jOBSERVACION, '')) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La nota es demasiado larga (máximo 300 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA REGISTRAR EL ORDEÑO DE UNA VACA EN UNA JORNADA
-- IDEMPOTENTE: SI EL UUID YA EXISTE RESPONDE 200 CON YA_EXISTIA Y NO DUPLICA
CREATE OR REPLACE FUNCTION FUN_CREAR_ORDENO_JSON(
    jUUID_ORDENO TAB_ORDENOS.UUID_ORDENO%TYPE,
    jID_FINCA TAB_ORDENOS.ID_FINCA%TYPE,
    jUUID_ANIMAL TAB_ANIMALES.UUID_ANIMAL%TYPE,
    jJORNADA TAB_ORDENOS.JORNADA_ORDENO%TYPE,
    jLITROS TAB_ORDENOS.LITROS_ORDENO%TYPE,
    jFECHA_EVENTO TAB_ORDENOS.FECHA_EVENTO%TYPE,
    jOBSERVACION TAB_ORDENOS.OBSERVACION_ORDENO%TYPE,
    jID_USUARIO TAB_ORDENOS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_ORDENO INTEGER;
    jID_ANIMAL INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_ORDENO INTO jID_ORDENO FROM TAB_ORDENOS WHERE UUID_ORDENO = jUUID_ORDENO;
    IF jID_ORDENO IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El ordeño ya estaba guardado',
            'DATOS', json_build_object('ID_ORDENO', jID_ORDENO, 'UUID_ORDENO', jUUID_ORDENO, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_ORDENO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del ordeño');
        RETURN RETORNO;
    END IF;

    --LLAMAR A LA FUNCION DE VALIDACION
    jID_ANIMAL := FUN_ID_ANIMAL_POR_UUID(jID_FINCA, jUUID_ANIMAL);
    jVALIDACION := FUN_VALIDAR_ORDENOS(jID_ANIMAL, jFECHA_EVENTO, jJORNADA, jLITROS, jOBSERVACION);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --INSERTAR EL ORDEÑO
    jID_ORDENO := funcion_Retorna_ultmoid('TAB_ORDENOS', 'ID_ORDENO');
    INSERT INTO TAB_ORDENOS (ID_ORDENO, UUID_ORDENO, ID_FINCA, ID_ANIMAL, FECHA_EVENTO, JORNADA_ORDENO, LITROS_ORDENO, OBSERVACION_ORDENO, USUARIO_CREACION)
    VALUES (jID_ORDENO, jUUID_ORDENO, jID_FINCA, jID_ANIMAL, jFECHA_EVENTO, jJORNADA, jLITROS, NULLIF(TRIM(jOBSERVACION), ''), jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ordeño guardado: ' || trim(to_char(jLITROS, 'FM990.0')) || ' litros',
            'DATOS', json_build_object('ID_ORDENO', jID_ORDENO, 'UUID_ORDENO', jUUID_ORDENO, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al guardar el ordeño');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
