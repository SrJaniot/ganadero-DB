-- FUNCION QUE DEVUELVE EL HISTORIAL DE CAMBIOS DE UN REGISTRO DE LA FINCA ("¿QUIEN CAMBIO ESTA VACA?"). SOLO EL DUEÑO
-- jTIPO: LOTE, ANIMAL, PESAJE, VACUNACION, SERVICIO, PALPACION, PARTO, ORDENO, SALIDA
CREATE OR REPLACE FUNCTION FUN_OBTENER_HISTORIAL_REGISTRO_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jTIPO VARCHAR,
    jUUID TAB_AUDITORIAS.UUID_REGISTRO_AUDITORIA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jTABLA JSON;
    LISTA_CAMBIOS JSON;
BEGIN
    --VALIDAR EL ACCESO (SOLO EL DUEÑO VE LA AUDITORIA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jTABLA := FUN_TABLA_POR_TIPO(jTIPO);
    IF jTABLA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Tipo de registro no válido');
        RETURN RETORNO;
    END IF;

    --CAMBIOS DEL REGISTRO, DEL MAS NUEVO AL MAS VIEJO
    SELECT json_agg(json_build_object(
        'OPERACION_AUDITORIA', A.OPERACION_AUDITORIA,
        'CAMBIOS_AUDITORIA', A.CAMBIOS_AUDITORIA,
        'USUARIO_AUDITORIA', A.USUARIO_AUDITORIA,
        'NOM_PERSONA', P.NOM_PERSONA,
        'FECHA_AUDITORIA', A.FECHA_AUDITORIA
    ) ORDER BY A.ID_AUDITORIA DESC) INTO LISTA_CAMBIOS
    FROM TAB_AUDITORIAS A
    LEFT JOIN TAB_FINCAS_PERSONAS P ON P.ID_FINCA = A.ID_FINCA AND P.ID_USUARIO = A.USUARIO_AUDITORIA
    WHERE A.NOM_TABLA_AUDITORIA = jTABLA ->> 'TABLA'
      AND A.UUID_REGISTRO_AUDITORIA = jUUID
      AND A.ID_FINCA = jID_FINCA;

    IF LISTA_CAMBIOS IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Ese registro no tiene historial en esta finca');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Historial del registro', 'DATOS', LISTA_CAMBIOS);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LA ACTIVIDAD DE LA FINCA ENTRE DOS FECHAS (QUIEN HIZO QUE). SOLO EL DUEÑO. MAXIMO 500 FILAS, LO MAS NUEVO PRIMERO
CREATE OR REPLACE FUNCTION FUN_OBTENER_AUDITORIA_FINCA_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jDESDE DATE,
    jHASTA DATE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    LISTA_AUDITORIA JSON;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jDESDE IS NULL OR jHASTA IS NULL OR jHASTA < jDESDE THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige un rango de fechas válido');
        RETURN RETORNO;
    END IF;

    SELECT json_agg(json_build_object(
        'NOM_TABLA_AUDITORIA', T.NOM_TABLA_AUDITORIA,
        'OPERACION_AUDITORIA', T.OPERACION_AUDITORIA,
        'UUID_REGISTRO_AUDITORIA', T.UUID_REGISTRO_AUDITORIA,
        'CAMBIOS_AUDITORIA', T.CAMBIOS_AUDITORIA,
        'USUARIO_AUDITORIA', T.USUARIO_AUDITORIA,
        'NOM_PERSONA', T.NOM_PERSONA,
        'FECHA_AUDITORIA', T.FECHA_AUDITORIA
    ) ORDER BY T.ID_AUDITORIA DESC) INTO LISTA_AUDITORIA
    FROM (
        SELECT A.*, P.NOM_PERSONA
        FROM TAB_AUDITORIAS A
        LEFT JOIN TAB_FINCAS_PERSONAS P ON P.ID_FINCA = A.ID_FINCA AND P.ID_USUARIO = A.USUARIO_AUDITORIA
        WHERE A.ID_FINCA = jID_FINCA
          AND A.FECHA_AUDITORIA >= jDESDE
          AND A.FECHA_AUDITORIA < jHASTA + 1
        ORDER BY A.ID_AUDITORIA DESC
        LIMIT 500
    ) T;

    IF LISTA_AUDITORIA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'No hubo cambios en esas fechas');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Actividad de la finca', 'DATOS', LISTA_AUDITORIA);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
