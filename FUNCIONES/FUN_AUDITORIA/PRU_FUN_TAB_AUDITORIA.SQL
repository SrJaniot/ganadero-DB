-- PRUEBAS de los triggers de protección y auditoría (TRG_PROTEGER_*, TRG_NO_BORRAR_*, TRG_AUDITORIA_*) y de sus consultas
-- SE EJECUTAN DENTRO DE UNA TRANSACCION Y AL FINAL SE HACE ROLLBACK PARA NO DEJAR DATOS DE PRUEBA
-- LOS ERRORES ESPERADOS SE ATRAPAN CON UN AYUDANTE QUE DEVUELVE EL MENSAJE (ASI LA TRANSACCION SIGUE)
BEGIN;

SELECT FUN_CREAR_FINCA_JSON('Finca Prueba', 'San Gil', NULL, NULL, NULL, 'PRU-DUENO', 'Dueño Prueba') ->> 'CODIGO' AS FINCA_200;
CREATE FUNCTION pg_temp.FINCA() RETURNS INTEGER AS $$ SELECT ID_FINCA FROM TAB_FINCAS WHERE NOM_FINCA = 'Finca Prueba' $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.ID_VACA() RETURNS INTEGER AS $$ SELECT ID_ANIMAL FROM TAB_ANIMALES WHERE UUID_ANIMAL = '00000000-0000-0000-0000-00000000000a' $$ LANGUAGE sql;
--EJECUTA UNA SENTENCIA Y DEVUELVE 'OK' O EL MENSAJE DEL ERROR
CREATE FUNCTION pg_temp.INTENTAR(jSQL VARCHAR) RETURNS VARCHAR AS $$
BEGIN
    EXECUTE jSQL;
    RETURN 'OK';
EXCEPTION WHEN OTHERS THEN
    RETURN SQLERRM;
END;
$$ LANGUAGE plpgsql;
SELECT FUN_CREAR_ANIMAL_JSON('00000000-0000-0000-0000-00000000000a', pg_temp.FINCA(), NULL, 2, '23', 'Lucero', 'H', '2021-03-10', 'SI', NULL, NULL, NULL, 'COMPRADO', '2024-05-01', 'PRU-DUENO') ->> 'CODIGO' AS VACA_200;


SELECT 'PRUEBA 1.1: TRG_PROTEGER. Al crear, FECHA_MODIFICACION ya viene puesta (para que la vaca baje a los celulares) = TRUE' as PRUEBA;
SELECT FECHA_MODIFICACION IS NOT NULL AS FECHA_MODIFICACION_TRUE FROM TAB_ANIMALES WHERE ID_ANIMAL = pg_temp.ID_VACA();

SELECT 'PRUEBA 1.2: TRG_PROTEGER. No se puede cambiar UUID, finca ni usuario de creación (3 errores); un UPDATE a mano sin poner FECHA_MODIFICACION igual la actualiza (TRUE)' as PRUEBA;
SELECT pg_temp.INTENTAR('UPDATE TAB_ANIMALES SET UUID_ANIMAL = gen_random_uuid() WHERE ID_ANIMAL = ' || pg_temp.ID_VACA()) AS UUID_INMUTABLE,
       pg_temp.INTENTAR('UPDATE TAB_ANIMALES SET ID_FINCA = ID_FINCA + 1000 WHERE ID_ANIMAL = ' || pg_temp.ID_VACA()) AS FINCA_INMUTABLE,
       pg_temp.INTENTAR('UPDATE TAB_ANIMALES SET USUARIO_CREACION = ''OTRO'' WHERE ID_ANIMAL = ' || pg_temp.ID_VACA()) AS CREADOR_INMUTABLE;
CREATE TEMP TABLE PRU_ANTES AS SELECT FECHA_MODIFICACION FROM TAB_ANIMALES WHERE ID_ANIMAL = pg_temp.ID_VACA();
ALTER TABLE TAB_ANIMALES DISABLE TRIGGER TRG_PROTEGER_ANIMALES;
UPDATE TAB_ANIMALES SET FECHA_MODIFICACION = '2020-01-01' WHERE ID_ANIMAL = pg_temp.ID_VACA();
ALTER TABLE TAB_ANIMALES ENABLE TRIGGER TRG_PROTEGER_ANIMALES;
UPDATE TAB_ANIMALES SET NOM_ANIMAL = 'Lucerito', USUARIO_MODIFICACION = 'PRU-DUENO' WHERE ID_ANIMAL = pg_temp.ID_VACA();
SELECT FECHA_MODIFICACION > '2020-01-01' AS SE_ACTUALIZO_SOLA_TRUE FROM TAB_ANIMALES WHERE ID_ANIMAL = pg_temp.ID_VACA();

SELECT 'PRUEBA 2.1: TRG_NO_BORRAR. DELETE de la vaca: error "se anula"; con ganadero.permitir_borrar = SI (limpiezas) sí deja: OK y queda BORRAR en la auditoría' as PRUEBA;
SELECT pg_temp.INTENTAR('DELETE FROM TAB_ANIMALES WHERE ID_ANIMAL = ' || pg_temp.ID_VACA()) AS NO_SE_BORRA;
SAVEPOINT ANTES_DE_BORRAR;
SET LOCAL ganadero.permitir_borrar = 'SI';
SELECT pg_temp.INTENTAR('DELETE FROM TAB_ANIMALES WHERE ID_ANIMAL = ' || pg_temp.ID_VACA()) AS LIMPIEZA_OK;
SELECT OPERACION_AUDITORIA AS BORRAR FROM TAB_AUDITORIAS WHERE NOM_TABLA_AUDITORIA = 'TAB_ANIMALES' ORDER BY ID_AUDITORIA DESC LIMIT 1;
ROLLBACK TO SAVEPOINT ANTES_DE_BORRAR;
RESET ganadero.permitir_borrar;

SELECT 'PRUEBA 3.1: TRG_AUDITORIA. La vaca tiene CREAR (con la fila completa) y EDITAR (solo NOM_ANIMAL: Lucero -> Lucerito), con el usuario' as PRUEBA;
SELECT OPERACION_AUDITORIA AS OPERACION, USUARIO_AUDITORIA AS USUARIO, CAMBIOS_AUDITORIA AS CAMBIOS, DATOS_AUDITORIA ->> 'chapeta_animal' AS CHAPETA_EN_CREAR
FROM TAB_AUDITORIAS WHERE NOM_TABLA_AUDITORIA = 'TAB_ANIMALES' AND ID_REGISTRO_AUDITORIA = pg_temp.ID_VACA() ORDER BY ID_AUDITORIA;

SELECT 'PRUEBA 3.2: Un UPDATE que no cambia nada (mismo nombre) no deja auditoría: siguen 2 filas' as PRUEBA;
UPDATE TAB_ANIMALES SET NOM_ANIMAL = 'Lucerito', USUARIO_MODIFICACION = 'PRU-DUENO' WHERE ID_ANIMAL = pg_temp.ID_VACA();
SELECT COUNT(*) AS DOS FROM TAB_AUDITORIAS WHERE NOM_TABLA_AUDITORIA = 'TAB_ANIMALES' AND ID_REGISTRO_AUDITORIA = pg_temp.ID_VACA();

SELECT 'PRUEBA 3.3: Pesar deja CREAR en el pesaje y EDITAR en la vaca (peso actual, por el trigger); anular el pesaje queda como ANULAR' as PRUEBA;
SELECT FUN_CREAR_PESAJE_JSON('00000000-0000-0000-0000-000000000e01', pg_temp.FINCA(), '00000000-0000-0000-0000-00000000000a', 410, 'NO', NULL, LOCALTIMESTAMP, NULL, 'PRU-DUENO') ->> 'CODIGO' AS PESAJE_200;
SELECT FUN_ANULAR_EVENTO_JSON('PESAJE', '00000000-0000-0000-0000-000000000e01', pg_temp.FINCA(), 'PRU-DUENO') ->> 'CODIGO' AS ANULAR_200;
SELECT NOM_TABLA_AUDITORIA AS TABLA, OPERACION_AUDITORIA AS OPERACION, CAMBIOS_AUDITORIA AS CAMBIOS
FROM TAB_AUDITORIAS WHERE ID_FINCA = pg_temp.FINCA() AND NOM_TABLA_AUDITORIA IN ('TAB_PESAJES', 'TAB_ANIMALES') AND OPERACION_AUDITORIA <> 'CREAR' OR UUID_REGISTRO_AUDITORIA = '00000000-0000-0000-0000-000000000e01'
ORDER BY ID_AUDITORIA;

SELECT 'PRUEBA 4.1: Consultas. Historial de la vaca (dueño) 200 con el nombre de quien la cambió; el vaquero no ve la auditoría 400; actividad de hoy 200; tipo malo 400' as PRUEBA;
SELECT FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VAQUERO', 'Vaquero Prueba', 'VAQUERO', 'PRU-DUENO') ->> 'CODIGO' AS VAQUERO_200;
SELECT FUN_OBTENER_HISTORIAL_REGISTRO_JSON(pg_temp.FINCA(), 'ANIMAL', '00000000-0000-0000-0000-00000000000a', 'PRU-DUENO') -> 'DATOS' -> 0 ->> 'NOM_PERSONA' AS DUENIO_PRUEBA,
       FUN_OBTENER_HISTORIAL_REGISTRO_JSON(pg_temp.FINCA(), 'ANIMAL', '00000000-0000-0000-0000-00000000000a', 'PRU-VAQUERO') ->> 'CODIGO' AS VAQUERO_400,
       FUN_OBTENER_AUDITORIA_FINCA_JSON(pg_temp.FINCA(), CURRENT_DATE, CURRENT_DATE, 'PRU-DUENO') ->> 'CODIGO' AS ACTIVIDAD_200,
       FUN_OBTENER_HISTORIAL_REGISTRO_JSON(pg_temp.FINCA(), 'GALLINA', '00000000-0000-0000-0000-00000000000a', 'PRU-DUENO') ->> 'CODIGO' AS TIPO_MALO_400;

ROLLBACK;
