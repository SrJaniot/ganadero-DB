SELECT FUN_CREAR_FINCA_JSON('Finca Prueba', 'San Gil', NULL, NULL, NULL, 'PRU-DUENO', 'Dueño Prueba') ->> 'CODIGO' AS FINCA_200;
CREATE FUNCTION pg_temp.FINCA() RETURNS INTEGER AS $$ SELECT ID_FINCA FROM TAB_FINCAS WHERE NOM_FINCA = 'Finca Prueba' $$ LANGUAGE sql;
--EL UUID SALE DE LA CHAPETA (T -> F Y C -> C: UN UUID SOLO ACEPTA HEXADECIMAL)
CREATE FUNCTION pg_temp.U(jSUFIJO VARCHAR) RETURNS UUID AS $$ SELECT ('00000000-0000-0000-0000-' || lpad(replace(jSUFIJO, 'T', 'F'), 12, '0'))::UUID $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.HACE(jDIAS INTEGER, jHORA TIME DEFAULT '08:00') RETURNS TIMESTAMP AS $$ SELECT (CURRENT_DATE - jDIAS) + jHORA $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.IND() RETURNS JSON AS $$ SELECT FUN_OBTENER_INDICADORES_JSON(pg_temp.FINCA(), 'PRU-DUENO', CURRENT_DATE - 364, CURRENT_DATE) -> 'DATOS' $$ LANGUAGE sql;
SELECT FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VAQUERO', 'Vaquero Prueba', 'VAQUERO', 'PRU-DUENO') ->> 'CODIGO' AS VAQUERO_200,
       FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VET', 'Veterinaria Prueba', 'VETERINARIO', 'PRU-DUENO') ->> 'CODIGO' AS VET_200,
       FUN_CREAR_LOTE_JSON('00000000-0000-0000-0000-0000000000ce', pg_temp.FINCA(), 'Ceba', 'PRU-DUENO') ->> 'CODIGO' AS LOTE_200;

--LOS ANIMALES (COMPRADOS HACE 600 DIAS)
SELECT FUN_CREAR_ANIMAL_JSON(pg_temp.U(c), pg_temp.FINCA(), CASE WHEN c = 'T1' THEN '00000000-0000-0000-0000-0000000000ce'::UUID END, NULL, c, NULL,
       CASE WHEN c = 'T1' THEN 'M' ELSE 'H' END, CASE WHEN c = '25' THEN (CURRENT_DATE - 500) ELSE '2019-01-01'::DATE END, 'SI', NULL, NULL, NULL,
       'COMPRADO', CASE WHEN c = '25' THEN CURRENT_DATE - 450 ELSE CURRENT_DATE - 600 END, 'PRU-DUENO') ->> 'CODIGO' AS ANIMAL_200
FROM unnest(ARRAY['23', '24', '25', '26', 'T1']) AS c;

