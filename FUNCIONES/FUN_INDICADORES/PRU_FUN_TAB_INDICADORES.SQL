--   26 VACA DE 2019, MURIO HACE 30                          -> UNA MUERTE
--   T1 TORO EN EL LOTE CEBA: 400 KG HACE 60 Y 430 HACE 30   -> 1000 GRAMOS AL DIA
--   ORDEÑO: HACE 10 DIAS 23 (8 + 6) Y 24 (4) = 18 L / 2 VACAS = 9; HACE 9 DIAS 23 (10) = 10  -> 9,5 L POR VACA AL DIA, 28 L EN TOTAL
-- RESULTADO: 6 ANIMALES EN EL PERIODO (23, 24, 25, 26, T1, C1); 3 HEMBRAS REPRODUCTORAS (23, 24, 26) -> NATALIDAD 33,3 %; MORTALIDAD 1/6 = 16,7 %
