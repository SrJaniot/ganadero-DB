-- FUNCIONES DE LOS INDICADORES DE LA FINCA (FASE 4, MENU 6 INDICADORES Y EXCEL) ---------------------------------------------------------------------
-- LOS CALCULA LA BASE CON LOS EVENTOS ACTIVOS DE UN PERIODO (DESDE / HASTA). NADA SE GUARDA. EL CELULAR GUARDA LA ULTIMA RESPUESTA PARA VERLA SIN SEÑAL
-- SOLO EL DUEÑO Y EL VETERINARIO (EL VAQUERO NO TIENE EL MENU 6)
--
-- QUIEN CUENTA EN EL PERIODO: UN ANIMAL "ESTUVO EN LA FINCA" SI LLEGO (FECHA_INGRESO_ANIMAL) ANTES DEL FIN DEL PERIODO Y NO HABIA SALIDO
-- (FECHA_SALIDA_ANIMAL) ANTES DEL INICIO. LOS ANULADOS NUNCA CUENTAN
--
-- INDICADOR                COMO SE CALCULA
-- NATALIDAD (%)            CRIAS NACIDAS VIVAS EN EL PERIODO / HEMBRAS REPRODUCTORAS QUE ESTUVIERON (24 MESES O MAS AL FINAL DEL PERIODO, O CON PARTOS) × 100
-- MORTALIDAD (%)           MUERTES EN EL PERIODO / ANIMALES QUE ESTUVIERON × 100
-- INTERVALO ENTRE PARTOS   PROMEDIO DE DIAS ENTRE DOS PARTOS SEGUIDOS DE LA MISMA VACA, CUANDO EL SEGUNDO CAE EN EL PERIODO
-- LITROS POR VACA AL DIA   PROMEDIO, ENTRE LOS DIAS CON ORDEÑO, DE (LITROS DEL DIA / VACAS ORDEÑADAS ESE DIA)
-- GANANCIA DIARIA DE PESO  POR ANIMAL CON DOS O MAS PESAJES EN EL PERIODO SEPARADOS AL MENOS 14 DIAS: (ULTIMO - PRIMERO) / DIAS, EN GRAMOS;
--                          PROMEDIO POR LOTE (EL LOTE DE HOY DEL ANIMAL)



-- FUNCION QUE DEVUELVE LOS INDICADORES DE UNA FINCA EN UN PERIODO. DESDE Y HASTA NULL = LOS ULTIMOS 12 MESES HASTA HOY. MAXIMO 3 AÑOS
CREATE OR REPLACE FUNCTION FUN_OBTENER_INDICADORES_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jDESDE DATE,
    jHASTA DATE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jFIN DATE;
    jINICIO DATE;
    jPRESENTES INTEGER;
    jHEMBRAS INTEGER;
    jCRIAS_VIVAS INTEGER;
    jMUERTES INTEGER;
    jINTERVALO NUMERIC;
    jINTERVALOS INTEGER;
    jLITROS NUMERIC;
    jDIAS_ORDENO INTEGER;
    jLITROS_VACA_DIA NUMERIC;
    jVENTAS INTEGER;
    jVALOR_VENTAS NUMERIC;
    jGDP_GENERAL NUMERIC;
    jGDP_ANIMALES INTEGER;
    LISTA_CATEGORIAS JSON;
    LISTA_LECHE_MES JSON;
    LISTA_PARTOS_MES JSON;
    LISTA_GDP_LOTE JSON;
BEGIN
    --VALIDAR EL ACCESO (DUEÑO Y VETERINARIO)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO', 'VETERINARIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --EL PERIODO
    jFIN := COALESCE(jHASTA, CURRENT_DATE);
    jINICIO := COALESCE(jDESDE, (jFIN - INTERVAL '12 months')::DATE + 1);
    IF jINICIO > jFIN THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha inicial debe ser antes de la final');
        RETURN RETORNO;
    ELSIF jFIN - jINICIO > 1100 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El periodo puede ser de máximo 3 años');
        RETURN RETORNO;
    END IF;

    --ANIMALES QUE ESTUVIERON EN LA FINCA EN EL PERIODO
    SELECT COUNT(*) INTO jPRESENTES
    FROM TAB_ANIMALES A
    WHERE A.ID_FINCA = jID_FINCA AND A.ESTADO_ANIMAL <> 'ANULADO'
      AND A.FECHA_INGRESO_ANIMAL <= jFIN AND COALESCE(A.FECHA_SALIDA_ANIMAL::DATE, 'infinity') >= jINICIO;

    --HEMBRAS REPRODUCTORAS QUE ESTUVIERON (24 MESES O MAS AL FINAL DEL PERIODO, O CON ALGUN PARTO)
    SELECT COUNT(*) INTO jHEMBRAS
    FROM TAB_ANIMALES A
    WHERE A.ID_FINCA = jID_FINCA AND A.ESTADO_ANIMAL <> 'ANULADO' AND A.SEXO_ANIMAL = 'H'
      AND A.FECHA_INGRESO_ANIMAL <= jFIN AND COALESCE(A.FECHA_SALIDA_ANIMAL::DATE, 'infinity') >= jINICIO
      AND (A.FECHA_NACIMIENTO <= (jFIN - INTERVAL '24 months')::DATE
           OR EXISTS (SELECT 1 FROM TAB_PARTOS P WHERE P.ID_ANIMAL = A.ID_ANIMAL AND P.ESTADO_PARTO = 'ACTIVO' AND P.FECHA_EVENTO::DATE <= jFIN));

    --CRIAS VIVAS Y MUERTES EN EL PERIODO
    SELECT COUNT(*) INTO jCRIAS_VIVAS FROM TAB_PARTOS
    WHERE ID_FINCA = jID_FINCA AND ESTADO_PARTO = 'ACTIVO' AND CRIA_VIVA = 'SI' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN;
    SELECT COUNT(*) INTO jMUERTES FROM TAB_SALIDAS
    WHERE ID_FINCA = jID_FINCA AND ESTADO_SALIDA = 'ACTIVO' AND TIPO_SALIDA = 'MUERTE' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN;

    --INTERVALO ENTRE PARTOS: CADA PARTO DEL PERIODO CONTRA EL PARTO ANTERIOR DE LA MISMA VACA
    SELECT AVG(T.DIAS), COUNT(*) INTO jINTERVALO, jINTERVALOS
    FROM (
        SELECT P.FECHA_EVENTO::DATE - (SELECT MAX(Q.FECHA_EVENTO)::DATE FROM TAB_PARTOS Q
                                       WHERE Q.ID_ANIMAL = P.ID_ANIMAL AND Q.ESTADO_PARTO = 'ACTIVO' AND Q.FECHA_EVENTO < P.FECHA_EVENTO) AS DIAS
        FROM TAB_PARTOS P
        WHERE P.ID_FINCA = jID_FINCA AND P.ESTADO_PARTO = 'ACTIVO' AND P.FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
    ) T
    WHERE T.DIAS IS NOT NULL;

    --LECHE: TOTAL, DIAS CON ORDEÑO Y LITROS POR VACA AL DIA
    SELECT SUM(T.LITROS), COUNT(*), AVG(T.LITROS / T.VACAS) INTO jLITROS, jDIAS_ORDENO, jLITROS_VACA_DIA
    FROM (
        SELECT FECHA_EVENTO::DATE AS DIA, SUM(LITROS_ORDENO) AS LITROS, COUNT(DISTINCT ID_ANIMAL) AS VACAS
        FROM TAB_ORDENOS
        WHERE ID_FINCA = jID_FINCA AND ESTADO_ORDENO = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
        GROUP BY FECHA_EVENTO::DATE
    ) T;

    --LECHE POR MES (PARA LA GRAFICA)
    SELECT json_agg(json_build_object('MES', T.MES, 'LITROS', T.LITROS, 'LITROS_VACA_DIA', round(T.LVD, 1)) ORDER BY T.MES) INTO LISTA_LECHE_MES
    FROM (
        SELECT to_char(D.DIA, 'YYYY-MM') AS MES, SUM(D.LITROS) AS LITROS, AVG(D.LITROS / D.VACAS) AS LVD
        FROM (
            SELECT FECHA_EVENTO::DATE AS DIA, SUM(LITROS_ORDENO) AS LITROS, COUNT(DISTINCT ID_ANIMAL) AS VACAS
            FROM TAB_ORDENOS
            WHERE ID_FINCA = jID_FINCA AND ESTADO_ORDENO = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
            GROUP BY FECHA_EVENTO::DATE
        ) D
        GROUP BY to_char(D.DIA, 'YYYY-MM')
    ) T;

    --PARTOS POR MES (PARA LA GRAFICA)
    SELECT json_agg(json_build_object('MES', T.MES, 'PARTOS', T.PARTOS, 'CRIAS_VIVAS', T.VIVAS) ORDER BY T.MES) INTO LISTA_PARTOS_MES
    FROM (
        SELECT to_char(FECHA_EVENTO, 'YYYY-MM') AS MES, COUNT(*) AS PARTOS, COUNT(*) FILTER (WHERE CRIA_VIVA = 'SI') AS VIVAS
        FROM TAB_PARTOS
        WHERE ID_FINCA = jID_FINCA AND ESTADO_PARTO = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
        GROUP BY to_char(FECHA_EVENTO, 'YYYY-MM')
    ) T;

    --GANANCIA DIARIA DE PESO: POR ANIMAL (PRIMER Y ULTIMO PESAJE DEL PERIODO, AL MENOS 14 DIAS ENTRE ELLOS) Y PROMEDIO POR LOTE
    SELECT json_agg(json_build_object('NOM_LOTE', T.NOM_LOTE, 'ANIMALES', T.ANIMALES, 'GRAMOS_DIA', round(T.GRAMOS)) ORDER BY T.NOM_LOTE) INTO LISTA_GDP_LOTE
    FROM (
        SELECT COALESCE(L.NOM_LOTE, 'Sin lote') AS NOM_LOTE, COUNT(*) AS ANIMALES, AVG(G.GRAMOS) AS GRAMOS
        FROM (
            SELECT P1.ID_ANIMAL, (P2.PESO_KG - P1.PESO_KG) * 1000 / (P2.FECHA_EVENTO::DATE - P1.FECHA_EVENTO::DATE) AS GRAMOS
            FROM (SELECT DISTINCT ON (ID_ANIMAL) ID_ANIMAL, PESO_KG, FECHA_EVENTO FROM TAB_PESAJES
                  WHERE ID_FINCA = jID_FINCA AND ESTADO_PESAJE = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
                  ORDER BY ID_ANIMAL, FECHA_EVENTO ASC) P1
            JOIN (SELECT DISTINCT ON (ID_ANIMAL) ID_ANIMAL, PESO_KG, FECHA_EVENTO FROM TAB_PESAJES
                  WHERE ID_FINCA = jID_FINCA AND ESTADO_PESAJE = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
                  ORDER BY ID_ANIMAL, FECHA_EVENTO DESC) P2 ON P2.ID_ANIMAL = P1.ID_ANIMAL
            WHERE P2.FECHA_EVENTO::DATE - P1.FECHA_EVENTO::DATE >= 14
        ) G
        JOIN TAB_ANIMALES A ON A.ID_ANIMAL = G.ID_ANIMAL
        LEFT JOIN TAB_LOTES L ON L.ID_LOTE = A.ID_LOTE
        GROUP BY COALESCE(L.NOM_LOTE, 'Sin lote')
    ) T;

    SELECT AVG(G.GRAMOS), COUNT(*) INTO jGDP_GENERAL, jGDP_ANIMALES
    FROM (
        SELECT (P2.PESO_KG - P1.PESO_KG) * 1000 / (P2.FECHA_EVENTO::DATE - P1.FECHA_EVENTO::DATE) AS GRAMOS
        FROM (SELECT DISTINCT ON (ID_ANIMAL) ID_ANIMAL, PESO_KG, FECHA_EVENTO FROM TAB_PESAJES
              WHERE ID_FINCA = jID_FINCA AND ESTADO_PESAJE = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
              ORDER BY ID_ANIMAL, FECHA_EVENTO ASC) P1
        JOIN (SELECT DISTINCT ON (ID_ANIMAL) ID_ANIMAL, PESO_KG, FECHA_EVENTO FROM TAB_PESAJES
              WHERE ID_FINCA = jID_FINCA AND ESTADO_PESAJE = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
              ORDER BY ID_ANIMAL, FECHA_EVENTO DESC) P2 ON P2.ID_ANIMAL = P1.ID_ANIMAL
        WHERE P2.FECHA_EVENTO::DATE - P1.FECHA_EVENTO::DATE >= 14
    ) G;

    --VENTAS DEL PERIODO
    SELECT COUNT(*), COALESCE(SUM(VALOR_SALIDA), 0) INTO jVENTAS, jVALOR_VENTAS FROM TAB_SALIDAS
    WHERE ID_FINCA = jID_FINCA AND ESTADO_SALIDA = 'ACTIVO' AND TIPO_SALIDA = 'VENTA' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN;

    --EL HATO DE HOY POR CATEGORIA
    SELECT json_agg(json_build_object('CATEGORIA', T.CATEGORIA, 'CANTIDAD', T.CANTIDAD) ORDER BY T.ORDEN) INTO LISTA_CATEGORIAS
    FROM (
        SELECT FUN_CATEGORIA_ANIMAL(ID_ANIMAL) AS CATEGORIA, COUNT(*) AS CANTIDAD,
            array_position(ARRAY['VACA', 'NOVILLA', 'TERNERA', 'TORO', 'NOVILLO', 'TERNERO']::VARCHAR[], FUN_CATEGORIA_ANIMAL(ID_ANIMAL)) AS ORDEN
        FROM TAB_ANIMALES
        WHERE ID_FINCA = jID_FINCA AND ESTADO_ANIMAL = 'ACTIVO'
        GROUP BY FUN_CATEGORIA_ANIMAL(ID_ANIMAL)
    ) T;

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Indicadores de la finca',
        'DATOS', json_build_object(
            'DESDE', jINICIO,
            'HASTA', jFIN,
            'ANIMALES_EN_EL_PERIODO', jPRESENTES,
            'HATO_POR_CATEGORIA', COALESCE(LISTA_CATEGORIAS, '[]'::JSON),
            'NATALIDAD', json_build_object('CRIAS_VIVAS', jCRIAS_VIVAS, 'HEMBRAS', jHEMBRAS,
                'PORCENTAJE', CASE WHEN jHEMBRAS > 0 THEN round(jCRIAS_VIVAS * 100.0 / jHEMBRAS, 1) END),
            'MORTALIDAD', json_build_object('MUERTES', jMUERTES, 'ANIMALES', jPRESENTES,
                'PORCENTAJE', CASE WHEN jPRESENTES > 0 THEN round(jMUERTES * 100.0 / jPRESENTES, 1) END),
            'INTERVALO_PARTOS', json_build_object('PROMEDIO_DIAS', round(jINTERVALO), 'INTERVALOS', COALESCE(jINTERVALOS, 0)),
            'LECHE', json_build_object('LITROS_TOTALES', COALESCE(jLITROS, 0), 'DIAS_CON_ORDENO', COALESCE(jDIAS_ORDENO, 0),
                'LITROS_VACA_DIA', round(jLITROS_VACA_DIA, 1), 'POR_MES', COALESCE(LISTA_LECHE_MES, '[]'::JSON)),
            'PARTOS_POR_MES', COALESCE(LISTA_PARTOS_MES, '[]'::JSON),
            'GANANCIA_PESO', json_build_object('GRAMOS_DIA', round(jGDP_GENERAL), 'ANIMALES', COALESCE(jGDP_ANIMALES, 0),
                'POR_LOTE', COALESCE(LISTA_GDP_LOTE, '[]'::JSON)),
            'VENTAS', json_build_object('CANTIDAD', jVENTAS, 'VALOR_TOTAL', jVALOR_VENTAS)));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
