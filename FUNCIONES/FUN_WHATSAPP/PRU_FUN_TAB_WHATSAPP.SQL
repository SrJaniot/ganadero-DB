-- PRUEBAS DEL RESUMEN DIARIO POR WHATSAPP (FASE 5D)
-- SE EJECUTAN DENTRO DE UNA TRANSACCION Y AL FINAL SE HACE ROLLBACK PARA NO DEJAR DATOS DE PRUEBA
-- ESCENARIO: "Finca Prueba" CON LA VACA 23 SERVIDA HACE 270 DIAS (PARTO EN 13 DIAS) Y TRATADA HACE 2 (RETIRO DE LECHE);
--            "Finca Tranquila" SIN NADA URGENTE. LOS DOS DUEÑOS PIDEN EL RESUMEN
BEGIN;

SELECT FUN_CREAR_FINCA_JSON('Finca Prueba', 'San Gil', NULL, NULL, NULL, 'PRU-DUENO', 'Dueño Prueba') ->> 'CODIGO' AS FINCA_200,
       FUN_CREAR_FINCA_JSON('Finca Tranquila', 'Mogotes', NULL, NULL, NULL, 'PRU-DUENO2', 'Dueña Tranquila') ->> 'CODIGO' AS FINCA2_200;
CREATE FUNCTION pg_temp.FINCA() RETURNS INTEGER AS $$ SELECT ID_FINCA FROM TAB_FINCAS WHERE NOM_FINCA = 'Finca Prueba' $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.FINCA2() RETURNS INTEGER AS $$ SELECT ID_FINCA FROM TAB_FINCAS WHERE NOM_FINCA = 'Finca Tranquila' $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.U(jSUFIJO VARCHAR) RETURNS UUID AS $$ SELECT ('00000000-0000-0000-0000-' || lpad(replace(jSUFIJO, 'T', 'F'), 12, '0'))::UUID $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.HACE(jDIAS INTEGER) RETURNS TIMESTAMP AS $$ SELECT (CURRENT_DATE - jDIAS) + TIME '08:00' $$ LANGUAGE sql;
SELECT FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VAQUERO', 'Vaquero Prueba', 'VAQUERO', 'PRU-DUENO') ->> 'CODIGO' AS VAQUERO_200;
SELECT FUN_CREAR_ANIMAL_JSON(pg_temp.U(c), pg_temp.FINCA(), NULL, NULL, c, NULL, CASE WHEN c = 'T1' THEN 'M' ELSE 'H' END, '2019-01-01', 'SI', NULL, NULL, NULL,
       'COMPRADO', (CURRENT_DATE - 400), 'PRU-DUENO') ->> 'CODIGO' AS ANIMAL_200
FROM unnest(ARRAY['23', 'T1']) AS c;
SELECT FUN_CREAR_SERVICIO_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('23'), 'MONTA', pg_temp.U('T1'), NULL, pg_temp.HACE(270), NULL, 'PRU-DUENO') ->> 'CODIGO' AS SERVICIO_200,
       FUN_CREAR_VACUNACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('23'), 8, NULL, pg_temp.HACE(2), NULL, 'PRU-DUENO') ->> 'CODIGO' AS TRATAMIENTO_200;


SELECT 'PRUEBA 1.1: El texto del resumen. DEBE TRAER LA FINCA, "No vender la leche de: 23 (hasta el ...)" Y "Partos próximos (1): 23 (en 13 días)", SIN ENLACES' as PRUEBA;
SELECT FUN_TEXTO_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO', CURRENT_DATE) -> 'DATOS' ->> 'TEXTO' AS TEXTO;
SELECT (FUN_TEXTO_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO', CURRENT_DATE) -> 'DATOS' ->> 'TEXTO') LIKE '%Partos próximos (1): 23 (en 13 días)%' AS PARTO_TRUE,
       (FUN_TEXTO_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO', CURRENT_DATE) -> 'DATOS' ->> 'TEXTO') LIKE '%No vender la leche de: 23 (hasta el %' AS LECHE_TRUE,
       (FUN_TEXTO_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO', CURRENT_DATE) -> 'DATOS' ->> 'TEXTO') NOT LIKE '%http%' AS SIN_ENLACES_TRUE,
       FUN_TEXTO_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA2(), 'PRU-DUENO2', CURRENT_DATE) -> 'DATOS' ->> 'HAY_ALERTAS' AS TRANQUILA_FALSE;

SELECT 'PRUEBA 1.2: Hasta 5 nombres y "y N más". CON 7 ANIMALES EN LA LISTA SALEN 5 Y "y 2 más"' as PRUEBA;
SELECT FUN_LISTA_RESUMEN_WHATSAPP(json_build_array(
    json_build_object('CHAPETA_ANIMAL', '1'), json_build_object('CHAPETA_ANIMAL', '2'), json_build_object('CHAPETA_ANIMAL', '3'), json_build_object('CHAPETA_ANIMAL', '4'),
    json_build_object('CHAPETA_ANIMAL', '5'), json_build_object('CHAPETA_ANIMAL', '6'), json_build_object('NOM_ANIMAL', 'Lucero')), NULL) AS LISTA,
    FUN_LISTA_RESUMEN_WHATSAPP('[]'::JSON, NULL) IS NULL AS VACIA_NULL;


SELECT 'PRUEBA 2.1: Encolar. CON EL ENVIO APAGADO 400; PRENDIDO Y SIN DUEÑOS QUE LO PIDAN, 0' as PRUEBA;
SELECT FUN_ENCOLAR_RESUMENES_JSON(CURRENT_DATE) ->> 'CODIGO' AS APAGADO_400;
SELECT FUN_GUARDAR_CONFIG_WHATSAPP_JSON('ganadero', '06:00', 'SI', 'PRU-ADMIN') ->> 'CODIGO' AS PRENDER_200;
SELECT FUN_ENCOLAR_RESUMENES_JSON(CURRENT_DATE) -> 'DATOS' ->> 'ENCOLADOS' AS ENCOLADOS_0;

SELECT 'PRUEBA 2.2: Pedir el resumen. LOS DOS DUEÑOS 200; EL VAQUERO NO PUEDE (400); VALOR RARO 400' as PRUEBA;
SELECT FUN_CAMBIAR_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO', 'SI') ->> 'CODIGO' AS DUENO_200,
       FUN_CAMBIAR_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA2(), 'PRU-DUENO2', 'SI') ->> 'CODIGO' AS DUENA_200,
       FUN_CAMBIAR_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-VAQUERO', 'SI') ->> 'CODIGO' AS VAQUERO_400,
       FUN_CAMBIAR_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO', 'TAL VEZ') ->> 'CODIGO' AS RARO_400;

SELECT 'PRUEBA 2.3: Encolar. SOLO 1 (LA FINCA TRANQUILA NO TIENE NADA URGENTE); OTRA VEZ EL MISMO DIA: 0 (NO REPITE)' as PRUEBA;
SELECT FUN_ENCOLAR_RESUMENES_JSON(CURRENT_DATE) -> 'DATOS' AS PRIMERA;
SELECT FUN_ENCOLAR_RESUMENES_JSON(CURRENT_DATE) -> 'DATOS' ->> 'ENCOLADOS' AS SEGUNDA_0;

SELECT 'PRUEBA 2.4: Lo que ve el dueño. ACTIVO true, ENVIO_PRENDIDO true, HORA 06:00, ULTIMO PENDIENTE' as PRUEBA;
SELECT FUN_OBTENER_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO') -> 'DATOS' ->> 'ACTIVO' AS ACTIVO,
       FUN_OBTENER_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO') -> 'DATOS' ->> 'ENVIO_PRENDIDO' AS PRENDIDO,
       FUN_OBTENER_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO') -> 'DATOS' ->> 'HORA' AS HORA,
       FUN_OBTENER_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-DUENO') -> 'DATOS' -> 'ULTIMO' ->> 'ESTADO_MENSAJE' AS ULTIMO,
       FUN_OBTENER_RESUMEN_WHATSAPP_JSON(pg_temp.FINCA(), 'PRU-VAQUERO') ->> 'CODIGO' AS VAQUERO_400;


SELECT 'PRUEBA 3.1: La cola. 1 PENDIENTE; TRES ERRORES LO DEJAN FALLIDO Y SALE DE LA COLA (404)' as PRUEBA;
SELECT json_array_length(FUN_OBTENER_MENSAJES_PENDIENTES_JSON(10) -> 'DATOS') AS PENDIENTES_1;
SELECT FUN_MARCAR_MENSAJE_WHATSAPP_JSON((SELECT MAX(ID_MENSAJE) FROM TAB_MENSAJES_WHATSAPP), 'ERROR', 'Evolution caído') ->> 'CODIGO' AS ERROR1,
       FUN_MARCAR_MENSAJE_WHATSAPP_JSON((SELECT MAX(ID_MENSAJE) FROM TAB_MENSAJES_WHATSAPP), 'ERROR', 'Evolution caído') ->> 'CODIGO' AS ERROR2;
SELECT FUN_MARCAR_MENSAJE_WHATSAPP_JSON((SELECT MAX(ID_MENSAJE) FROM TAB_MENSAJES_WHATSAPP), 'ERROR', 'Evolution caído') ->> 'CODIGO' AS ERROR3;
SELECT ESTADO_MENSAJE AS FALLIDO, INTENTOS_MENSAJE AS INTENTOS_3 FROM TAB_MENSAJES_WHATSAPP WHERE ID_MENSAJE = (SELECT MAX(ID_MENSAJE) FROM TAB_MENSAJES_WHATSAPP);
SELECT FUN_OBTENER_MENSAJES_PENDIENTES_JSON(10) ->> 'CODIGO' AS VACIA_404;

SELECT 'PRUEBA 3.2: Mañana sale otro; ENVIADO lo saca de la cola y guarda la hora. LA CONFIGURACION DE HOY: 0 ENVIADOS Y 1 FALLIDO (EL ENVIADO ES DE MAÑANA); 2 DUEÑOS CON RESUMEN' as PRUEBA;
SELECT FUN_ENCOLAR_RESUMENES_JSON(CURRENT_DATE + 1) -> 'DATOS' ->> 'ENCOLADOS' AS MANANA_1;
SELECT FUN_MARCAR_MENSAJE_WHATSAPP_JSON((SELECT MAX(ID_MENSAJE) FROM TAB_MENSAJES_WHATSAPP), 'ENVIADO', NULL) ->> 'CODIGO' AS ENVIADO_200;
SELECT ESTADO_MENSAJE, FECHA_ENVIO_MENSAJE IS NOT NULL AS CON_HORA_TRUE FROM TAB_MENSAJES_WHATSAPP WHERE ID_MENSAJE = (SELECT MAX(ID_MENSAJE) FROM TAB_MENSAJES_WHATSAPP);
SELECT FUN_OBTENER_CONFIG_WHATSAPP_JSON() -> 'DATOS' -> 'HOY' AS HOY_1_FALLIDO, FUN_OBTENER_CONFIG_WHATSAPP_JSON() -> 'DATOS' ->> 'DUENIOS_CON_RESUMEN' AS DUENIOS_2;

SELECT 'PRUEBA 4.1: Configuración del administrador. 400 CON INSTANCIA RARA, HORA 25:00 O ACTIVO RARO; 200 Y QUEDA LA HORA 05:30' as PRUEBA;
SELECT FUN_GUARDAR_CONFIG_WHATSAPP_JSON('mi instancia', '06:00', 'SI', 'PRU-ADMIN') ->> 'CODIGO' AS INSTANCIA_400,
       FUN_GUARDAR_CONFIG_WHATSAPP_JSON('ganadero', '25:00', 'SI', 'PRU-ADMIN') ->> 'CODIGO' AS HORA_400,
       FUN_GUARDAR_CONFIG_WHATSAPP_JSON('ganadero', '06:00', 'X', 'PRU-ADMIN') ->> 'CODIGO' AS ACTIVO_400,
       FUN_GUARDAR_CONFIG_WHATSAPP_JSON('ganadero-demo', '05:30', 'NO', 'PRU-ADMIN') ->> 'CODIGO' AS GUARDAR_200;
SELECT FUN_OBTENER_CONFIG_WHATSAPP_JSON() -> 'DATOS' ->> 'INSTANCIA' AS INSTANCIA, FUN_OBTENER_CONFIG_WHATSAPP_JSON() -> 'DATOS' ->> 'HORA' AS HORA_0530,
       FUN_OBTENER_CONFIG_WHATSAPP_JSON() -> 'DATOS' ->> 'ACTIVO' AS ACTIVO_FALSE;

