-- FUNCIONES DEL RESUMEN DIARIO POR WHATSAPP (FASE 5D) ------------------------------------------------------------------------------------------
-- EL DUEÑO LO ACTIVA EN "MI FINCA" (RESUMEN_WHATSAPP_PERSONA = 'SI'); EL ADMINISTRADOR VINCULA EL NUMERO QUE MANDA Y PRENDE EL ENVIO (WHATSAPP_ACTIVO)
-- EL TEXTO SALE DE FUN_OBTENER_ALERTAS_JSON (LO MISMO DE "PARA HOY"). SIN ENLACES. SI NO HAY NADA URGENTE ESE DIA, NO SE MANDA NADA
-- CONFIGURACION (TAB_CONFIGURACION): INSTANCIA_WHATSAPP, HORA_RESUMEN_WHATSAPP (HH:MM, HORA DE COLOMBIA), WHATSAPP_ACTIVO (SI / NO)



-- FUNCION QUE ARMA EL TEXTO DEL RESUMEN DE UN DUEÑO PARA UN DIA. DEVUELVE {CODIGO, DATOS:{TEXTO, HAY_ALERTAS}}
-- HASTA 5 NOMBRES POR LISTA Y "Y N MAS"; LAS LISTAS VACIAS NO SALEN
CREATE OR REPLACE FUNCTION FUN_TEXTO_RESUMEN_WHATSAPP_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jFECHA DATE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jALERTAS JSON;
    jA JSON;
    jNOM_FINCA VARCHAR;
    jLINEAS TEXT[] := ARRAY[]::TEXT[];
    jLINEA TEXT;
    jCICLO JSON;
BEGIN
    jALERTAS := FUN_OBTENER_ALERTAS_JSON(jID_FINCA, jID_USUARIO, jFECHA);
    IF (jALERTAS ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jALERTAS;
    END IF;
    jA := jALERTAS -> 'DATOS';
    SELECT NOM_FINCA INTO jNOM_FINCA FROM TAB_FINCAS WHERE ID_FINCA = jID_FINCA;

    --LECHE QUE NO SE VENDE (LO MAS URGENTE)
    jLINEA := FUN_LISTA_RESUMEN_WHATSAPP(jA -> 'RETIROS_LECHE', 'RETIRO');
    IF jLINEA IS NOT NULL THEN jLINEAS := jLINEAS || ('• No vender la leche de: ' || jLINEA); END IF;
    jLINEA := FUN_LISTA_RESUMEN_WHATSAPP(jA -> 'PARTOS_PROXIMOS', 'PARTO');
    IF jLINEA IS NOT NULL THEN jLINEAS := jLINEAS || ('• Partos próximos (' || json_array_length(jA -> 'PARTOS_PROXIMOS') || '): ' || jLINEA); END IF;
    jLINEA := FUN_LISTA_RESUMEN_WHATSAPP(jA -> 'PALPAR', NULL);
    IF jLINEA IS NOT NULL THEN jLINEAS := jLINEAS || ('• Para palpar (' || json_array_length(jA -> 'PALPAR') || '): ' || jLINEA); END IF;
    jLINEA := FUN_LISTA_RESUMEN_WHATSAPP(jA -> 'VACIAS', NULL);
    IF jLINEA IS NOT NULL THEN jLINEAS := jLINEAS || ('• Vacas vacías (' || json_array_length(jA -> 'VACIAS') || '): ' || jLINEA); END IF;
    jLINEA := FUN_LISTA_RESUMEN_WHATSAPP(jA -> 'VACUNAS_POR_APLICAR', 'VACUNA');
    IF jLINEA IS NOT NULL THEN jLINEAS := jLINEAS || ('• Vacunas por aplicar (' || json_array_length(jA -> 'VACUNAS_POR_APLICAR') || '): ' || jLINEA); END IF;
    FOR jCICLO IN SELECT C.value FROM json_array_elements(jA -> 'CICLOS_ICA') C WHERE (C.value ->> 'FALTAN')::INTEGER > 0 AND (C.value ->> 'VIGENTE')::BOOLEAN LOOP
        jLINEAS := jLINEAS || ('• Ciclo del ICA «' || (jCICLO ->> 'NOM_CICLO') || '»: faltan ' || (jCICLO ->> 'FALTAN') || ' animales por vacunar');
    END LOOP;

    IF array_length(jLINEAS, 1) IS NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Nada urgente hoy',
            'DATOS', json_build_object('HAY_ALERTAS', false,
                'TEXTO', 'Ganadero · ' || jNOM_FINCA || E'\n' || 'Hoy ' || to_char(jFECHA, 'DD/MM') || ': nada urgente. Todo al día.'));
        RETURN RETORNO;
    END IF;
    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Resumen de hoy',
        'DATOS', json_build_object('HAY_ALERTAS', true,
            'TEXTO', 'Ganadero · ' || jNOM_FINCA || E'\n' || 'Para hoy, ' || to_char(jFECHA, 'DD/MM') || E':\n' || array_to_string(jLINEAS, E'\n')
                || E'\n' || 'Abre la app para ver el detalle.'));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE CONVIERTE UNA LISTA DE ALERTAS EN "23, 25 (en 13 días) y 2 más" (HASTA 5 ANIMALES). NULL SI LA LISTA ESTA VACIA
-- jDETALLE: 'PARTO' (EN N DIAS), 'VACUNA' (NOMBRE DE LA VACUNA), 'RETIRO' (HASTA EL DIA) O NULL (SOLO EL ANIMAL)
CREATE OR REPLACE FUNCTION FUN_LISTA_RESUMEN_WHATSAPP(
    jLISTA JSON,
    jDETALLE VARCHAR
) RETURNS TEXT AS
$$
DECLARE
    jTOTAL INTEGER;
    jTEXTO TEXT;
BEGIN
    jTOTAL := COALESCE(json_array_length(jLISTA), 0);
    IF jTOTAL = 0 THEN
        RETURN NULL;
    END IF;
    SELECT string_agg(COALESCE(E.value ->> 'CHAPETA_ANIMAL', E.value ->> 'NOM_ANIMAL', 'sin chapeta')
        || CASE jDETALLE
               WHEN 'PARTO' THEN CASE WHEN (E.value ->> 'DIAS')::INTEGER < 0 THEN ' (atrasado ' || -(E.value ->> 'DIAS')::INTEGER || ' días)'
                                      WHEN (E.value ->> 'DIAS')::INTEGER = 0 THEN ' (hoy)'
                                      ELSE ' (en ' || (E.value ->> 'DIAS') || ' días)' END
               WHEN 'VACUNA' THEN ' (' || (E.value ->> 'NOM_VACUNA') || ')'
               WHEN 'RETIRO' THEN ' (hasta el ' || to_char((E.value ->> 'FECHA_FIN_RETIRO')::DATE, 'DD/MM') || ')'
               ELSE '' END, ', ' ORDER BY E.posicion)
    INTO jTEXTO
    FROM json_array_elements(jLISTA) WITH ORDINALITY AS E(value, posicion)
    WHERE E.posicion <= 5;
    IF jTOTAL > 5 THEN
        jTEXTO := jTEXTO || ' y ' || (jTOTAL - 5) || ' más';
    END IF;
    RETURN jTEXTO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE PONE EN LA COLA EL RESUMEN DEL DIA DE CADA DUEÑO ACTIVO QUE LO PIDIO (LA LLAMA ms-logica A LA HORA DEL RESUMEN)
-- SOLO SI EL ADMINISTRADOR PRENDIO EL ENVIO (WHATSAPP_ACTIVO = SI) Y SOLO SI ESE DIA HAY ALGO URGENTE. NO REPITE (UNO POR DIA)
CREATE OR REPLACE FUNCTION FUN_ENCOLAR_RESUMENES_JSON(
    jFECHA DATE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jPERSONA RECORD;
    jTEXTO JSON;
    jENCOLADOS INTEGER := 0;
    jSIN_NADA INTEGER := 0;
    jID_MENSAJE INTEGER;
BEGIN
    IF COALESCE((SELECT VALOR_CONFIGURACION FROM TAB_CONFIGURACION WHERE NOM_CONFIGURACION = 'WHATSAPP_ACTIVO'), 'NO') <> 'SI' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El envío por WhatsApp está apagado');
        RETURN RETORNO;
    END IF;

    FOR jPERSONA IN
        SELECT P.ID_FINCA, P.ID_USUARIO FROM TAB_FINCAS_PERSONAS P JOIN TAB_FINCAS F ON F.ID_FINCA = P.ID_FINCA
        WHERE P.ROL_FINCA = 'DUENIO' AND P.ESTADO_FINCA_PERSONA = 'ACTIVO' AND P.RESUMEN_WHATSAPP_PERSONA = 'SI'
          AND NOT EXISTS (SELECT 1 FROM TAB_MENSAJES_WHATSAPP M WHERE M.ID_FINCA = P.ID_FINCA AND M.ID_USUARIO = P.ID_USUARIO AND M.FECHA_RESUMEN = jFECHA)
        ORDER BY P.ID_FINCA_PERSONA
    LOOP
        jTEXTO := FUN_TEXTO_RESUMEN_WHATSAPP_JSON(jPERSONA.ID_FINCA, jPERSONA.ID_USUARIO, jFECHA);
        IF (jTEXTO ->> 'CODIGO')::INTEGER = 200 AND (jTEXTO -> 'DATOS' ->> 'HAY_ALERTAS')::BOOLEAN THEN
            jID_MENSAJE := funcion_Retorna_ultmoid('TAB_MENSAJES_WHATSAPP', 'ID_MENSAJE');
            INSERT INTO TAB_MENSAJES_WHATSAPP (ID_MENSAJE, ID_FINCA, ID_USUARIO, FECHA_RESUMEN, TEXTO_MENSAJE, USUARIO_CREACION)
            VALUES (jID_MENSAJE, jPERSONA.ID_FINCA, jPERSONA.ID_USUARIO, jFECHA, jTEXTO -> 'DATOS' ->> 'TEXTO', 'SISTEMA')
            ON CONFLICT ON CONSTRAINT UQ_MENSAJE_DIA DO NOTHING;
            IF FOUND THEN
                jENCOLADOS := jENCOLADOS + 1;
            END IF;
        ELSE
            jSIN_NADA := jSIN_NADA + 1;
        END IF;
    END LOOP;

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', jENCOLADOS || ' resúmenes en la cola',
        'DATOS', json_build_object('ENCOLADOS', jENCOLADOS, 'SIN_NADA_URGENTE', jSIN_NADA));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LOS MENSAJES POR MANDAR (EN ORDEN), HASTA jLIMITE. LISTA VACIA = 404
CREATE OR REPLACE FUNCTION FUN_OBTENER_MENSAJES_PENDIENTES_JSON(
    jLIMITE INTEGER
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    LISTA_MENSAJES JSON;
BEGIN
    SELECT json_agg(json_build_object('ID_MENSAJE', T.ID_MENSAJE, 'ID_USUARIO', T.ID_USUARIO, 'TEXTO_MENSAJE', T.TEXTO_MENSAJE) ORDER BY T.ID_MENSAJE)
    INTO LISTA_MENSAJES
    FROM (SELECT ID_MENSAJE, ID_USUARIO, TEXTO_MENSAJE FROM TAB_MENSAJES_WHATSAPP
          WHERE ESTADO_MENSAJE = 'PENDIENTE' ORDER BY ID_MENSAJE LIMIT GREATEST(COALESCE(jLIMITE, 20), 1)) T;
    IF LISTA_MENSAJES IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'No hay mensajes por mandar');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Mensajes por mandar', 'DATOS', LISTA_MENSAJES);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE ANOTA COMO LE FUE A UN MENSAJE. jRESULTADO: ENVIADO, SIN_NUMERO O ERROR (A LOS 3 ERRORES QUEDA FALLIDO)
CREATE OR REPLACE FUNCTION FUN_MARCAR_MENSAJE_WHATSAPP_JSON(
    jID_MENSAJE TAB_MENSAJES_WHATSAPP.ID_MENSAJE%TYPE,
    jRESULTADO VARCHAR,
    jERROR TAB_MENSAJES_WHATSAPP.ERROR_MENSAJE%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    IF jRESULTADO NOT IN ('ENVIADO', 'SIN_NUMERO', 'ERROR') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Resultado no válido');
        RETURN RETORNO;
    END IF;

    UPDATE TAB_MENSAJES_WHATSAPP
    SET INTENTOS_MENSAJE = INTENTOS_MENSAJE + 1,
        ESTADO_MENSAJE = CASE WHEN jRESULTADO = 'ENVIADO' THEN 'ENVIADO' WHEN jRESULTADO = 'SIN_NUMERO' THEN 'SIN_NUMERO'
                              WHEN INTENTOS_MENSAJE + 1 >= 3 THEN 'FALLIDO' ELSE 'PENDIENTE' END,
        ERROR_MENSAJE = CASE WHEN jRESULTADO = 'ENVIADO' THEN NULL ELSE left(jERROR, 300) END,
        FECHA_ENVIO_MENSAJE = CASE WHEN jRESULTADO = 'ENVIADO' THEN LOCALTIMESTAMP ELSE FECHA_ENVIO_MENSAJE END,
        USUARIO_MODIFICACION = 'SISTEMA',
        FECHA_MODIFICACION = NOW()
    WHERE ID_MENSAJE = jID_MENSAJE AND ESTADO_MENSAJE = 'PENDIENTE';

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Mensaje actualizado');
    ELSE
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Ese mensaje no está pendiente');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA QUE EL DUEÑO PRENDA O APAGUE SU RESUMEN DIARIO EN UNA FINCA
CREATE OR REPLACE FUNCTION FUN_CAMBIAR_RESUMEN_WHATSAPP_JSON(
    jID_FINCA TAB_FINCAS_PERSONAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jACTIVO TAB_FINCAS_PERSONAS.RESUMEN_WHATSAPP_PERSONA%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jACTIVO IS NULL OR jACTIVO NOT IN ('SI', 'NO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Di si quieres el resumen (SI o NO)');
        RETURN RETORNO;
    END IF;

    UPDATE TAB_FINCAS_PERSONAS
    SET RESUMEN_WHATSAPP_PERSONA = jACTIVO,
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_FINCA = jID_FINCA AND ID_USUARIO = jID_USUARIO;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', CASE jACTIVO WHEN 'SI' THEN 'Listo: te llega el resumen cada mañana que haya algo para hacer'
            ELSE 'Listo: ya no te llega el resumen' END);
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al guardar el resumen');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE COMO ESTA EL RESUMEN DE UN DUEÑO EN UNA FINCA: SI LO PIDIO, SI EL ENVIO ESTA PRENDIDO, LA HORA, EL TEXTO DE HOY Y EL ULTIMO
CREATE OR REPLACE FUNCTION FUN_OBTENER_RESUMEN_WHATSAPP_JSON(
    jID_FINCA TAB_FINCAS_PERSONAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jACTIVO VARCHAR;
    jTEXTO JSON;
    jULTIMO JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT RESUMEN_WHATSAPP_PERSONA INTO jACTIVO FROM TAB_FINCAS_PERSONAS WHERE ID_FINCA = jID_FINCA AND ID_USUARIO = jID_USUARIO;
    jTEXTO := FUN_TEXTO_RESUMEN_WHATSAPP_JSON(jID_FINCA, jID_USUARIO, CURRENT_DATE);
    SELECT json_build_object('FECHA_RESUMEN', FECHA_RESUMEN, 'ESTADO_MENSAJE', ESTADO_MENSAJE, 'FECHA_ENVIO_MENSAJE', FECHA_ENVIO_MENSAJE) INTO jULTIMO
    FROM TAB_MENSAJES_WHATSAPP WHERE ID_FINCA = jID_FINCA AND ID_USUARIO = jID_USUARIO ORDER BY FECHA_RESUMEN DESC LIMIT 1;

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Resumen por WhatsApp',
        'DATOS', json_build_object(
            'ACTIVO', jACTIVO = 'SI',
            'ENVIO_PRENDIDO', COALESCE((SELECT VALOR_CONFIGURACION FROM TAB_CONFIGURACION WHERE NOM_CONFIGURACION = 'WHATSAPP_ACTIVO'), 'NO') = 'SI',
            'HORA', COALESCE((SELECT VALOR_CONFIGURACION FROM TAB_CONFIGURACION WHERE NOM_CONFIGURACION = 'HORA_RESUMEN_WHATSAPP'), '06:00'),
            'TEXTO_HOY', jTEXTO -> 'DATOS' ->> 'TEXTO',
            'HAY_ALERTAS_HOY', (jTEXTO -> 'DATOS' ->> 'HAY_ALERTAS')::BOOLEAN,
            'ULTIMO', jULTIMO));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LA CONFIGURACION DEL WHATSAPP (PANTALLA DEL ADMINISTRADOR; EL PERMISO LO REVISA ms-logica CON EL MENU 7)
-- MAS LO QUE PASO HOY CON LA COLA
CREATE OR REPLACE FUNCTION FUN_OBTENER_CONFIG_WHATSAPP_JSON() RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Configuración del WhatsApp',
        'DATOS', json_build_object(
            'INSTANCIA', COALESCE((SELECT VALOR_CONFIGURACION FROM TAB_CONFIGURACION WHERE NOM_CONFIGURACION = 'INSTANCIA_WHATSAPP'), 'ganadero'),
            'HORA', COALESCE((SELECT VALOR_CONFIGURACION FROM TAB_CONFIGURACION WHERE NOM_CONFIGURACION = 'HORA_RESUMEN_WHATSAPP'), '06:00'),
            'ACTIVO', COALESCE((SELECT VALOR_CONFIGURACION FROM TAB_CONFIGURACION WHERE NOM_CONFIGURACION = 'WHATSAPP_ACTIVO'), 'NO') = 'SI',
            'DUENIOS_CON_RESUMEN', (SELECT COUNT(*) FROM TAB_FINCAS_PERSONAS WHERE ROL_FINCA = 'DUENIO' AND ESTADO_FINCA_PERSONA = 'ACTIVO' AND RESUMEN_WHATSAPP_PERSONA = 'SI'),
            'HOY', (SELECT json_build_object(
                        'ENVIADOS', COUNT(*) FILTER (WHERE ESTADO_MENSAJE = 'ENVIADO'),
                        'PENDIENTES', COUNT(*) FILTER (WHERE ESTADO_MENSAJE = 'PENDIENTE'),
                        'FALLIDOS', COUNT(*) FILTER (WHERE ESTADO_MENSAJE IN ('FALLIDO', 'SIN_NUMERO')))
                    FROM TAB_MENSAJES_WHATSAPP WHERE FECHA_RESUMEN = CURRENT_DATE)));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE GUARDA LA CONFIGURACION DEL WHATSAPP (ADMINISTRADOR): TODO O NADA (BLOQUE BEGIN ... EXCEPTION)
CREATE OR REPLACE FUNCTION FUN_GUARDAR_CONFIG_WHATSAPP_JSON(
    jINSTANCIA VARCHAR,
    jHORA VARCHAR,
    jACTIVO VARCHAR,
    jID_USUARIO TAB_CONFIGURACION.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    IF jINSTANCIA IS NULL OR jINSTANCIA !~ '^[A-Za-z0-9_-]{1,50}$' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El nombre de la instancia solo lleva letras, números, - y _ (máximo 50)');
        RETURN RETORNO;
    ELSIF jHORA IS NULL OR jHORA !~ '^([01][0-9]|2[0-3]):[0-5][0-9]$' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La hora va como 06:00 (de 00:00 a 23:59)');
        RETURN RETORNO;
    ELSIF jACTIVO IS NULL OR jACTIVO NOT IN ('SI', 'NO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Di si el envío queda prendido (SI o NO)');
        RETURN RETORNO;
    END IF;

    BEGIN
        UPDATE TAB_CONFIGURACION SET VALOR_CONFIGURACION = jINSTANCIA, USUARIO_MODIFICACION = jID_USUARIO, FECHA_MODIFICACION = NOW() WHERE NOM_CONFIGURACION = 'INSTANCIA_WHATSAPP';
        IF NOT FOUND THEN RAISE EXCEPTION 'Falta INSTANCIA_WHATSAPP en la configuración (corre la migración 004)'; END IF;
        UPDATE TAB_CONFIGURACION SET VALOR_CONFIGURACION = jHORA, USUARIO_MODIFICACION = jID_USUARIO, FECHA_MODIFICACION = NOW() WHERE NOM_CONFIGURACION = 'HORA_RESUMEN_WHATSAPP';
        IF NOT FOUND THEN RAISE EXCEPTION 'Falta HORA_RESUMEN_WHATSAPP en la configuración (corre la migración 004)'; END IF;
        UPDATE TAB_CONFIGURACION SET VALOR_CONFIGURACION = jACTIVO, USUARIO_MODIFICACION = jID_USUARIO, FECHA_MODIFICACION = NOW() WHERE NOM_CONFIGURACION = 'WHATSAPP_ACTIVO';
        IF NOT FOUND THEN RAISE EXCEPTION 'Falta WHATSAPP_ACTIVO en la configuración (corre la migración 004)'; END IF;
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', CASE jACTIVO WHEN 'SI' THEN 'Guardado: el resumen sale cada día a las ' || jHORA ELSE 'Guardado: el envío quedó apagado' END);
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
