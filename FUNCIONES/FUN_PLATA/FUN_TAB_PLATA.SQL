-- FUNCIONES DE LA PLATA DE LA FINCA (FASE 5B: TAB_MOVIMIENTOS) -----------------------------------------------------------------------------------
-- SOLO EL DUEÑO ANOTA, VE Y ANULA (EL VAQUERO Y EL VETERINARIO NO RECIBEN LOS MOVIMIENTOS AL SINCRONIZAR)
-- SE ANOTA SIN SEÑAL: EL CELULAR GENERA EL UUID Y CREAR ES IDEMPOTENTE. ANULAR USA FUN_ANULAR_EVENTO_JSON (TIPO MOVIMIENTO)
-- LA VENTA DE ANIMALES NO SE ANOTA AQUI: SALE DE TAB_SALIDAS (VENTA CON VALOR), ASI NUNCA SE CUENTA DOS VECES



-- FUNCION QUE VALIDA UN MOVIMIENTO
CREATE OR REPLACE FUNCTION FUN_VALIDAR_MOVIMIENTO(
    jTIPO_MOVIMIENTO TAB_MOVIMIENTOS.TIPO_MOVIMIENTO%TYPE,
    jCATEGORIA_MOVIMIENTO TAB_MOVIMIENTOS.CATEGORIA_MOVIMIENTO%TYPE,
    jVALOR_MOVIMIENTO TAB_MOVIMIENTOS.VALOR_MOVIMIENTO%TYPE,
    jLITROS_MOVIMIENTO TAB_MOVIMIENTOS.LITROS_MOVIMIENTO%TYPE,
    jDESCRIPCION_MOVIMIENTO TAB_MOVIMIENTOS.DESCRIPCION_MOVIMIENTO%TYPE,
    jFECHA_EVENTO TAB_MOVIMIENTOS.FECHA_EVENTO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    IF jTIPO_MOVIMIENTO IS NULL OR jTIPO_MOVIMIENTO NOT IN ('INGRESO', 'GASTO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Di si es un ingreso o un gasto');
        RETURN RETORNO;
    ELSIF jTIPO_MOVIMIENTO = 'INGRESO' AND jCATEGORIA_MOVIMIENTO IS DISTINCT FROM 'VENTA_LECHE' AND jCATEGORIA_MOVIMIENTO IS DISTINCT FROM 'OTRO_INGRESO' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige de dónde viene el ingreso (la venta de animales se anota como salida del animal)');
        RETURN RETORNO;
    ELSIF jTIPO_MOVIMIENTO = 'GASTO' AND (jCATEGORIA_MOVIMIENTO IS NULL OR jCATEGORIA_MOVIMIENTO NOT IN ('COMPRA_ANIMAL', 'DROGAS', 'SAL_CONCENTRADO', 'JORNALES', 'OTRO_GASTO')) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige en qué fue el gasto');
        RETURN RETORNO;
    ELSIF jVALOR_MOVIMIENTO IS NULL OR jVALOR_MOVIMIENTO <= 0 OR jVALOR_MOVIMIENTO > 9999999999 OR jVALOR_MOVIMIENTO <> TRUNC(jVALOR_MOVIMIENTO) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el valor en pesos (sin centavos)');
        RETURN RETORNO;
    ELSIF jLITROS_MOVIMIENTO IS NOT NULL AND jCATEGORIA_MOVIMIENTO <> 'VENTA_LECHE' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Los litros solo van en la venta de leche');
        RETURN RETORNO;
    ELSIF jLITROS_MOVIMIENTO IS NOT NULL AND (jLITROS_MOVIMIENTO <= 0 OR jLITROS_MOVIMIENTO > 1000000) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Los litros deben ser más de 0');
        RETURN RETORNO;
    ELSIF jCATEGORIA_MOVIMIENTO IN ('OTRO_INGRESO', 'OTRO_GASTO') AND (jDESCRIPCION_MOVIMIENTO IS NULL OR TRIM(jDESCRIPCION_MOVIMIENTO) = '') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe qué fue (en «Otro» la descripción es obligatoria)');
        RETURN RETORNO;
    ELSIF jDESCRIPCION_MOVIMIENTO IS NOT NULL AND LENGTH(TRIM(jDESCRIPCION_MOVIMIENTO)) > 200 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La descripción es muy larga (máximo 200 caracteres)');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta la fecha');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO > NOW() + INTERVAL '1 day' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha no puede ser futura');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO < NOW() - INTERVAL '5 years' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha es de hace más de 5 años');
        RETURN RETORNO;
    END IF;
    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ANOTAR UN INGRESO O UN GASTO (SOLO EL DUEÑO)
CREATE OR REPLACE FUNCTION FUN_CREAR_MOVIMIENTO_JSON(
    jUUID_MOVIMIENTO TAB_MOVIMIENTOS.UUID_MOVIMIENTO%TYPE,
    jID_FINCA TAB_MOVIMIENTOS.ID_FINCA%TYPE,
    jTIPO_MOVIMIENTO TAB_MOVIMIENTOS.TIPO_MOVIMIENTO%TYPE,
    jCATEGORIA_MOVIMIENTO TAB_MOVIMIENTOS.CATEGORIA_MOVIMIENTO%TYPE,
    jVALOR_MOVIMIENTO TAB_MOVIMIENTOS.VALOR_MOVIMIENTO%TYPE,
    jLITROS_MOVIMIENTO TAB_MOVIMIENTOS.LITROS_MOVIMIENTO%TYPE,
    jDESCRIPCION_MOVIMIENTO TAB_MOVIMIENTOS.DESCRIPCION_MOVIMIENTO%TYPE,
    jFECHA_EVENTO TAB_MOVIMIENTOS.FECHA_EVENTO%TYPE,
    jID_USUARIO TAB_MOVIMIENTOS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_MOVIMIENTO INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_MOVIMIENTO INTO jID_MOVIMIENTO FROM TAB_MOVIMIENTOS WHERE UUID_MOVIMIENTO = jUUID_MOVIMIENTO;
    IF jID_MOVIMIENTO IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El movimiento ya estaba guardado',
            'DATOS', json_build_object('ID_MOVIMIENTO', jID_MOVIMIENTO, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO (SOLO EL DUEÑO) Y LOS DATOS
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_MOVIMIENTO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del movimiento');
        RETURN RETORNO;
    END IF;
    jVALIDACION := FUN_VALIDAR_MOVIMIENTO(jTIPO_MOVIMIENTO, jCATEGORIA_MOVIMIENTO, jVALOR_MOVIMIENTO, jLITROS_MOVIMIENTO, jDESCRIPCION_MOVIMIENTO, jFECHA_EVENTO);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --INSERTAR EL MOVIMIENTO
    jID_MOVIMIENTO := funcion_Retorna_ultmoid('TAB_MOVIMIENTOS', 'ID_MOVIMIENTO');
    INSERT INTO TAB_MOVIMIENTOS (ID_MOVIMIENTO, UUID_MOVIMIENTO, ID_FINCA, FECHA_EVENTO, TIPO_MOVIMIENTO, CATEGORIA_MOVIMIENTO, VALOR_MOVIMIENTO,
        LITROS_MOVIMIENTO, DESCRIPCION_MOVIMIENTO, USUARIO_CREACION)
    VALUES (jID_MOVIMIENTO, jUUID_MOVIMIENTO, jID_FINCA, jFECHA_EVENTO, jTIPO_MOVIMIENTO, jCATEGORIA_MOVIMIENTO, jVALOR_MOVIMIENTO,
        jLITROS_MOVIMIENTO, NULLIF(TRIM(jDESCRIPCION_MOVIMIENTO), ''), jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', CASE jTIPO_MOVIMIENTO WHEN 'INGRESO' THEN 'Ingreso anotado' ELSE 'Gasto anotado' END,
            'DATOS', json_build_object('ID_MOVIMIENTO', jID_MOVIMIENTO, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al anotar el movimiento');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE TODA LA PLATA DE UN PERIODO EN UNA SOLA LISTA: LOS MOVIMIENTOS ANOTADOS Y LAS VENTAS DE ANIMALES (TAB_SALIDAS)
-- LA USAN FUN_OBTENER_PLATA_JSON Y SUS PRUEBAS. NO REVISA ACCESO: QUIEN LA LLAMA YA LO HIZO
CREATE OR REPLACE FUNCTION FUN_PLATA_DEL_PERIODO(
    jID_FINCA TAB_MOVIMIENTOS.ID_FINCA%TYPE,
    jINICIO DATE,
    jFIN DATE
) RETURNS TABLE (TIPO VARCHAR, CATEGORIA VARCHAR, VALOR NUMERIC, LITROS NUMERIC, FECHA DATE) AS
$$
    SELECT TIPO_MOVIMIENTO, CATEGORIA_MOVIMIENTO, VALOR_MOVIMIENTO, LITROS_MOVIMIENTO, FECHA_EVENTO::DATE
    FROM TAB_MOVIMIENTOS
    WHERE ID_FINCA = jID_FINCA AND ESTADO_MOVIMIENTO = 'ACTIVO' AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN
    UNION ALL
    SELECT 'INGRESO', 'VENTA_ANIMAL', VALOR_SALIDA, NULL, FECHA_EVENTO::DATE
    FROM TAB_SALIDAS
    WHERE ID_FINCA = jID_FINCA AND ESTADO_SALIDA = 'ACTIVO' AND TIPO_SALIDA = 'VENTA' AND VALOR_SALIDA > 0
      AND FECHA_EVENTO::DATE BETWEEN jINICIO AND jFIN;
$$ LANGUAGE sql STABLE;



-- FUNCION QUE DEVUELVE EL RESUMEN DE LA PLATA DE UN PERIODO (SOLO EL DUEÑO). DESDE Y HASTA NULL = ESTE MES. MAXIMO 3 AÑOS
-- INGRESOS = MOVIMIENTOS DE INGRESO + VENTAS DE ANIMALES (TAB_SALIDAS VENTA CON VALOR). SALDO = INGRESOS - GASTOS
-- DATOS: {DESDE, HASTA, INGRESOS, GASTOS, SALDO, POR_CATEGORIA:[{TIPO, CATEGORIA, VALOR, CANTIDAD}],
--         POR_MES:[{MES, INGRESOS, GASTOS, SALDO}], LECHE:{LITROS, VALOR, PRECIO_LITRO}}
CREATE OR REPLACE FUNCTION FUN_OBTENER_PLATA_JSON(
    jID_FINCA TAB_MOVIMIENTOS.ID_FINCA%TYPE,
    jID_USUARIO TAB_MOVIMIENTOS.USUARIO_CREACION%TYPE,
    jDESDE DATE,
    jHASTA DATE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jINICIO DATE;
    jFIN DATE;
    jINGRESOS NUMERIC;
    jGASTOS NUMERIC;
    jLITROS NUMERIC;
    jVALOR_LECHE_CON_LITROS NUMERIC;
    jVALOR_LECHE NUMERIC;
    LISTA_CATEGORIAS JSON;
    LISTA_MESES JSON;
BEGIN
    --VALIDAR EL ACCESO (SOLO EL DUEÑO)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --EL PERIODO
    jFIN := COALESCE(jHASTA, CURRENT_DATE);
    jINICIO := COALESCE(jDESDE, date_trunc('month', jFIN)::DATE);
    IF jINICIO > jFIN THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha inicial debe ser antes de la final');
        RETURN RETORNO;
    ELSIF jFIN - jINICIO > 1100 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El periodo puede ser de máximo 3 años');
        RETURN RETORNO;
    END IF;

    --TOTALES
    SELECT COALESCE(SUM(VALOR) FILTER (WHERE TIPO = 'INGRESO'), 0), COALESCE(SUM(VALOR) FILTER (WHERE TIPO = 'GASTO'), 0)
    INTO jINGRESOS, jGASTOS FROM FUN_PLATA_DEL_PERIODO(jID_FINCA, jINICIO, jFIN);

    --POR CATEGORIA (DE MAYOR A MENOR DENTRO DE CADA TIPO)
    SELECT json_agg(json_build_object('TIPO', T.TIPO, 'CATEGORIA', T.CATEGORIA, 'VALOR', T.VALOR, 'CANTIDAD', T.CANTIDAD) ORDER BY T.TIPO DESC, T.VALOR DESC)
    INTO LISTA_CATEGORIAS
    FROM (SELECT TIPO, CATEGORIA, SUM(VALOR) AS VALOR, COUNT(*) AS CANTIDAD FROM FUN_PLATA_DEL_PERIODO(jID_FINCA, jINICIO, jFIN) GROUP BY TIPO, CATEGORIA) T;

    --POR MES (SOLO LOS MESES CON MOVIMIENTOS)
    SELECT json_agg(json_build_object('MES', T.MES, 'INGRESOS', T.INGRESOS, 'GASTOS', T.GASTOS, 'SALDO', T.INGRESOS - T.GASTOS) ORDER BY T.MES)
    INTO LISTA_MESES
    FROM (SELECT to_char(FECHA, 'YYYY-MM') AS MES,
                 COALESCE(SUM(VALOR) FILTER (WHERE TIPO = 'INGRESO'), 0) AS INGRESOS,
                 COALESCE(SUM(VALOR) FILTER (WHERE TIPO = 'GASTO'), 0) AS GASTOS
          FROM FUN_PLATA_DEL_PERIODO(jID_FINCA, jINICIO, jFIN) GROUP BY to_char(FECHA, 'YYYY-MM')) T;

    --LA LECHE VENDIDA: EL PRECIO POR LITRO SOLO CON LAS VENTAS QUE TRAEN LITROS
    SELECT COALESCE(SUM(VALOR), 0), SUM(LITROS), SUM(VALOR) FILTER (WHERE LITROS IS NOT NULL)
    INTO jVALOR_LECHE, jLITROS, jVALOR_LECHE_CON_LITROS
    FROM FUN_PLATA_DEL_PERIODO(jID_FINCA, jINICIO, jFIN) WHERE CATEGORIA = 'VENTA_LECHE';

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Plata de la finca',
        'DATOS', json_build_object(
            'DESDE', jINICIO,
            'HASTA', jFIN,
            'INGRESOS', jINGRESOS,
            'GASTOS', jGASTOS,
            'SALDO', jINGRESOS - jGASTOS,
            'POR_CATEGORIA', COALESCE(LISTA_CATEGORIAS, '[]'::JSON),
            'POR_MES', COALESCE(LISTA_MESES, '[]'::JSON),
            'LECHE', json_build_object('LITROS', jLITROS, 'VALOR', jVALOR_LECHE,
                'PRECIO_LITRO', CASE WHEN jLITROS > 0 THEN ROUND(jVALOR_LECHE_CON_LITROS / jLITROS) END)));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
