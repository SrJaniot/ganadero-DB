-- FUNCIONES DE LA TABLA TAB_LOTES -------------------------------------------------------------------------------------------------------------------
-- LOS LOTES SE PUEDEN CREAR SIN SEÑAL: EL CELULAR GENERA EL UUID Y LA FUNCION ES IDEMPOTENTE (SI EL UUID YA EXISTE, NO DUPLICA)
-- CREAR Y EDITAR: DUEÑO Y VAQUERO PUEDEN CREAR; SOLO EL DUEÑO EDITA Y ANULA



-- FUNCION PARA CREAR UN LOTE
CREATE OR REPLACE FUNCTION FUN_CREAR_LOTE_JSON(
    jUUID_LOTE TAB_LOTES.UUID_LOTE%TYPE,
    jID_FINCA TAB_LOTES.ID_FINCA%TYPE,
    jNOM_LOTE TAB_LOTES.NOM_LOTE%TYPE,
    jID_USUARIO TAB_LOTES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_LOTE INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_LOTE INTO jID_LOTE FROM TAB_LOTES WHERE UUID_LOTE = jUUID_LOTE;
    IF jID_LOTE IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El lote ya estaba guardado',
            'DATOS', json_build_object('ID_LOTE', jID_LOTE, 'UUID_LOTE', jUUID_LOTE, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO Y LOS DATOS
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO', 'VAQUERO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_LOTE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del lote');
        RETURN RETORNO;
    ELSIF jNOM_LOTE IS NULL OR TRIM(jNOM_LOTE) = '' OR LENGTH(TRIM(jNOM_LOTE)) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre del lote (máximo 60 caracteres)');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_LOTES WHERE ID_FINCA = jID_FINCA AND LOWER(NOM_LOTE) = LOWER(TRIM(jNOM_LOTE)) AND ESTADO_LOTE = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya hay un lote con ese nombre');
        RETURN RETORNO;
    END IF;

    --INSERTAR EL LOTE
    jID_LOTE := funcion_Retorna_ultmoid('TAB_LOTES', 'ID_LOTE');
    INSERT INTO TAB_LOTES (ID_LOTE, UUID_LOTE, ID_FINCA, NOM_LOTE, USUARIO_CREACION)
    VALUES (jID_LOTE, jUUID_LOTE, jID_FINCA, regexp_replace(TRIM(jNOM_LOTE), '\s+', ' ', 'g'), jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Lote creado',
            'DATOS', json_build_object('ID_LOTE', jID_LOTE, 'UUID_LOTE', jUUID_LOTE, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al crear el lote');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CAMBIAR EL NOMBRE DE UN LOTE (SOLO EL DUEÑO)
CREATE OR REPLACE FUNCTION FUN_ACTUALIZAR_LOTE_JSON(
    jUUID_LOTE TAB_LOTES.UUID_LOTE%TYPE,
    jID_FINCA TAB_LOTES.ID_FINCA%TYPE,
    jNOM_LOTE TAB_LOTES.NOM_LOTE%TYPE,
    jID_USUARIO TAB_LOTES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_LOTE INTEGER;
BEGIN
    --VALIDAR EL ACCESO Y LOS DATOS
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_LOTE := FUN_ID_LOTE_POR_UUID(jID_FINCA, jUUID_LOTE);
    IF jID_LOTE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El lote no existe en esta finca');
        RETURN RETORNO;
    ELSIF jNOM_LOTE IS NULL OR TRIM(jNOM_LOTE) = '' OR LENGTH(TRIM(jNOM_LOTE)) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre del lote (máximo 60 caracteres)');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_LOTES WHERE ID_FINCA = jID_FINCA AND LOWER(NOM_LOTE) = LOWER(TRIM(jNOM_LOTE)) AND ESTADO_LOTE = 'ACTIVO' AND ID_LOTE <> jID_LOTE) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya hay un lote con ese nombre');
        RETURN RETORNO;
    END IF;

    UPDATE TAB_LOTES
    SET NOM_LOTE = regexp_replace(TRIM(jNOM_LOTE), '\s+', ' ', 'g'),
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_LOTE = jID_LOTE;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Lote actualizado');
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al actualizar el lote');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ANULAR UN LOTE (SOLO EL DUEÑO). SUS ANIMALES QUEDAN SIN LOTE
-- DOS DML: BLOQUE BEGIN ... EXCEPTION. SI YA ESTABA ANULADO RESPONDE 200 CON YA_EXISTIA (REINTENTO SEGURO)
CREATE OR REPLACE FUNCTION FUN_ANULAR_LOTE_JSON(
    jUUID_LOTE TAB_LOTES.UUID_LOTE%TYPE,
    jID_FINCA TAB_LOTES.ID_FINCA%TYPE,
    jID_USUARIO TAB_LOTES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_LOTE INTEGER;
    jESTADO VARCHAR;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT ID_LOTE, ESTADO_LOTE INTO jID_LOTE, jESTADO FROM TAB_LOTES WHERE UUID_LOTE = jUUID_LOTE AND ID_FINCA = jID_FINCA;
    IF jID_LOTE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El lote no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El lote ya estaba anulado', 'DATOS', json_build_object('YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    BEGIN
        --LOS ANIMALES DEL LOTE QUEDAN SIN LOTE (PUEDE QUE NO HAYA NINGUNO: NO SE REVISA FOUND)
        UPDATE TAB_ANIMALES
        SET ID_LOTE = NULL,
            USUARIO_MODIFICACION = jID_USUARIO,
            FECHA_MODIFICACION = NOW()
        WHERE ID_LOTE = jID_LOTE;

        --ANULAR EL LOTE
        UPDATE TAB_LOTES
        SET ESTADO_LOTE = 'ANULADO',
            USUARIO_MODIFICACION = jID_USUARIO,
            FECHA_MODIFICACION = NOW()
        WHERE ID_LOTE = jID_LOTE;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No se pudo anular el lote';
        END IF;

        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Lote anulado: sus animales quedaron sin lote', 'DATOS', json_build_object('YA_EXISTIA', false));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LOS LOTES ACTIVOS DE LA FINCA CON CUANTOS ANIMALES ACTIVOS TIENE CADA UNO
CREATE OR REPLACE FUNCTION FUN_OBTENER_LOTES_JSON(
    jID_FINCA TAB_LOTES.ID_FINCA%TYPE,
    jID_USUARIO TAB_LOTES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    LISTA_LOTES JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT json_agg(json_build_object(
        'ID_LOTE', L.ID_LOTE,
        'UUID_LOTE', L.UUID_LOTE,
        'NOM_LOTE', L.NOM_LOTE,
        'ANIMALES_ACTIVOS', (SELECT COUNT(*) FROM TAB_ANIMALES A WHERE A.ID_LOTE = L.ID_LOTE AND A.ESTADO_ANIMAL = 'ACTIVO')
    ) ORDER BY L.NOM_LOTE) INTO LISTA_LOTES
    FROM TAB_LOTES L
    WHERE L.ID_FINCA = jID_FINCA AND L.ESTADO_LOTE = 'ACTIVO';

    IF LISTA_LOTES IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'La finca todavía no tiene lotes');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Lotes de la finca', 'DATOS', LISTA_LOTES);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
