-- FUNCION QUE CALCULA LA CATEGORIA DE UN ANIMAL (NO SE GUARDA: ASI NUNCA QUEDA DESACTUALIZADA)
-- HEMBRA: MENOS DE 12 MESES TERNERA; SIN PARTOS NOVILLA; CON AL MENOS UN PARTO VACA
-- MACHO: MENOS DE 12 MESES TERNERO; MENOS DE 30 MESES NOVILLO; DESDE 30 MESES TORO
-- jFECHA: A QUE FECHA SE CALCULA (NULL = HOY). SIRVE PARA VALIDAR EVENTOS QUE LLEGAN TARDE
CREATE OR REPLACE FUNCTION FUN_CATEGORIA_ANIMAL(
    jID_ANIMAL TAB_ANIMALES.ID_ANIMAL%TYPE,
    jFECHA DATE DEFAULT NULL
) RETURNS VARCHAR AS
$$
DECLARE
    jSEXO VARCHAR;
    jNACIMIENTO DATE;
    jMESES INTEGER;
    jPARTOS INTEGER;
BEGIN
    SELECT SEXO_ANIMAL, FECHA_NACIMIENTO INTO jSEXO, jNACIMIENTO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;
    IF jSEXO IS NULL THEN
        RETURN NULL;
    END IF;

    --EDAD EN MESES CUMPLIDOS
    jMESES := (EXTRACT(YEAR FROM age(COALESCE(jFECHA, CURRENT_DATE), jNACIMIENTO)) * 12
             + EXTRACT(MONTH FROM age(COALESCE(jFECHA, CURRENT_DATE), jNACIMIENTO)))::INTEGER;

    IF jSEXO = 'H' THEN
        SELECT COUNT(*) INTO jPARTOS FROM TAB_PARTOS
        WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_PARTO = 'ACTIVO' AND FECHA_EVENTO::DATE <= COALESCE(jFECHA, CURRENT_DATE);
        IF jPARTOS > 0 THEN
            RETURN 'VACA';
        ELSIF jMESES < 12 THEN
            RETURN 'TERNERA';
        ELSE
            RETURN 'NOVILLA';
        END IF;
    ELSE
        IF jMESES < 12 THEN
            RETURN 'TERNERO';
        ELSIF jMESES < 30 THEN
            RETURN 'NOVILLO';
        ELSE
            RETURN 'TORO';
        END IF;
    END IF;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE ARMA COMO SE NOMBRA UN ANIMAL EN LOS MENSAJES: "la vaca 23 (Lucero)", "el ternero sin chapeta"
CREATE OR REPLACE FUNCTION FUN_ETIQUETA_ANIMAL(
    jID_ANIMAL TAB_ANIMALES.ID_ANIMAL%TYPE
) RETURNS VARCHAR AS
$$
DECLARE
    jCATEGORIA VARCHAR;
    jCHAPETA VARCHAR;
    jNOM VARCHAR;
BEGIN
    SELECT CHAPETA_ANIMAL, NOM_ANIMAL INTO jCHAPETA, jNOM FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;
    jCATEGORIA := FUN_CATEGORIA_ANIMAL(jID_ANIMAL);
    IF jCATEGORIA IS NULL THEN
        RETURN 'el animal';
    END IF;

    RETURN CASE WHEN jCATEGORIA IN ('TERNERA', 'NOVILLA', 'VACA') THEN 'la ' ELSE 'el ' END
        || LOWER(jCATEGORIA)
        || COALESCE(' ' || jCHAPETA, ' sin chapeta')
        || COALESCE(' (' || jNOM || ')', '');
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE VALIDA LO COMUN A TODOS LOS EVENTOS DE UN ANIMAL
-- LA FECHA NO PUEDE SER FUTURA (UN DIA DE MARGEN POR EL RELOJ DEL CELULAR), NI ANTES DEL NACIMIENTO, NI DESPUES DE LA SALIDA DEL ANIMAL
-- SE COMPARA CON LA FECHA DE LA SALIDA Y NO CON EL ESTADO: UN EVENTO SIN SEÑAL DE ANTES DE LA VENTA PUEDE LLEGAR DESPUES Y ES VALIDO
CREATE OR REPLACE FUNCTION FUN_VALIDAR_EVENTO_ANIMAL(
    jID_ANIMAL TAB_ANIMALES.ID_ANIMAL%TYPE,
    jFECHA_EVENTO TAB_PESAJES.FECHA_EVENTO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jESTADO VARCHAR;
    jNACIMIENTO DATE;
    jFECHA_SALIDA TIMESTAMP;
    jTIPO_SALIDA VARCHAR;
BEGIN
    SELECT ESTADO_ANIMAL, FECHA_NACIMIENTO INTO jESTADO, jNACIMIENTO FROM TAB_ANIMALES WHERE ID_ANIMAL = jID_ANIMAL;
    SELECT FECHA_EVENTO, TIPO_SALIDA INTO jFECHA_SALIDA, jTIPO_SALIDA FROM TAB_SALIDAS WHERE ID_ANIMAL = jID_ANIMAL AND ESTADO_SALIDA = 'ACTIVO';

    --VALIDACION DEL ANIMAL
    IF jESTADO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El animal no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ese animal fue anulado');
        RETURN RETORNO;

    --VALIDACION DE LA FECHA DEL EVENTO
    ELSIF jFECHA_EVENTO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta la fecha');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO > NOW() + INTERVAL '1 day' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha no puede ser futura');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO::DATE < jNACIMIENTO THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha es anterior al nacimiento de ' || FUN_ETIQUETA_ANIMAL(jID_ANIMAL)
            || ' (' || to_char(jNACIMIENTO, 'DD/MM/YYYY') || ')');
        RETURN RETORNO;
    ELSIF jFECHA_SALIDA IS NOT NULL AND jFECHA_EVENTO > jFECHA_SALIDA THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', upper(left(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 1)) || substr(FUN_ETIQUETA_ANIMAL(jID_ANIMAL), 2)
            || CASE jTIPO_SALIDA WHEN 'VENTA' THEN ' se vendió' WHEN 'MUERTE' THEN ' murió' ELSE ' salió de la finca' END
            || ' el ' || to_char(jFECHA_SALIDA, 'DD/MM/YYYY') || ': no se le pueden registrar cosas después de esa fecha');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LA TABLA Y LAS COLUMNAS DE UN TIPO DE REGISTRO (LA USAN ANULAR, EL HISTORIAL Y LA SINCRONIZACION)
-- NULL SI EL TIPO NO EXISTE. ES LA LISTA BLANCA: NINGUN NOMBRE DE TABLA LLEGA DESDE AFUERA SIN PASAR POR AQUI
CREATE OR REPLACE FUNCTION FUN_TABLA_POR_TIPO(
    jTIPO VARCHAR
) RETURNS JSON AS
$$
BEGIN
    RETURN CASE UPPER(TRIM(jTIPO))
        WHEN 'LOTE'       THEN json_build_object('TABLA', 'TAB_LOTES',        'ID', 'ID_LOTE',       'UUID', 'UUID_LOTE',       'ESTADO', 'ESTADO_LOTE')
        WHEN 'ANIMAL'     THEN json_build_object('TABLA', 'TAB_ANIMALES',     'ID', 'ID_ANIMAL',     'UUID', 'UUID_ANIMAL',     'ESTADO', 'ESTADO_ANIMAL')
        WHEN 'PESAJE'     THEN json_build_object('TABLA', 'TAB_PESAJES',      'ID', 'ID_PESAJE',     'UUID', 'UUID_PESAJE',     'ESTADO', 'ESTADO_PESAJE')
        WHEN 'VACUNACION' THEN json_build_object('TABLA', 'TAB_VACUNACIONES', 'ID', 'ID_VACUNACION', 'UUID', 'UUID_VACUNACION', 'ESTADO', 'ESTADO_VACUNACION')
        WHEN 'SERVICIO'   THEN json_build_object('TABLA', 'TAB_SERVICIOS',    'ID', 'ID_SERVICIO',   'UUID', 'UUID_SERVICIO',   'ESTADO', 'ESTADO_SERVICIO')
        WHEN 'PALPACION'  THEN json_build_object('TABLA', 'TAB_PALPACIONES',  'ID', 'ID_PALPACION',  'UUID', 'UUID_PALPACION',  'ESTADO', 'ESTADO_PALPACION')
        WHEN 'PARTO'      THEN json_build_object('TABLA', 'TAB_PARTOS',       'ID', 'ID_PARTO',      'UUID', 'UUID_PARTO',      'ESTADO', 'ESTADO_PARTO')
        WHEN 'ORDENO'     THEN json_build_object('TABLA', 'TAB_ORDENOS',      'ID', 'ID_ORDENO',     'UUID', 'UUID_ORDENO',     'ESTADO', 'ESTADO_ORDENO')
        WHEN 'SALIDA'     THEN json_build_object('TABLA', 'TAB_SALIDAS',      'ID', 'ID_SALIDA',     'UUID', 'UUID_SALIDA',     'ESTADO', 'ESTADO_SALIDA')
        ELSE NULL
    END;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DICE SI YA EXISTE UN REGISTRO CON ESE UUID EN LA TABLA DE SU TIPO (FALSE SI EL TIPO NO EXISTE)
-- LA USA LA SINCRONIZACION CUANDO DOS CELULARES SUBEN EL MISMO REGISTRO AL MISMO TIEMPO Y EL SEGUNDO CHOCA CON EL UNIQUE DEL UUID
CREATE OR REPLACE FUNCTION FUN_EXISTE_UUID(
    jTIPO VARCHAR,
    jUUID UUID
) RETURNS BOOLEAN AS
$$
DECLARE
    jTABLA JSON;
    jEXISTE BOOLEAN;
BEGIN
    jTABLA := FUN_TABLA_POR_TIPO(jTIPO);
    IF jTABLA IS NULL OR jUUID IS NULL THEN
        RETURN false;
    END IF;
    EXECUTE format('SELECT EXISTS (SELECT 1 FROM %s WHERE %s = $1)', jTABLA ->> 'TABLA', jTABLA ->> 'UUID') INTO jEXISTE USING jUUID;
    RETURN jEXISTE;
END;
$$ LANGUAGE plpgsql;
