-- FUNCION QUE DEVUELVE UN VALOR NUMERICO DE TAB_CONFIGURACION (NULL SI NO EXISTE O ESTA VACIO)
CREATE OR REPLACE FUNCTION FUN_CONFIGURACION_NUMERO(
    jNOM_CONFIGURACION TAB_CONFIGURACION.NOM_CONFIGURACION%TYPE
) RETURNS NUMERIC AS
$$
DECLARE
    jVALOR VARCHAR;
BEGIN
    SELECT VALOR_CONFIGURACION INTO jVALOR FROM TAB_CONFIGURACION WHERE NOM_CONFIGURACION = jNOM_CONFIGURACION;
    IF jVALOR IS NULL OR TRIM(jVALOR) = '' OR NOT TRIM(jVALOR) ~ '^-?[0-9]+(\.[0-9]+)?$' THEN
        RETURN NULL;
    END IF;
    RETURN TRIM(jVALOR)::NUMERIC;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE REVISA QUE LA PERSONA TRABAJE EN LA FINCA Y QUE SU ROL ESTE ENTRE LOS PERMITIDOS
-- jROLES: ROLES DE LA FINCA QUE PUEDEN HACER LA ACCION (NULL = CUALQUIER ROL ACTIVO)
-- DEVUELVE 200 CON DATOS.ROL_FINCA, 404 SI LA FINCA NO EXISTE O 400 SI NO TRABAJA AHI O SU ROL NO ALCANZA
CREATE OR REPLACE FUNCTION FUN_VALIDAR_ACCESO_FINCA(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jROLES VARCHAR[]
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jROL_FINCA VARCHAR;
BEGIN
    --VALIDACION DE LA FINCA
    IF jID_FINCA IS NULL OR NOT EXISTS (SELECT 1 FROM TAB_FINCAS WHERE ID_FINCA = jID_FINCA AND ESTADO_FINCA = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'La finca no existe');
        RETURN RETORNO;
    END IF;

    --ROL DE LA PERSONA EN ESA FINCA
    SELECT ROL_FINCA INTO jROL_FINCA
    FROM TAB_FINCAS_PERSONAS
    WHERE ID_FINCA = jID_FINCA AND ID_USUARIO = jID_USUARIO AND ESTADO_FINCA_PERSONA = 'ACTIVO';

    IF jROL_FINCA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'No trabajas en esta finca');
    ELSIF jROLES IS NOT NULL AND NOT (jROL_FINCA = ANY (jROLES)) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Tu rol en esta finca no permite hacer esto. Pídeselo al dueño');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Acceso permitido', 'DATOS', json_build_object('ROL_FINCA', jROL_FINCA));
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE TRADUCE EL UUID DE UN ANIMAL A SU ID, SOLO SI ES DE ESA FINCA (NULL SI NO EXISTE O ES DE OTRA)
