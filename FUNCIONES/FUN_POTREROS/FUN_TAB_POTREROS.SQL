-- FUNCIONES DE LAS TABLAS TAB_POTREROS Y TAB_OCUPACIONES (FASE 5A: POTREROS Y ROTACION) ----------------------------------------------------------
-- TODO SE PUEDE HACER SIN SEÑAL: EL CELULAR GENERA LOS UUID Y LAS FUNCIONES SON IDEMPOTENTES (UN REINTENTO NO DUPLICA)
-- POTREROS: DUEÑO Y VAQUERO CREAN; SOLO EL DUEÑO EDITA Y ANULA (COMO LOS LOTES)
-- OCUPACIONES: DUEÑO Y VAQUERO METEN Y SACAN LOTES; SOLO EL DUEÑO ANULA (COMO LOS EVENTOS)
-- ESTADO DE UN POTRERO (FUN_ESTADO_POTRERO):
--   OCUPADO      UNO O MAS LOTES ADENTRO (OCUPACION ABIERTA)
--   DESCANSANDO  SIN LOTES; LLEVA (HOY - ULTIMA SALIDA) DIAS DE DESCANSO DE LOS DIAS_DESCANSO_POTRERO QUE NECESITA
--   LISTO        SIN LOTES Y YA DESCANSO SUS DIAS
--   SIN_USO      NUNCA SE HA REGISTRADO UN LOTE EN EL
-- EL CELULAR CALCULA LO MISMO CON SU COPIA PARA VERLO SIN SEÑAL (estadoPotrero EN potreros.service.ts); LA REGLA OFICIAL ES ESTA



-- FUNCION QUE DEVUELVE EL ID DE UN POTRERO ACTIVO DE LA FINCA POR SU UUID (NULL SI NO EXISTE O ESTA ANULADO)
CREATE OR REPLACE FUNCTION FUN_ID_POTRERO_POR_UUID(
    jID_FINCA TAB_POTREROS.ID_FINCA%TYPE,
    jUUID_POTRERO TAB_POTREROS.UUID_POTRERO%TYPE
) RETURNS INTEGER AS
$$
DECLARE
    jID_POTRERO INTEGER;
BEGIN
    SELECT ID_POTRERO INTO jID_POTRERO FROM TAB_POTREROS WHERE UUID_POTRERO = jUUID_POTRERO AND ID_FINCA = jID_FINCA AND ESTADO_POTRERO = 'ACTIVO';
    RETURN jID_POTRERO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE VALIDA LOS DATOS DE UN POTRERO (CREAR Y ACTUALIZAR). jID_POTRERO NULL AL CREAR
-- EL CONTORNO ES OPCIONAL: SI VIENE, UNA LISTA DE 3 A 200 PUNTOS [LATITUD, LONGITUD] DENTRO DE COLOMBIA (APROXIMADO)
CREATE OR REPLACE FUNCTION FUN_VALIDAR_POTRERO(
    jID_FINCA TAB_POTREROS.ID_FINCA%TYPE,
    jID_POTRERO TAB_POTREROS.ID_POTRERO%TYPE,
    jNOM_POTRERO TAB_POTREROS.NOM_POTRERO%TYPE,
    jAREA_POTRERO TAB_POTREROS.AREA_POTRERO%TYPE,
    jDIAS_DESCANSO_POTRERO TAB_POTREROS.DIAS_DESCANSO_POTRERO%TYPE,
    jCONTORNO_POTRERO TAB_POTREROS.CONTORNO_POTRERO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jPUNTOS_MALOS INTEGER;
BEGIN
    IF jNOM_POTRERO IS NULL OR TRIM(jNOM_POTRERO) = '' OR LENGTH(TRIM(jNOM_POTRERO)) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre del potrero (máximo 60 caracteres)');
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_POTREROS WHERE ID_FINCA = jID_FINCA AND LOWER(NOM_POTRERO) = LOWER(regexp_replace(TRIM(jNOM_POTRERO), '\s+', ' ', 'g'))
                  AND ESTADO_POTRERO = 'ACTIVO' AND ID_POTRERO IS DISTINCT FROM jID_POTRERO) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Ya hay un potrero con ese nombre');
        RETURN RETORNO;
    ELSIF jAREA_POTRERO IS NOT NULL AND (jAREA_POTRERO <= 0 OR jAREA_POTRERO > 10000) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El área debe estar entre 0,01 y 10.000 hectáreas');
        RETURN RETORNO;
    ELSIF jDIAS_DESCANSO_POTRERO IS NULL OR jDIAS_DESCANSO_POTRERO < 1 OR jDIAS_DESCANSO_POTRERO > 365 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Los días de descanso deben estar entre 1 y 365');
        RETURN RETORNO;
    ELSIF jCONTORNO_POTRERO IS NOT NULL AND json_typeof(jCONTORNO_POTRERO) <> 'null' THEN
        IF json_typeof(jCONTORNO_POTRERO) <> 'array' OR json_array_length(jCONTORNO_POTRERO) < 3 OR json_array_length(jCONTORNO_POTRERO) > 200 THEN
            RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El contorno del mapa debe tener entre 3 y 200 puntos');
            RETURN RETORNO;
        END IF;
        SELECT COUNT(*) INTO jPUNTOS_MALOS
        FROM json_array_elements(jCONTORNO_POTRERO) P
        WHERE json_typeof(P.value) <> 'array' OR json_array_length(P.value) <> 2
           OR json_typeof(P.value -> 0) <> 'number' OR json_typeof(P.value -> 1) <> 'number'
           OR (P.value ->> 0)::NUMERIC NOT BETWEEN -5 AND 14 OR (P.value ->> 1)::NUMERIC NOT BETWEEN -82 AND -66;
        IF jPUNTOS_MALOS > 0 THEN
            RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El contorno del mapa tiene puntos que no son válidos');
            RETURN RETORNO;
        END IF;
    END IF;
    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CREAR UN POTRERO (DUEÑO Y VAQUERO)
CREATE OR REPLACE FUNCTION FUN_CREAR_POTRERO_JSON(
    jUUID_POTRERO TAB_POTREROS.UUID_POTRERO%TYPE,
    jID_FINCA TAB_POTREROS.ID_FINCA%TYPE,
    jNOM_POTRERO TAB_POTREROS.NOM_POTRERO%TYPE,
    jAREA_POTRERO TAB_POTREROS.AREA_POTRERO%TYPE,
    jDIAS_DESCANSO_POTRERO TAB_POTREROS.DIAS_DESCANSO_POTRERO%TYPE,
    jCONTORNO_POTRERO TAB_POTREROS.CONTORNO_POTRERO%TYPE,
    jID_USUARIO TAB_POTREROS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_POTRERO INTEGER;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_POTRERO INTO jID_POTRERO FROM TAB_POTREROS WHERE UUID_POTRERO = jUUID_POTRERO;
    IF jID_POTRERO IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El potrero ya estaba guardado',
            'DATOS', json_build_object('ID_POTRERO', jID_POTRERO, 'UUID_POTRERO', jUUID_POTRERO, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO Y LOS DATOS
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO', 'VAQUERO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jUUID_POTRERO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del potrero');
        RETURN RETORNO;
    END IF;
    jVALIDACION := FUN_VALIDAR_POTRERO(jID_FINCA, NULL, jNOM_POTRERO, jAREA_POTRERO, COALESCE(jDIAS_DESCANSO_POTRERO, 30), jCONTORNO_POTRERO);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --INSERTAR EL POTRERO
    jID_POTRERO := funcion_Retorna_ultmoid('TAB_POTREROS', 'ID_POTRERO');
    INSERT INTO TAB_POTREROS (ID_POTRERO, UUID_POTRERO, ID_FINCA, NOM_POTRERO, AREA_POTRERO, DIAS_DESCANSO_POTRERO, CONTORNO_POTRERO, USUARIO_CREACION)
    VALUES (jID_POTRERO, jUUID_POTRERO, jID_FINCA, regexp_replace(TRIM(jNOM_POTRERO), '\s+', ' ', 'g'), jAREA_POTRERO,
        COALESCE(jDIAS_DESCANSO_POTRERO, 30), CASE WHEN json_typeof(jCONTORNO_POTRERO) = 'array' THEN jCONTORNO_POTRERO END, jID_USUARIO);

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Potrero creado',
            'DATOS', json_build_object('ID_POTRERO', jID_POTRERO, 'UUID_POTRERO', jUUID_POTRERO, 'YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al crear el potrero');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ACTUALIZAR UN POTRERO: NOMBRE, AREA, DIAS DE DESCANSO Y CONTORNO (SOLO EL DUEÑO). GANA EL ULTIMO QUE SINCRONIZA
CREATE OR REPLACE FUNCTION FUN_ACTUALIZAR_POTRERO_JSON(
    jUUID_POTRERO TAB_POTREROS.UUID_POTRERO%TYPE,
    jID_FINCA TAB_POTREROS.ID_FINCA%TYPE,
    jNOM_POTRERO TAB_POTREROS.NOM_POTRERO%TYPE,
    jAREA_POTRERO TAB_POTREROS.AREA_POTRERO%TYPE,
    jDIAS_DESCANSO_POTRERO TAB_POTREROS.DIAS_DESCANSO_POTRERO%TYPE,
    jCONTORNO_POTRERO TAB_POTREROS.CONTORNO_POTRERO%TYPE,
    jID_USUARIO TAB_POTREROS.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_POTRERO INTEGER;
BEGIN
    --VALIDAR EL ACCESO Y LOS DATOS
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;
    jID_POTRERO := FUN_ID_POTRERO_POR_UUID(jID_FINCA, jUUID_POTRERO);
    IF jID_POTRERO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El potrero no existe en esta finca');
        RETURN RETORNO;
    END IF;
    jVALIDACION := FUN_VALIDAR_POTRERO(jID_FINCA, jID_POTRERO, jNOM_POTRERO, jAREA_POTRERO, jDIAS_DESCANSO_POTRERO, jCONTORNO_POTRERO);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    UPDATE TAB_POTREROS
    SET NOM_POTRERO = regexp_replace(TRIM(jNOM_POTRERO), '\s+', ' ', 'g'),
        AREA_POTRERO = jAREA_POTRERO,
        DIAS_DESCANSO_POTRERO = jDIAS_DESCANSO_POTRERO,
        CONTORNO_POTRERO = CASE WHEN json_typeof(jCONTORNO_POTRERO) = 'array' THEN jCONTORNO_POTRERO END,
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_POTRERO = jID_POTRERO;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Potrero actualizado');
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al actualizar el potrero');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ANULAR UN POTRERO (SOLO EL DUEÑO). NO SE PUEDE SI TIENE UN LOTE ADENTRO: PRIMERO SE SACA
-- SI YA ESTABA ANULADO RESPONDE 200 CON YA_EXISTIA (REINTENTO SEGURO). SU HISTORIA DE OCUPACIONES SE CONSERVA
CREATE OR REPLACE FUNCTION FUN_ANULAR_POTRERO_JSON(
    jUUID_POTRERO TAB_POTREROS.UUID_POTRERO%TYPE,
    jID_FINCA TAB_POTREROS.ID_FINCA%TYPE,
    jID_USUARIO TAB_POTREROS.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_POTRERO INTEGER;
    jESTADO VARCHAR;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT ID_POTRERO, ESTADO_POTRERO INTO jID_POTRERO, jESTADO FROM TAB_POTREROS WHERE UUID_POTRERO = jUUID_POTRERO AND ID_FINCA = jID_FINCA;
    IF jID_POTRERO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El potrero no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El potrero ya estaba anulado', 'DATOS', json_build_object('YA_EXISTIA', true));
        RETURN RETORNO;
    ELSIF EXISTS (SELECT 1 FROM TAB_OCUPACIONES WHERE ID_POTRERO = jID_POTRERO AND FECHA_SALIDA_OCUPACION IS NULL AND ESTADO_OCUPACION = 'ACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El potrero tiene un lote adentro: sácalo antes de anularlo');
        RETURN RETORNO;
    END IF;

    UPDATE TAB_POTREROS
    SET ESTADO_POTRERO = 'ANULADO',
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_POTRERO = jID_POTRERO;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Potrero anulado', 'DATOS', json_build_object('YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al anular el potrero');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA METER UN LOTE A UN POTRERO (DUEÑO Y VAQUERO). SI EL LOTE ESTABA EN OTRO POTRERO, ESA OCUPACION SE CIERRA CON LA MISMA FECHA
-- REGLAS: LA FECHA NO PUEDE SER FUTURA (UN DIA DE MARGEN, COMO LOS EVENTOS) NI ANTERIOR A LA ULTIMA ENTRADA O SALIDA DEL LOTE
-- (SIN SEÑAL LOS MOVIMIENTOS LLEGAN EN ORDEN; UNO VIEJO QUE LLEGA TARDE SE RECHAZA EN VEZ DE REESCRIBIR LA HISTORIA)
-- DOS DML: BLOQUE BEGIN ... EXCEPTION
CREATE OR REPLACE FUNCTION FUN_ENTRAR_LOTE_POTRERO_JSON(
    jUUID_OCUPACION TAB_OCUPACIONES.UUID_OCUPACION%TYPE,
    jID_FINCA TAB_OCUPACIONES.ID_FINCA%TYPE,
    jUUID_LOTE TAB_LOTES.UUID_LOTE%TYPE,
    jUUID_POTRERO TAB_POTREROS.UUID_POTRERO%TYPE,
    jFECHA_EVENTO TAB_OCUPACIONES.FECHA_EVENTO%TYPE,
    jOBSERVACION TAB_OCUPACIONES.OBSERVACION_OCUPACION%TYPE,
    jID_USUARIO TAB_OCUPACIONES.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_OCUPACION INTEGER;
    jID_LOTE INTEGER;
    jID_POTRERO INTEGER;
    jID_ABIERTA INTEGER;
    jID_POTRERO_ABIERTA INTEGER;
    jULTIMA_FECHA TIMESTAMP;
    jNOM_POTRERO VARCHAR;
BEGIN
    --SI YA LLEGO ANTES (REINTENTO DE LA SINCRONIZACION), NO SE DUPLICA
    SELECT ID_OCUPACION INTO jID_OCUPACION FROM TAB_OCUPACIONES WHERE UUID_OCUPACION = jUUID_OCUPACION;
    IF jID_OCUPACION IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El movimiento ya estaba guardado',
            'DATOS', json_build_object('ID_OCUPACION', jID_OCUPACION, 'YA_EXISTIA', true));
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO', 'VAQUERO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    jID_LOTE := FUN_ID_LOTE_POR_UUID(jID_FINCA, jUUID_LOTE);
    jID_POTRERO := FUN_ID_POTRERO_POR_UUID(jID_FINCA, jUUID_POTRERO);
    SELECT ID_OCUPACION, ID_POTRERO INTO jID_ABIERTA, jID_POTRERO_ABIERTA
    FROM TAB_OCUPACIONES WHERE ID_LOTE = jID_LOTE AND FECHA_SALIDA_OCUPACION IS NULL AND ESTADO_OCUPACION = 'ACTIVO';
    SELECT MAX(GREATEST(FECHA_EVENTO, COALESCE(FECHA_SALIDA_OCUPACION, FECHA_EVENTO))) INTO jULTIMA_FECHA
    FROM TAB_OCUPACIONES WHERE ID_LOTE = jID_LOTE AND ESTADO_OCUPACION = 'ACTIVO';
    SELECT NOM_POTRERO INTO jNOM_POTRERO FROM TAB_POTREROS WHERE ID_POTRERO = jID_POTRERO;

    --VALIDAR LOS DATOS
    IF jUUID_OCUPACION IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el UUID del movimiento');
        RETURN RETORNO;
    ELSIF jID_LOTE IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El lote no existe en esta finca');
        RETURN RETORNO;
    ELSIF jID_POTRERO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'El potrero no existe en esta finca');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta la fecha');
        RETURN RETORNO;
    ELSIF jFECHA_EVENTO > NOW() + INTERVAL '1 day' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha no puede ser futura');
        RETURN RETORNO;
    ELSIF jID_POTRERO_ABIERTA = jID_POTRERO THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El lote ya está en el potrero ' || jNOM_POTRERO);
        RETURN RETORNO;
    ELSIF jULTIMA_FECHA IS NOT NULL AND jFECHA_EVENTO < jULTIMA_FECHA THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El lote ya tiene un movimiento del ' || to_char(jULTIMA_FECHA, 'DD/MM/YYYY')
            || ': la entrada no puede ser antes');
        RETURN RETORNO;
    ELSIF jOBSERVACION IS NOT NULL AND LENGTH(jOBSERVACION) > 300 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La observación es muy larga (máximo 300 caracteres)');
        RETURN RETORNO;
    END IF;

    BEGIN
        --CERRAR LA OCUPACION ANTERIOR DEL LOTE (SI ESTABA EN OTRO POTRERO)
        IF jID_ABIERTA IS NOT NULL THEN
            UPDATE TAB_OCUPACIONES
            SET FECHA_SALIDA_OCUPACION = jFECHA_EVENTO,
                USUARIO_MODIFICACION = jID_USUARIO,
                FECHA_MODIFICACION = NOW()
            WHERE ID_OCUPACION = jID_ABIERTA;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No se pudo sacar el lote del potrero anterior';
            END IF;
        END IF;

        --LA OCUPACION NUEVA
        jID_OCUPACION := funcion_Retorna_ultmoid('TAB_OCUPACIONES', 'ID_OCUPACION');
        INSERT INTO TAB_OCUPACIONES (ID_OCUPACION, UUID_OCUPACION, ID_FINCA, ID_POTRERO, ID_LOTE, FECHA_EVENTO, OBSERVACION_OCUPACION, USUARIO_CREACION)
        VALUES (jID_OCUPACION, jUUID_OCUPACION, jID_FINCA, jID_POTRERO, jID_LOTE, jFECHA_EVENTO, NULLIF(TRIM(jOBSERVACION), ''), jID_USUARIO);
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No se pudo meter el lote al potrero';
        END IF;

        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El lote entró al potrero ' || jNOM_POTRERO,
            'DATOS', json_build_object('ID_OCUPACION', jID_OCUPACION, 'YA_EXISTIA', false));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA SACAR UN LOTE DE SU POTRERO SIN METERLO A OTRO (AL CORRAL, A LA CARRETERA...) (DUEÑO Y VAQUERO)
-- jUUID_OCUPACION ES LA OCUPACION ABIERTA. SI YA ESTABA CERRADA CON ESA MISMA FECHA, RESPONDE 200 CON YA_EXISTIA (REINTENTO)
CREATE OR REPLACE FUNCTION FUN_SACAR_LOTE_POTRERO_JSON(
    jUUID_OCUPACION TAB_OCUPACIONES.UUID_OCUPACION%TYPE,
    jID_FINCA TAB_OCUPACIONES.ID_FINCA%TYPE,
    jFECHA_SALIDA TAB_OCUPACIONES.FECHA_SALIDA_OCUPACION%TYPE,
    jID_USUARIO TAB_OCUPACIONES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_OCUPACION INTEGER;
    jENTRADA TIMESTAMP;
    jSALIDA TIMESTAMP;
    jESTADO VARCHAR;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO', 'VAQUERO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT ID_OCUPACION, FECHA_EVENTO, FECHA_SALIDA_OCUPACION, ESTADO_OCUPACION INTO jID_OCUPACION, jENTRADA, jSALIDA, jESTADO
    FROM TAB_OCUPACIONES WHERE UUID_OCUPACION = jUUID_OCUPACION AND ID_FINCA = jID_FINCA;

    --VALIDAR LOS DATOS
    IF jID_OCUPACION IS NULL OR jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Ese movimiento no existe en esta finca');
        RETURN RETORNO;
    ELSIF jSALIDA IS NOT NULL AND jSALIDA = jFECHA_SALIDA THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El lote ya había salido', 'DATOS', json_build_object('YA_EXISTIA', true));
        RETURN RETORNO;
    ELSIF jSALIDA IS NOT NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El lote ya había salido de ese potrero el ' || to_char(jSALIDA, 'DD/MM/YYYY'));
        RETURN RETORNO;
    ELSIF jFECHA_SALIDA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta la fecha');
        RETURN RETORNO;
    ELSIF jFECHA_SALIDA > NOW() + INTERVAL '1 day' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La fecha no puede ser futura');
        RETURN RETORNO;
    ELSIF jFECHA_SALIDA < jENTRADA THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La salida no puede ser antes de la entrada (' || to_char(jENTRADA, 'DD/MM/YYYY') || ')');
        RETURN RETORNO;
    END IF;

    UPDATE TAB_OCUPACIONES
    SET FECHA_SALIDA_OCUPACION = jFECHA_SALIDA,
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_OCUPACION = jID_OCUPACION;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El lote salió del potrero', 'DATOS', json_build_object('YA_EXISTIA', false));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al sacar el lote');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ANULAR UN MOVIMIENTO (SOLO EL DUEÑO, PARA CORREGIR UN ERROR). SOLO EL ULTIMO MOVIMIENTO DEL LOTE
-- SI AL ENTRAR SE HABIA CERRADO LA OCUPACION ANTERIOR (SALIDA = ESTA ENTRADA), ESA SE VUELVE A ABRIR: EL LOTE QUEDA DONDE ESTABA
-- DOS DML: BLOQUE BEGIN ... EXCEPTION. SI YA ESTABA ANULADO RESPONDE 200 CON YA_EXISTIA
CREATE OR REPLACE FUNCTION FUN_ANULAR_OCUPACION_JSON(
    jUUID_OCUPACION TAB_OCUPACIONES.UUID_OCUPACION%TYPE,
    jID_FINCA TAB_OCUPACIONES.ID_FINCA%TYPE,
    jID_USUARIO TAB_OCUPACIONES.USUARIO_MODIFICACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_OCUPACION INTEGER;
    jID_LOTE INTEGER;
    jENTRADA TIMESTAMP;
    jESTADO VARCHAR;
    jID_ANTERIOR INTEGER;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT ID_OCUPACION, ID_LOTE, FECHA_EVENTO, ESTADO_OCUPACION INTO jID_OCUPACION, jID_LOTE, jENTRADA, jESTADO
    FROM TAB_OCUPACIONES WHERE UUID_OCUPACION = jUUID_OCUPACION AND ID_FINCA = jID_FINCA;
    IF jID_OCUPACION IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Ese movimiento no existe en esta finca');
        RETURN RETORNO;
    ELSIF jESTADO = 'ANULADO' THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'El movimiento ya estaba anulado', 'DATOS', json_build_object('YA_EXISTIA', true));
        RETURN RETORNO;
    --CON LA MISMA HORA (DOS MOVIMIENTOS EN EL MISMO MINUTO) GANA EL QUE SE GUARDO DESPUES (ID MAS ALTO)
    ELSIF EXISTS (SELECT 1 FROM TAB_OCUPACIONES WHERE ID_LOTE = jID_LOTE AND ESTADO_OCUPACION = 'ACTIVO' AND ID_OCUPACION <> jID_OCUPACION
                  AND (FECHA_EVENTO > jENTRADA OR (FECHA_EVENTO = jENTRADA AND ID_OCUPACION > jID_OCUPACION))) THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Solo se puede anular el último movimiento del lote');
        RETURN RETORNO;
    END IF;

    --LA OCUPACION QUE ESTA ENTRADA CERRO (SI LA HUBO)
    SELECT ID_OCUPACION INTO jID_ANTERIOR FROM TAB_OCUPACIONES
    WHERE ID_LOTE = jID_LOTE AND ESTADO_OCUPACION = 'ACTIVO' AND ID_OCUPACION < jID_OCUPACION AND FECHA_SALIDA_OCUPACION = jENTRADA
    ORDER BY FECHA_EVENTO DESC, ID_OCUPACION DESC LIMIT 1;

    BEGIN
        UPDATE TAB_OCUPACIONES
        SET ESTADO_OCUPACION = 'ANULADO',
            USUARIO_MODIFICACION = jID_USUARIO,
            FECHA_MODIFICACION = NOW()
        WHERE ID_OCUPACION = jID_OCUPACION;
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No se pudo anular el movimiento';
        END IF;

        IF jID_ANTERIOR IS NOT NULL THEN
            UPDATE TAB_OCUPACIONES
            SET FECHA_SALIDA_OCUPACION = NULL,
                USUARIO_MODIFICACION = jID_USUARIO,
                FECHA_MODIFICACION = NOW()
            WHERE ID_OCUPACION = jID_ANTERIOR;
            IF NOT FOUND THEN
                RAISE EXCEPTION 'No se pudo devolver el lote al potrero anterior';
            END IF;
        END IF;

        RETORNO := json_build_object('CODIGO', 200,
            'MENSAJE', CASE WHEN jID_ANTERIOR IS NULL THEN 'Movimiento anulado' ELSE 'Movimiento anulado: el lote volvió al potrero anterior' END,
            'DATOS', json_build_object('YA_EXISTIA', false));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DICE EN QUE ESTADO ESTA UN POTRERO HOY (VER LA TABLA DE ESTADOS ARRIBA)
-- DEVUELVE {ESTADO, DIAS_OCUPADO, DIAS_DESCANSO, LOTES:[{UUID_LOTE, NOM_LOTE, FECHA_ENTRADA, DIAS}]}
CREATE OR REPLACE FUNCTION FUN_ESTADO_POTRERO(
    jID_POTRERO TAB_POTREROS.ID_POTRERO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    LISTA_LOTES JSON;
    jENTRADA_MAS_VIEJA TIMESTAMP;
    jULTIMA_SALIDA TIMESTAMP;
    jDIAS_NECESARIOS INTEGER;
    jDIAS INTEGER;
BEGIN
    SELECT DIAS_DESCANSO_POTRERO INTO jDIAS_NECESARIOS FROM TAB_POTREROS WHERE ID_POTRERO = jID_POTRERO;

    --LOTES ADENTRO
    SELECT json_agg(json_build_object('UUID_LOTE', L.UUID_LOTE, 'NOM_LOTE', L.NOM_LOTE, 'FECHA_ENTRADA', O.FECHA_EVENTO,
        'DIAS', CURRENT_DATE - O.FECHA_EVENTO::DATE) ORDER BY O.FECHA_EVENTO), MIN(O.FECHA_EVENTO)
    INTO LISTA_LOTES, jENTRADA_MAS_VIEJA
    FROM TAB_OCUPACIONES O JOIN TAB_LOTES L ON L.ID_LOTE = O.ID_LOTE
    WHERE O.ID_POTRERO = jID_POTRERO AND O.FECHA_SALIDA_OCUPACION IS NULL AND O.ESTADO_OCUPACION = 'ACTIVO';

    IF LISTA_LOTES IS NOT NULL THEN
        RETORNO := json_build_object('ESTADO', 'OCUPADO', 'DIAS_OCUPADO', CURRENT_DATE - jENTRADA_MAS_VIEJA::DATE, 'DIAS_DESCANSO', NULL,
            'DIAS_DESCANSO_POTRERO', jDIAS_NECESARIOS, 'LOTES', LISTA_LOTES);
        RETURN RETORNO;
    END IF;

    --SIN LOTES: DESDE CUANDO DESCANSA
    SELECT MAX(FECHA_SALIDA_OCUPACION) INTO jULTIMA_SALIDA
    FROM TAB_OCUPACIONES WHERE ID_POTRERO = jID_POTRERO AND ESTADO_OCUPACION = 'ACTIVO';
    IF jULTIMA_SALIDA IS NULL THEN
        RETORNO := json_build_object('ESTADO', 'SIN_USO', 'DIAS_OCUPADO', NULL, 'DIAS_DESCANSO', NULL,
            'DIAS_DESCANSO_POTRERO', jDIAS_NECESARIOS, 'LOTES', '[]'::JSON);
        RETURN RETORNO;
    END IF;
    jDIAS := CURRENT_DATE - jULTIMA_SALIDA::DATE;
    RETORNO := json_build_object('ESTADO', CASE WHEN jDIAS >= jDIAS_NECESARIOS THEN 'LISTO' ELSE 'DESCANSANDO' END,
        'DIAS_OCUPADO', NULL, 'DIAS_DESCANSO', jDIAS, 'DIAS_DESCANSO_POTRERO', jDIAS_NECESARIOS, 'LOTES', '[]'::JSON);
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LOS POTREROS ACTIVOS DE LA FINCA CON SU ESTADO DE HOY (CUALQUIER ROL DE LA FINCA)
CREATE OR REPLACE FUNCTION FUN_OBTENER_POTREROS_JSON(
    jID_FINCA TAB_POTREROS.ID_FINCA%TYPE,
    jID_USUARIO TAB_POTREROS.USUARIO_CREACION%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    LISTA_POTREROS JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT json_agg(json_build_object(
        'UUID_POTRERO', P.UUID_POTRERO,
        'NOM_POTRERO', P.NOM_POTRERO,
        'AREA_POTRERO', P.AREA_POTRERO,
        'DIAS_DESCANSO_POTRERO', P.DIAS_DESCANSO_POTRERO,
        'TIENE_CONTORNO', P.CONTORNO_POTRERO IS NOT NULL,
        'ESTADO_HOY', FUN_ESTADO_POTRERO(P.ID_POTRERO)
    ) ORDER BY P.NOM_POTRERO) INTO LISTA_POTREROS
    FROM TAB_POTREROS P
    WHERE P.ID_FINCA = jID_FINCA AND P.ESTADO_POTRERO = 'ACTIVO';

    IF LISTA_POTREROS IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'La finca todavía no tiene potreros');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Potreros de la finca', 'DATOS', LISTA_POTREROS);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
