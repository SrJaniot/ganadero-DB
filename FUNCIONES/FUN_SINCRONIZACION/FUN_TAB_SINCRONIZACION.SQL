-- FUNCIONES DEL MOTOR DE SINCRONIZACION -------------------------------------------------------------------------------------------------------------
-- DOS PASOS, SIEMPRE EN ESTE ORDEN: PRIMERO SE SUBE LO DEL CELULAR (FUN_SINCRONIZAR_REGISTROS_JSON) Y DESPUES SE BAJA LO DE LOS DEMAS
-- (FUN_OBTENER_CAMBIOS_JSON). CONTRATO COMPLETO EN PLAN_GANADERO.md, SECCION 4
--
-- CADA REGISTRO DE LA BANDEJA DE SALIDA DEL CELULAR:
--   { "orden": 57, "uuid": "8f3c...", "tipo": "PESAJE", "operacion": "CREAR", "datos": { "uuid_animal": "a91d...", "peso_kg": 412, ... } }
-- tipo: LOTE, ANIMAL, PESAJE, VACUNACION, SERVICIO, PALPACION, PARTO, ORDENO, SALIDA
-- operacion: CREAR (TODOS), EDITAR (LOTE Y ANIMAL), ANULAR (TODOS)
-- LAS CLAVES DE "datos" SON LOS NOMBRES DE LAS COLUMNAS EN MINUSCULAS (VER CADA RAMA DE FUN_SINCRONIZAR_REGISTROS_JSON)



-- FUNCION QUE SUBE LA BANDEJA DE SALIDA DEL CELULAR (LOTES DE HASTA LOTE_MAXIMO_SINCRONIZACION REGISTROS)
-- RECORRE LOS REGISTROS EN EL ORDEN EN QUE LLEGAN Y LLAMA A LA MISMA FUNCION QUE SE USA EN LINEA (MISMAS REGLAS)
-- CADA REGISTRO VA EN SU PROPIO BEGIN ... EXCEPTION: SI UNO FALLA, SOLO ESE SE RECHAZA Y LOS DEMAS SE GUARDAN.
-- ES UNA EXCEPCION JUSTIFICADA AL "TODO O NADA": UN PESAJE MALO NO DEBE FRENAR LOS OTROS 49. DENTRO DE CADA REGISTRO SE MANTIENE
-- EL ROLLBACK REAL (UN PARTO Y SU CRIA ENTRAN JUNTOS O NINGUNO)
-- ESTADO DE CADA REGISTRO: OK (GUARDADO), YA_EXISTIA (YA HABIA LLEGADO: EL CELULAR LO BORRA DE LA BANDEJA), RECHAZADO (CON MENSAJE)
CREATE OR REPLACE FUNCTION FUN_SINCRONIZAR_REGISTROS_JSON(
    jID_FINCA TAB_SINCRONIZACIONES.ID_FINCA%TYPE,
    jID_USUARIO TAB_SINCRONIZACIONES.ID_USUARIO%TYPE,
    jREGISTROS JSON
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jREGISTRO JSON;
    jDATOS JSON;
    jTIPO VARCHAR;
    jOPERACION VARCHAR;
    jUUID UUID;
    jRESULTADO JSON;
    jESTADO VARCHAR;
    jMAXIMO INTEGER;
    jRECIBIDOS INTEGER;
    jGUARDADOS INTEGER := 0;
    jOMITIDOS INTEGER := 0;
    jRECHAZADOS INTEGER := 0;
    LISTA_RESULTADOS JSON[] := ARRAY[]::JSON[];
    LISTA_RECHAZADOS JSON[] := ARRAY[]::JSON[];
    jID_SINCRONIZACION INTEGER;
BEGIN
    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA; CADA FUNCION REVISA DESPUES SU PROPIO PERMISO)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --VALIDAR EL LOTE
    jMAXIMO := COALESCE(FUN_CONFIGURACION_NUMERO('LOTE_MAXIMO_SINCRONIZACION'), 50)::INTEGER;
    IF jREGISTROS IS NULL OR json_typeof(jREGISTROS) <> 'array' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Los registros deben llegar en una lista');
        RETURN RETORNO;
    END IF;
    jRECIBIDOS := json_array_length(jREGISTROS);
    IF jRECIBIDOS = 0 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'No hay registros para subir');
        RETURN RETORNO;
    ELSIF jRECIBIDOS > jMAXIMO THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Máximo ' || jMAXIMO || ' registros por envío');
        RETURN RETORNO;
    END IF;

    --RECORRER LOS REGISTROS EN EL ORDEN EN QUE LLEGARON (UN ANIMAL CREADO SIN SEÑAL LLEGA ANTES QUE SUS EVENTOS)
    FOR jREGISTRO IN SELECT R.value FROM json_array_elements(jREGISTROS) WITH ORDINALITY AS R(value, posicion) ORDER BY R.posicion LOOP
        jTIPO := UPPER(TRIM(jREGISTRO ->> 'tipo'));
        jOPERACION := UPPER(TRIM(COALESCE(jREGISTRO ->> 'operacion', 'CREAR')));
        jDATOS := COALESCE(jREGISTRO -> 'datos', '{}'::JSON);
        jUUID := NULL;

        BEGIN
            jUUID := NULLIF(jREGISTRO ->> 'uuid', '')::UUID;
            IF jUUID IS NULL THEN
                jRESULTADO := json_build_object('CODIGO', 400, 'MENSAJE', 'El registro no trae UUID');

            --CREAR
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'LOTE' THEN
                jRESULTADO := FUN_CREAR_LOTE_JSON(jUUID, jID_FINCA, jDATOS ->> 'nom_lote', jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'ANIMAL' THEN
                jRESULTADO := FUN_CREAR_ANIMAL_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_lote', '')::UUID, (jDATOS ->> 'id_raza')::INTEGER,
                    jDATOS ->> 'chapeta_animal', jDATOS ->> 'nom_animal', jDATOS ->> 'sexo_animal', (jDATOS ->> 'fecha_nacimiento')::DATE,
                    jDATOS ->> 'fecha_nacimiento_estimada', NULLIF(jDATOS ->> 'uuid_madre', '')::UUID, NULLIF(jDATOS ->> 'uuid_padre', '')::UUID,
                    jDATOS ->> 'padre_externo', jDATOS ->> 'origen_animal', (jDATOS ->> 'fecha_ingreso_animal')::DATE, jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'PESAJE' THEN
                jRESULTADO := FUN_CREAR_PESAJE_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_animal', '')::UUID, (jDATOS ->> 'peso_kg')::NUMERIC,
                    COALESCE(jDATOS ->> 'estimado_cinta', 'NO'), (jDATOS ->> 'perimetro_cm')::NUMERIC, (jDATOS ->> 'fecha_evento')::TIMESTAMP,
                    jDATOS ->> 'observacion', jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'VACUNACION' THEN
                jRESULTADO := FUN_CREAR_VACUNACION_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_animal', '')::UUID, (jDATOS ->> 'id_vacuna')::INTEGER,
                    jDATOS ->> 'dosis_vacunacion', (jDATOS ->> 'fecha_evento')::TIMESTAMP, jDATOS ->> 'observacion', jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'SERVICIO' THEN
                jRESULTADO := FUN_CREAR_SERVICIO_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_animal', '')::UUID, jDATOS ->> 'tipo_servicio',
                    NULLIF(jDATOS ->> 'uuid_toro', '')::UUID, jDATOS ->> 'toro_externo', (jDATOS ->> 'fecha_evento')::TIMESTAMP, jDATOS ->> 'observacion', jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'PALPACION' THEN
                jRESULTADO := FUN_CREAR_PALPACION_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_animal', '')::UUID, jDATOS ->> 'resultado_palpacion',
                    (jDATOS ->> 'meses_gestacion')::INTEGER, (jDATOS ->> 'fecha_evento')::TIMESTAMP, jDATOS ->> 'observacion', jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'PARTO' THEN
                jRESULTADO := FUN_CREAR_PARTO_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_animal', '')::UUID, jDATOS ->> 'tipo_parto', jDATOS ->> 'cria_viva',
                    NULLIF(jDATOS ->> 'uuid_cria', '')::UUID, jDATOS ->> 'sexo_cria', jDATOS ->> 'chapeta_cria', jDATOS ->> 'nom_cria',
                    (jDATOS ->> 'peso_cria_kg')::NUMERIC, (jDATOS ->> 'fecha_evento')::TIMESTAMP, jDATOS ->> 'observacion', jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'ORDENO' THEN
                jRESULTADO := FUN_CREAR_ORDENO_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_animal', '')::UUID, jDATOS ->> 'jornada_ordeno',
                    (jDATOS ->> 'litros_ordeno')::NUMERIC, (jDATOS ->> 'fecha_evento')::TIMESTAMP, jDATOS ->> 'observacion', jID_USUARIO);
            ELSIF jOPERACION = 'CREAR' AND jTIPO = 'SALIDA' THEN
                jRESULTADO := FUN_CREAR_SALIDA_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_animal', '')::UUID, jDATOS ->> 'tipo_salida',
                    (jDATOS ->> 'valor_salida')::NUMERIC, (jDATOS ->> 'peso_salida_kg')::NUMERIC, jDATOS ->> 'causa_salida',
                    (jDATOS ->> 'fecha_evento')::TIMESTAMP, jDATOS ->> 'observacion', jID_USUARIO);

            --EDITAR (GANA EL ULTIMO QUE SINCRONIZA)
            ELSIF jOPERACION = 'EDITAR' AND jTIPO = 'LOTE' THEN
                jRESULTADO := FUN_ACTUALIZAR_LOTE_JSON(jUUID, jID_FINCA, jDATOS ->> 'nom_lote', jID_USUARIO);
            ELSIF jOPERACION = 'EDITAR' AND jTIPO = 'ANIMAL' THEN
                jRESULTADO := FUN_ACTUALIZAR_ANIMAL_JSON(jUUID, jID_FINCA, NULLIF(jDATOS ->> 'uuid_lote', '')::UUID, (jDATOS ->> 'id_raza')::INTEGER,
                    jDATOS ->> 'chapeta_animal', jDATOS ->> 'nom_animal', jDATOS ->> 'sexo_animal', (jDATOS ->> 'fecha_nacimiento')::DATE,
                    jDATOS ->> 'fecha_nacimiento_estimada', NULLIF(jDATOS ->> 'uuid_madre', '')::UUID, NULLIF(jDATOS ->> 'uuid_padre', '')::UUID,
                    jDATOS ->> 'padre_externo', jDATOS ->> 'origen_animal', (jDATOS ->> 'fecha_ingreso_animal')::DATE, jID_USUARIO);

            --ANULAR
            ELSIF jOPERACION = 'ANULAR' AND jTIPO = 'LOTE' THEN
                jRESULTADO := FUN_ANULAR_LOTE_JSON(jUUID, jID_FINCA, jID_USUARIO);
            ELSIF jOPERACION = 'ANULAR' AND jTIPO = 'ANIMAL' THEN
                jRESULTADO := FUN_ANULAR_ANIMAL_JSON(jUUID, jID_FINCA, jID_USUARIO);
            ELSIF jOPERACION = 'ANULAR' AND FUN_TABLA_POR_TIPO(jTIPO) IS NOT NULL THEN
                jRESULTADO := FUN_ANULAR_EVENTO_JSON(jTIPO, jUUID, jID_FINCA, jID_USUARIO);

            ELSE
                jRESULTADO := json_build_object('CODIGO', 400, 'MENSAJE', 'Tipo u operación no soportada: ' || COALESCE(jTIPO, '?') || ' ' || jOPERACION);
            END IF;

            --SI LA FUNCION NO GUARDO, SE DESHACE LO QUE HUBIERA HECHO ESTE REGISTRO (SOLO ESTE)
            IF (jRESULTADO ->> 'CODIGO')::INTEGER != 200 THEN
                RAISE EXCEPTION USING ERRCODE = 'P0001', MESSAGE = jRESULTADO ->> 'MENSAJE';
            END IF;
        EXCEPTION
            WHEN unique_violation THEN
                --DOS CELULARES SUBIERON LO MISMO A LA VEZ: EL OTRO YA LO GUARDO (YA_EXISTIA). SI EL CHOQUE FUE CON OTRA REGLA UNICA
                --(POR EJEMPLO LA MISMA JORNADA DE ORDEÑO DESDE DOS CELULARES), SE RECHAZA CON UN MENSAJE CLARO
                IF FUN_EXISTE_UUID(jTIPO, jUUID) THEN
                    jRESULTADO := json_build_object('CODIGO', 200, 'MENSAJE', 'Ya estaba guardado', 'DATOS', json_build_object('YA_EXISTIA', true));
                ELSE
                    jRESULTADO := json_build_object('CODIGO', 400, 'MENSAJE', 'Otro celular guardó lo mismo al mismo tiempo. Sincroniza de nuevo para verlo');
                END IF;
            WHEN OTHERS THEN
                --DATOS MAL FORMADOS (UUID O FECHA INVALIDA) O RECHAZO DE LA FUNCION
                jRESULTADO := json_build_object('CODIGO', 400, 'MENSAJE', SQLERRM);
        END;

        --CLASIFICAR EL RESULTADO
        IF (jRESULTADO ->> 'CODIGO')::INTEGER = 200 AND COALESCE((jRESULTADO -> 'DATOS' ->> 'YA_EXISTIA')::BOOLEAN, false) THEN
            jESTADO := 'YA_EXISTIA';
            jOMITIDOS := jOMITIDOS + 1;
        ELSIF (jRESULTADO ->> 'CODIGO')::INTEGER = 200 THEN
            jESTADO := 'OK';
            jGUARDADOS := jGUARDADOS + 1;
        ELSE
            jESTADO := 'RECHAZADO';
            jRECHAZADOS := jRECHAZADOS + 1;
            LISTA_RECHAZADOS := LISTA_RECHAZADOS || json_build_object('UUID', jREGISTRO ->> 'uuid', 'TIPO', jTIPO, 'OPERACION', jOPERACION, 'MENSAJE', jRESULTADO ->> 'MENSAJE');
        END IF;

        LISTA_RESULTADOS := LISTA_RESULTADOS || json_build_object(
            'UUID', jREGISTRO ->> 'uuid',
            'ORDEN', jREGISTRO -> 'orden',
            'ESTADO', jESTADO,
            'MENSAJE', CASE WHEN jESTADO = 'RECHAZADO' THEN jRESULTADO ->> 'MENSAJE' END);
    END LOOP;

    --DEJAR CONSTANCIA DE LA SINCRONIZACION
    jID_SINCRONIZACION := funcion_Retorna_ultmoid('TAB_SINCRONIZACIONES', 'ID_SINCRONIZACION');
    INSERT INTO TAB_SINCRONIZACIONES (ID_SINCRONIZACION, ID_FINCA, ID_USUARIO, RECIBIDOS_SINCRONIZACION, GUARDADOS_SINCRONIZACION,
        OMITIDOS_SINCRONIZACION, RECHAZADOS_SINCRONIZACION, DETALLE_SINCRONIZACION)
    VALUES (jID_SINCRONIZACION, jID_FINCA, jID_USUARIO, jRECIBIDOS, jGUARDADOS, jOMITIDOS, jRECHAZADOS,
        CASE WHEN jRECHAZADOS > 0 THEN array_to_json(LISTA_RECHAZADOS) END);

    RETORNO := json_build_object('CODIGO', 200,
        'MENSAJE', jGUARDADOS || CASE WHEN jGUARDADOS = 1 THEN ' subido' ELSE ' subidos' END
            || ', ' || jOMITIDOS || CASE WHEN jOMITIDOS = 1 THEN ' ya existía' ELSE ' ya existían' END
            || ', ' || jRECHAZADOS || CASE WHEN jRECHAZADOS = 1 THEN ' rechazado' ELSE ' rechazados' END,
        'DATOS', array_to_json(LISTA_RESULTADOS));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE BAJA AL CELULAR TODO LO DE LA FINCA QUE CAMBIO DESDE SU MARCA (NUEVO, EDITADO O ANULADO) Y LA MARCA NUEVA
-- jDESDE: LA MARCA QUE GUARDO EL CELULAR (HORA DEL SERVIDOR DE SU ULTIMA BAJADA). NULL = PRIMERA VEZ: BAJA LA FINCA COMPLETA SIN LO ANULADO
-- SE PIDEN MARGEN_SINCRONIZACION_SEGUNDOS ANTES DE LA MARCA PARA NO PERDER LO QUE SE GUARDABA EN ESE MOMENTO; LO REPETIDO NO HACE DAÑO
-- PORQUE EL CELULAR ACTUALIZA POR UUID. LA MARCA NUEVA ES NOW() DEL SERVIDOR, NUNCA LA HORA DEL CELULAR
-- LOS CATALOGOS (RAZAS, VACUNAS, CICLOS DEL ICA) SON GLOBALES Y BAJAN CON LA MISMA MARCA
CREATE OR REPLACE FUNCTION FUN_OBTENER_CAMBIOS_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jDESDE TIMESTAMP WITHOUT TIME ZONE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jMARCA TIMESTAMP WITHOUT TIME ZONE;
    jDESDE_REAL TIMESTAMP WITHOUT TIME ZONE;
    jCOMPLETO BOOLEAN;
    jFINCA JSON;
    LISTA_PERSONAS JSON;
    LISTA_LOTES JSON;
    LISTA_ANIMALES JSON;
    LISTA_PESAJES JSON;
    LISTA_VACUNACIONES JSON;
    LISTA_SERVICIOS JSON;
    LISTA_PALPACIONES JSON;
    LISTA_PARTOS JSON;
    LISTA_ORDENOS JSON;
    LISTA_SALIDAS JSON;
    LISTA_RAZAS JSON;
    LISTA_VACUNAS JSON;
    LISTA_CICLOS JSON;
BEGIN
    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jDESDE IS NOT NULL AND jDESDE > NOW() + INTERVAL '1 minute' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La marca de sincronización es del futuro: se bajará todo de nuevo');
        RETURN RETORNO;
    END IF;

    --MARCA NUEVA Y DESDE CUANDO SE BUSCA
    jMARCA := NOW();
    jCOMPLETO := jDESDE IS NULL;
    jDESDE_REAL := jDESDE - make_interval(secs => COALESCE(FUN_CONFIGURACION_NUMERO('MARGEN_SINCRONIZACION_SEGUNDOS'), 5));

    --LA FINCA Y SUS PERSONAS
    SELECT json_build_object('ID_FINCA', ID_FINCA, 'NOM_FINCA', NOM_FINCA, 'MUNICIPIO_FINCA', MUNICIPIO_FINCA, 'VEREDA_FINCA', VEREDA_FINCA,
        'REGISTRO_ICA_FINCA', REGISTRO_ICA_FINCA, 'HIERRO_FINCA', HIERRO_FINCA) INTO jFINCA
    FROM TAB_FINCAS WHERE ID_FINCA = jID_FINCA AND (jCOMPLETO OR FECHA_MODIFICACION > jDESDE_REAL);

    SELECT json_agg(json_build_object('ID_USUARIO', ID_USUARIO, 'NOM_PERSONA', NOM_PERSONA, 'ROL_FINCA', ROL_FINCA, 'ESTADO_FINCA_PERSONA', ESTADO_FINCA_PERSONA))
    INTO LISTA_PERSONAS
    FROM TAB_FINCAS_PERSONAS WHERE ID_FINCA = jID_FINCA AND (jCOMPLETO OR FECHA_MODIFICACION > jDESDE_REAL);

    --LOTES Y ANIMALES
    SELECT json_agg(json_build_object('ID_LOTE', ID_LOTE, 'UUID_LOTE', UUID_LOTE, 'NOM_LOTE', NOM_LOTE, 'ESTADO_LOTE', ESTADO_LOTE)) INTO LISTA_LOTES
    FROM TAB_LOTES WHERE ID_FINCA = jID_FINCA
      AND ((jCOMPLETO AND ESTADO_LOTE <> 'ANULADO') OR (NOT jCOMPLETO AND FECHA_MODIFICACION > jDESDE_REAL));

    SELECT json_agg(FUN_DATOS_ANIMAL(ID_ANIMAL) ORDER BY ID_ANIMAL) INTO LISTA_ANIMALES
    FROM TAB_ANIMALES WHERE ID_FINCA = jID_FINCA
      AND ((jCOMPLETO AND ESTADO_ANIMAL <> 'ANULADO') OR (NOT jCOMPLETO AND FECHA_MODIFICACION > jDESDE_REAL));

    --EVENTOS (CON EL UUID DEL ANIMAL, QUE ES COMO LOS GUARDA EL CELULAR)
    SELECT json_agg(json_build_object('UUID_PESAJE', E.UUID_PESAJE, 'UUID_ANIMAL', A.UUID_ANIMAL, 'FECHA_EVENTO', E.FECHA_EVENTO, 'PESO_KG', E.PESO_KG,
        'ESTIMADO_CINTA', E.ESTIMADO_CINTA, 'PERIMETRO_CM', E.PERIMETRO_CM, 'OBSERVACION_PESAJE', E.OBSERVACION_PESAJE, 'ESTADO_PESAJE', E.ESTADO_PESAJE,
        'USUARIO_CREACION', E.USUARIO_CREACION)) INTO LISTA_PESAJES
    FROM TAB_PESAJES E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_PESAJE = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

    SELECT json_agg(json_build_object('UUID_VACUNACION', E.UUID_VACUNACION, 'UUID_ANIMAL', A.UUID_ANIMAL, 'FECHA_EVENTO', E.FECHA_EVENTO, 'ID_VACUNA', E.ID_VACUNA,
        'DOSIS_VACUNACION', E.DOSIS_VACUNACION, 'FECHA_PROXIMA_DOSIS', E.FECHA_PROXIMA_DOSIS, 'FECHA_FIN_RETIRO', E.FECHA_FIN_RETIRO,
        'OBSERVACION_VACUNACION', E.OBSERVACION_VACUNACION, 'ESTADO_VACUNACION', E.ESTADO_VACUNACION, 'USUARIO_CREACION', E.USUARIO_CREACION)) INTO LISTA_VACUNACIONES
    FROM TAB_VACUNACIONES E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_VACUNACION = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

    SELECT json_agg(json_build_object('UUID_SERVICIO', E.UUID_SERVICIO, 'UUID_ANIMAL', A.UUID_ANIMAL, 'FECHA_EVENTO', E.FECHA_EVENTO, 'TIPO_SERVICIO', E.TIPO_SERVICIO,
        'UUID_TORO', T.UUID_ANIMAL, 'TORO_EXTERNO', E.TORO_EXTERNO, 'OBSERVACION_SERVICIO', E.OBSERVACION_SERVICIO, 'ESTADO_SERVICIO', E.ESTADO_SERVICIO,
        'USUARIO_CREACION', E.USUARIO_CREACION)) INTO LISTA_SERVICIOS
    FROM TAB_SERVICIOS E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL LEFT JOIN TAB_ANIMALES T ON T.ID_ANIMAL = E.ID_TORO
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_SERVICIO = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

    SELECT json_agg(json_build_object('UUID_PALPACION', E.UUID_PALPACION, 'UUID_ANIMAL', A.UUID_ANIMAL, 'FECHA_EVENTO', E.FECHA_EVENTO,
        'RESULTADO_PALPACION', E.RESULTADO_PALPACION, 'MESES_GESTACION', E.MESES_GESTACION, 'OBSERVACION_PALPACION', E.OBSERVACION_PALPACION,
        'ESTADO_PALPACION', E.ESTADO_PALPACION, 'USUARIO_CREACION', E.USUARIO_CREACION)) INTO LISTA_PALPACIONES
    FROM TAB_PALPACIONES E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_PALPACION = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

    SELECT json_agg(json_build_object('UUID_PARTO', E.UUID_PARTO, 'UUID_ANIMAL', A.UUID_ANIMAL, 'FECHA_EVENTO', E.FECHA_EVENTO, 'TIPO_PARTO', E.TIPO_PARTO,
        'CRIA_VIVA', E.CRIA_VIVA, 'SEXO_CRIA', E.SEXO_CRIA, 'UUID_CRIA', C.UUID_ANIMAL, 'OBSERVACION_PARTO', E.OBSERVACION_PARTO, 'ESTADO_PARTO', E.ESTADO_PARTO,
        'USUARIO_CREACION', E.USUARIO_CREACION)) INTO LISTA_PARTOS
    FROM TAB_PARTOS E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL LEFT JOIN TAB_ANIMALES C ON C.ID_ANIMAL = E.ID_CRIA
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_PARTO = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

    SELECT json_agg(json_build_object('UUID_ORDENO', E.UUID_ORDENO, 'UUID_ANIMAL', A.UUID_ANIMAL, 'FECHA_EVENTO', E.FECHA_EVENTO, 'JORNADA_ORDENO', E.JORNADA_ORDENO,
        'LITROS_ORDENO', E.LITROS_ORDENO, 'OBSERVACION_ORDENO', E.OBSERVACION_ORDENO, 'ESTADO_ORDENO', E.ESTADO_ORDENO, 'USUARIO_CREACION', E.USUARIO_CREACION))
    INTO LISTA_ORDENOS
    FROM TAB_ORDENOS E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_ORDENO = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

    SELECT json_agg(json_build_object('UUID_SALIDA', E.UUID_SALIDA, 'UUID_ANIMAL', A.UUID_ANIMAL, 'FECHA_EVENTO', E.FECHA_EVENTO, 'TIPO_SALIDA', E.TIPO_SALIDA,
        'VALOR_SALIDA', E.VALOR_SALIDA, 'PESO_SALIDA_KG', E.PESO_SALIDA_KG, 'CAUSA_SALIDA', E.CAUSA_SALIDA, 'OBSERVACION_SALIDA', E.OBSERVACION_SALIDA,
        'ESTADO_SALIDA', E.ESTADO_SALIDA, 'USUARIO_CREACION', E.USUARIO_CREACION)) INTO LISTA_SALIDAS
    FROM TAB_SALIDAS E JOIN TAB_ANIMALES A ON A.ID_ANIMAL = E.ID_ANIMAL
    WHERE E.ID_FINCA = jID_FINCA AND ((jCOMPLETO AND E.ESTADO_SALIDA = 'ACTIVO') OR (NOT jCOMPLETO AND E.FECHA_MODIFICACION > jDESDE_REAL));

    --CATALOGOS GLOBALES
    SELECT json_agg(json_build_object('ID_RAZA', ID_RAZA, 'NOM_RAZA', NOM_RAZA, 'ESTADO_RAZA', ESTADO_RAZA)) INTO LISTA_RAZAS
    FROM TAB_RAZAS WHERE jCOMPLETO OR FECHA_MODIFICACION > jDESDE_REAL;

    SELECT json_agg(json_build_object('ID_VACUNA', ID_VACUNA, 'NOM_VACUNA', NOM_VACUNA, 'TIPO_VACUNA', TIPO_VACUNA, 'DIAS_REFUERZO', DIAS_REFUERZO,
        'DIAS_RETIRO_LECHE', DIAS_RETIRO_LECHE, 'OBLIGATORIA_ICA', OBLIGATORIA_ICA, 'ESTADO_VACUNA', ESTADO_VACUNA)) INTO LISTA_VACUNAS
    FROM TAB_VACUNAS WHERE jCOMPLETO OR FECHA_MODIFICACION > jDESDE_REAL;

    SELECT json_agg(json_build_object('ID_CICLO', ID_CICLO, 'ID_VACUNA', ID_VACUNA, 'NOM_CICLO', NOM_CICLO, 'FECHA_INICIO_CICLO', FECHA_INICIO_CICLO,
        'FECHA_FIN_CICLO', FECHA_FIN_CICLO, 'ESTADO_CICLO', ESTADO_CICLO)) INTO LISTA_CICLOS
    FROM TAB_CICLOS_ICA WHERE (jCOMPLETO AND ESTADO_CICLO = 'ACTIVO') OR (NOT jCOMPLETO AND FECHA_MODIFICACION > jDESDE_REAL);

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', CASE WHEN jCOMPLETO THEN 'Finca completa' ELSE 'Cambios desde la última vez' END,
        'DATOS', json_build_object(
            'MARCA', jMARCA,
            'COMPLETO', jCOMPLETO,
            'ROL_FINCA', jVALIDACION -> 'DATOS' ->> 'ROL_FINCA',
            'FINCA', jFINCA,
            'PERSONAS', COALESCE(LISTA_PERSONAS, '[]'::JSON),
            'LOTES', COALESCE(LISTA_LOTES, '[]'::JSON),
            'ANIMALES', COALESCE(LISTA_ANIMALES, '[]'::JSON),
            'PESAJES', COALESCE(LISTA_PESAJES, '[]'::JSON),
            'VACUNACIONES', COALESCE(LISTA_VACUNACIONES, '[]'::JSON),
            'SERVICIOS', COALESCE(LISTA_SERVICIOS, '[]'::JSON),
            'PALPACIONES', COALESCE(LISTA_PALPACIONES, '[]'::JSON),
            'PARTOS', COALESCE(LISTA_PARTOS, '[]'::JSON),
            'ORDENOS', COALESCE(LISTA_ORDENOS, '[]'::JSON),
            'SALIDAS', COALESCE(LISTA_SALIDAS, '[]'::JSON),
            'RAZAS', COALESCE(LISTA_RAZAS, '[]'::JSON),
            'VACUNAS', COALESCE(LISTA_VACUNAS, '[]'::JSON),
            'CICLOS_ICA', COALESCE(LISTA_CICLOS, '[]'::JSON)));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LAS ULTIMAS 20 SINCRONIZACIONES (PANTALLA "SINCRONIZACION"). EL DUEÑO VE LAS DE TODOS; LOS DEMAS, LAS SUYAS
CREATE OR REPLACE FUNCTION FUN_OBTENER_SINCRONIZACIONES_JSON(
    jID_FINCA TAB_SINCRONIZACIONES.ID_FINCA%TYPE,
    jID_USUARIO TAB_SINCRONIZACIONES.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    LISTA_SINCRONIZACIONES JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT json_agg(json_build_object(
        'ID_SINCRONIZACION', T.ID_SINCRONIZACION,
        'NOM_PERSONA', T.NOM_PERSONA,
        'FECHA_SINCRONIZACION', T.FECHA_SINCRONIZACION,
        'RECIBIDOS_SINCRONIZACION', T.RECIBIDOS_SINCRONIZACION,
        'GUARDADOS_SINCRONIZACION', T.GUARDADOS_SINCRONIZACION,
        'OMITIDOS_SINCRONIZACION', T.OMITIDOS_SINCRONIZACION,
        'RECHAZADOS_SINCRONIZACION', T.RECHAZADOS_SINCRONIZACION,
        'DETALLE_SINCRONIZACION', T.DETALLE_SINCRONIZACION
    ) ORDER BY T.ID_SINCRONIZACION DESC) INTO LISTA_SINCRONIZACIONES
    FROM (
        SELECT S.*, P.NOM_PERSONA
        FROM TAB_SINCRONIZACIONES S
        LEFT JOIN TAB_FINCAS_PERSONAS P ON P.ID_FINCA = S.ID_FINCA AND P.ID_USUARIO = S.ID_USUARIO
        WHERE S.ID_FINCA = jID_FINCA
          AND (jVALIDACION -> 'DATOS' ->> 'ROL_FINCA' = 'DUENIO' OR S.ID_USUARIO = jID_USUARIO)
        ORDER BY S.ID_SINCRONIZACION DESC
        LIMIT 20
    ) T;

    IF LISTA_SINCRONIZACIONES IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Todavía no hay sincronizaciones');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Últimas sincronizaciones', 'DATOS', LISTA_SINCRONIZACIONES);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
