-- PRUEBAS para TAB_FINCAS y TAB_FINCAS_PERSONAS
-- SE EJECUTAN DENTRO DE UNA TRANSACCION Y AL FINAL SE HACE ROLLBACK PARA NO DEJAR DATOS DE PRUEBA
-- CADA CONSULTA DICE EN SU ETIQUETA LO QUE DEBE SALIR. LOS USUARIOS DE PRUEBA EMPIEZAN POR PRU-
BEGIN;

--AYUDANTES (VIVEN SOLO EN ESTA SESION)
CREATE FUNCTION pg_temp.FINCA() RETURNS INTEGER AS $$ SELECT ID_FINCA FROM TAB_FINCAS WHERE NOM_FINCA = 'Finca Prueba' $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.FP(jUSUARIO VARCHAR) RETURNS INTEGER AS $$ SELECT ID_FINCA_PERSONA FROM TAB_FINCAS_PERSONAS WHERE ID_FINCA = pg_temp.FINCA() AND ID_USUARIO = jUSUARIO $$ LANGUAGE sql;

SELECT 'PRUEBA 1.1: Crear finca. DEBE SALIR 200 y quien la crea queda como DUENIO' as PRUEBA;
SELECT FUN_CREAR_FINCA_JSON('  Finca   Prueba ', 'San Gil', 'Vereda El Prueba', 'ica-123', 'Hierro JP', 'PRU-DUENO', 'Dueño Prueba') ->> 'CODIGO' AS CREAR_200;
SELECT NOM_FINCA || '|' || REGISTRO_ICA_FINCA AS NORMALIZADO_FINCA_PRUEBA_ICA_123, (SELECT ROL_FINCA FROM TAB_FINCAS_PERSONAS WHERE ID_FINCA = F.ID_FINCA) AS DUENIO
FROM TAB_FINCAS F WHERE ID_FINCA = pg_temp.FINCA();

SELECT 'PRUEBA 1.2: Validaciones al crear. TODAS 400' as PRUEBA;
SELECT T.CASO, R ->> 'CODIGO' AS CODIGO, R ->> 'MENSAJE' AS MENSAJE
FROM (VALUES
    ('SIN NOMBRE', FUN_CREAR_FINCA_JSON(' ', 'San Gil', NULL, NULL, NULL, 'PRU-DUENO', 'Dueño')),
    ('SIN MUNICIPIO', FUN_CREAR_FINCA_JSON('Otra', '', NULL, NULL, NULL, 'PRU-DUENO', 'Dueño')),
    ('ICA MALO', FUN_CREAR_FINCA_JSON('Otra', 'San Gil', NULL, 'ica 12/3', NULL, 'PRU-DUENO', 'Dueño')),
    ('SIN USUARIO', FUN_CREAR_FINCA_JSON('Otra', 'San Gil', NULL, NULL, NULL, NULL, 'Dueño'))
) AS T(CASO, R);

SELECT 'PRUEBA 2.1: Agregar personas. Vaquero y veterinario 200; repetido 400; rol malo 400; el vaquero no agrega a nadie 400' as PRUEBA;
SELECT FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VAQUERO', 'Vaquero Prueba', 'VAQUERO', 'PRU-DUENO') ->> 'CODIGO' AS VAQUERO_200,
       FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VET', 'Veterinaria Prueba', 'VETERINARIO', 'PRU-DUENO') ->> 'CODIGO' AS VETERINARIO_200;
SELECT FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VAQUERO', 'Vaquero Prueba', 'VAQUERO', 'PRU-DUENO') ->> 'CODIGO' AS REPETIDO_400,
       FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-OTRO', 'Otro', 'CAPATAZ', 'PRU-DUENO') ->> 'CODIGO' AS ROL_MALO_400,
       FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-OTRO', 'Otro', 'VAQUERO', 'PRU-VAQUERO') ->> 'CODIGO' AS VAQUERO_NO_AGREGA_400;

SELECT 'PRUEBA 3.1: Acceso. Extraño 400 (no trabaja aqui); finca inexistente 404; vaquero edita la finca 400; dueño edita 200' as PRUEBA;
SELECT FUN_OBTENER_FINCA_POR_ID_JSON(pg_temp.FINCA(), 'PRU-EXTRANO') ->> 'CODIGO' AS EXTRANO_400,
       FUN_OBTENER_FINCA_POR_ID_JSON(-1, 'PRU-DUENO') ->> 'CODIGO' AS NO_EXISTE_404,
       FUN_ACTUALIZAR_FINCA_JSON(pg_temp.FINCA(), 'Finca Prueba', 'Socorro', NULL, NULL, NULL, 'PRU-VAQUERO') ->> 'CODIGO' AS VAQUERO_EDITA_400,
       FUN_ACTUALIZAR_FINCA_JSON(pg_temp.FINCA(), 'Finca Prueba', 'Socorro', NULL, NULL, NULL, 'PRU-DUENO') ->> 'CODIGO' AS DUENIO_EDITA_200;
SELECT FUN_OBTENER_FINCA_POR_ID_JSON(pg_temp.FINCA(), 'PRU-VAQUERO') -> 'DATOS' ->> 'ROL_FINCA' AS VAQUERO,
       FUN_OBTENER_MIS_FINCAS_JSON('PRU-VET') -> 'DATOS' -> 0 ->> 'NOM_FINCA' AS FINCA_PRUEBA,
       FUN_OBTENER_MIS_FINCAS_JSON('PRU-EXTRANO') ->> 'CODIGO' AS SIN_FINCAS_404,
       json_array_length(FUN_OBTENER_PERSONAS_FINCA_JSON(pg_temp.FINCA(), 'PRU-VAQUERO') -> 'DATOS') AS TRES_PERSONAS;

SELECT 'PRUEBA 4.1: Siempre queda un dueño. El dueño no se quita a si mismo 400; quitar al vaquero 200 (ya no ve la finca); devolverlo 200' as PRUEBA;
SELECT FUN_ACTUALIZAR_PERSONA_FINCA_JSON(pg_temp.FP('PRU-DUENO'), 'VAQUERO', 'ACTIVO', 'PRU-DUENO') ->> 'CODIGO' AS A_SI_MISMO_400,
       FUN_ACTUALIZAR_PERSONA_FINCA_JSON(pg_temp.FP('PRU-VAQUERO'), 'VAQUERO', 'INACTIVO', 'PRU-DUENO') ->> 'CODIGO' AS QUITAR_200;
SELECT FUN_OBTENER_FINCA_POR_ID_JSON(pg_temp.FINCA(), 'PRU-VAQUERO') ->> 'CODIGO' AS YA_NO_VE_400,
       FUN_AGREGAR_PERSONA_FINCA_JSON(pg_temp.FINCA(), 'PRU-VAQUERO', 'Vaquero Prueba', 'VAQUERO', 'PRU-DUENO') ->> 'CODIGO' AS DEVOLVER_200;

SELECT 'PRUEBA 4.2: Con dos dueños, uno puede pasar al otro a vaquero (200); el que queda no puede quedar sin dueño: el veterinario no lo cambia (400 por rol)' as PRUEBA;
SELECT FUN_ACTUALIZAR_PERSONA_FINCA_JSON(pg_temp.FP('PRU-VET'), 'DUENIO', 'ACTIVO', 'PRU-DUENO') ->> 'CODIGO' AS VET_A_DUENIO_200;
SELECT FUN_ACTUALIZAR_PERSONA_FINCA_JSON(pg_temp.FP('PRU-DUENO'), 'VAQUERO', 'ACTIVO', 'PRU-VET') ->> 'CODIGO' AS DUENIO_A_VAQUERO_200;
SELECT FUN_ACTUALIZAR_PERSONA_FINCA_JSON(pg_temp.FP('PRU-VET'), 'VAQUERO', 'ACTIVO', 'PRU-DUENO') ->> 'CODIGO' AS YA_NO_ES_DUENIO_400;

ROLLBACK;
