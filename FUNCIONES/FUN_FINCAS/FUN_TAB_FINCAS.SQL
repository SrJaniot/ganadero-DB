-- FUNCIONES DE LAS TABLAS TAB_FINCAS Y TAB_FINCAS_PERSONAS -------------------------------------------------------------------------------------------
-- QUIEN CREA LA FINCA QUEDA COMO SU DUEÑO (EN LA MISMA TRANSACCION). EL DUEÑO AGREGA A LOS VAQUEROS Y AL VETERINARIO
-- REGLAS: TODA FINCA TIENE AL MENOS UN DUEÑO ACTIVO Y NADIE SE QUITA A SI MISMO DE LA FINCA



--FUNCION PARA VALIDAR LOS DATOS DE UNA FINCA (SIRVE PARA CREAR Y ACTUALIZAR)
--EL ORDEN DE LAS VALIDACIONES ES EL DEL FORMULARIO
CREATE OR REPLACE FUNCTION FUN_VALIDAR_FINCAS(
    jNOM_FINCA TAB_FINCAS.NOM_FINCA%TYPE,
    jMUNICIPIO_FINCA TAB_FINCAS.MUNICIPIO_FINCA%TYPE,
    jVEREDA_FINCA TAB_FINCAS.VEREDA_FINCA%TYPE,
    jREGISTRO_ICA_FINCA TAB_FINCAS.REGISTRO_ICA_FINCA%TYPE,
    jHIERRO_FINCA TAB_FINCAS.HIERRO_FINCA%TYPE
    ) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
BEGIN
    --VALIDACION VARIABLE NOM_FINCA (OBLIGATORIO)
    IF jNOM_FINCA IS NULL OR TRIM(jNOM_FINCA) = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el nombre de la finca');
        RETURN RETORNO;
    ELSIF LENGTH(TRIM(jNOM_FINCA)) > 100 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El nombre de la finca es demasiado largo (máximo 100 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE MUNICIPIO_FINCA (OBLIGATORIO)
    ELSIF jMUNICIPIO_FINCA IS NULL OR TRIM(jMUNICIPIO_FINCA) = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Escribe el municipio');
        RETURN RETORNO;
    ELSIF LENGTH(TRIM(jMUNICIPIO_FINCA)) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El municipio es demasiado largo (máximo 80 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE VEREDA_FINCA (OPCIONAL)
    ELSIF LENGTH(TRIM(COALESCE(jVEREDA_FINCA, ''))) > 80 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La vereda es demasiado larga (máximo 80 caracteres)');
        RETURN RETORNO;

    --VALIDACION VARIABLE REGISTRO_ICA_FINCA (OPCIONAL: LETRAS, NUMEROS Y GUIONES)
    ELSIF COALESCE(TRIM(jREGISTRO_ICA_FINCA), '') <> '' AND NOT TRIM(jREGISTRO_ICA_FINCA) ~ '^[A-Za-z0-9-]{3,30}$' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El registro ICA solo puede tener letras, números y guiones (de 3 a 30)');
        RETURN RETORNO;

    --VALIDACION VARIABLE HIERRO_FINCA (OPCIONAL)
    ELSIF LENGTH(TRIM(COALESCE(jHIERRO_FINCA, ''))) > 60 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La descripción del hierro es demasiado larga (máximo 60 caracteres)');
        RETURN RETORNO;

    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Todos los datos son válidos');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CREAR UNA FINCA. QUIEN LA CREA QUEDA COMO DUEÑO
-- DOS DML (FINCA Y DUEÑO): BLOQUE BEGIN ... EXCEPTION, ENTRAN LOS DOS O NINGUNO
CREATE OR REPLACE FUNCTION FUN_CREAR_FINCA_JSON(
    jNOM_FINCA TAB_FINCAS.NOM_FINCA%TYPE,
    jMUNICIPIO_FINCA TAB_FINCAS.MUNICIPIO_FINCA%TYPE,
    jVEREDA_FINCA TAB_FINCAS.VEREDA_FINCA%TYPE,
    jREGISTRO_ICA_FINCA TAB_FINCAS.REGISTRO_ICA_FINCA%TYPE,
    jHIERRO_FINCA TAB_FINCAS.HIERRO_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jNOM_PERSONA TAB_FINCAS_PERSONAS.NOM_PERSONA%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_FINCA INTEGER;
    jID_FINCA_PERSONA INTEGER;
BEGIN
    --LLAMAR A LA FUNCION DE VALIDACION
    jVALIDACION := FUN_VALIDAR_FINCAS(jNOM_FINCA, jMUNICIPIO_FINCA, jVEREDA_FINCA, jREGISTRO_ICA_FINCA, jHIERRO_FINCA);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    ELSIF jID_USUARIO IS NULL OR TRIM(jID_USUARIO) = '' OR jNOM_PERSONA IS NULL OR TRIM(jNOM_PERSONA) = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el usuario que crea la finca');
        RETURN RETORNO;
    END IF;

    BEGIN
        --CREAR LA FINCA
        jID_FINCA := funcion_Retorna_ultmoid('TAB_FINCAS', 'ID_FINCA');
        INSERT INTO TAB_FINCAS (ID_FINCA, NOM_FINCA, MUNICIPIO_FINCA, VEREDA_FINCA, REGISTRO_ICA_FINCA, HIERRO_FINCA, USUARIO_CREACION)
        VALUES (jID_FINCA, regexp_replace(TRIM(jNOM_FINCA), '\s+', ' ', 'g'), regexp_replace(TRIM(jMUNICIPIO_FINCA), '\s+', ' ', 'g'),
            NULLIF(TRIM(jVEREDA_FINCA), ''), NULLIF(UPPER(TRIM(jREGISTRO_ICA_FINCA)), ''), NULLIF(TRIM(jHIERRO_FINCA), ''), jID_USUARIO);
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No se pudo crear la finca';
        END IF;

        --QUIEN LA CREA QUEDA COMO DUEÑO
        jID_FINCA_PERSONA := funcion_Retorna_ultmoid('TAB_FINCAS_PERSONAS', 'ID_FINCA_PERSONA');
        INSERT INTO TAB_FINCAS_PERSONAS (ID_FINCA_PERSONA, ID_FINCA, ID_USUARIO, NOM_PERSONA, ROL_FINCA, USUARIO_CREACION)
        VALUES (jID_FINCA_PERSONA, jID_FINCA, TRIM(jID_USUARIO), regexp_replace(TRIM(jNOM_PERSONA), '\s+', ' ', 'g'), 'DUENIO', jID_USUARIO);
        IF NOT FOUND THEN
            RAISE EXCEPTION 'No se pudo asignar el dueño de la finca';
        END IF;

        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Finca creada: ya puedes registrar tus animales', 'DATOS', json_build_object('ID_FINCA', jID_FINCA));
    EXCEPTION WHEN OTHERS THEN
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', SQLERRM);
    END;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA ACTUALIZAR LOS DATOS DE UNA FINCA (SOLO EL DUEÑO)
CREATE OR REPLACE FUNCTION FUN_ACTUALIZAR_FINCA_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jNOM_FINCA TAB_FINCAS.NOM_FINCA%TYPE,
    jMUNICIPIO_FINCA TAB_FINCAS.MUNICIPIO_FINCA%TYPE,
    jVEREDA_FINCA TAB_FINCAS.VEREDA_FINCA%TYPE,
    jREGISTRO_ICA_FINCA TAB_FINCAS.REGISTRO_ICA_FINCA%TYPE,
    jHIERRO_FINCA TAB_FINCAS.HIERRO_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
BEGIN
    --VALIDAR EL ACCESO Y LOS DATOS
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;
    jVALIDACION := FUN_VALIDAR_FINCAS(jNOM_FINCA, jMUNICIPIO_FINCA, jVEREDA_FINCA, jREGISTRO_ICA_FINCA, jHIERRO_FINCA);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --ACTUALIZAR LA FINCA
    UPDATE TAB_FINCAS
    SET NOM_FINCA = regexp_replace(TRIM(jNOM_FINCA), '\s+', ' ', 'g'),
        MUNICIPIO_FINCA = regexp_replace(TRIM(jMUNICIPIO_FINCA), '\s+', ' ', 'g'),
        VEREDA_FINCA = NULLIF(TRIM(jVEREDA_FINCA), ''),
        REGISTRO_ICA_FINCA = NULLIF(UPPER(TRIM(jREGISTRO_ICA_FINCA)), ''),
        HIERRO_FINCA = NULLIF(TRIM(jHIERRO_FINCA), ''),
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_FINCA = jID_FINCA;

    --VERIFICAR SI LA ACTUALIZACION FUE EXITOSA
    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Datos de la finca actualizados');
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al actualizar la finca');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LAS FINCAS DONDE TRABAJA UNA PERSONA, CON SU ROL Y CUANTOS ANIMALES ACTIVOS TIENE CADA UNA
CREATE OR REPLACE FUNCTION FUN_OBTENER_MIS_FINCAS_JSON(
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    LISTA_FINCAS JSON;
BEGIN
    SELECT json_agg(json_build_object(
        'ID_FINCA', F.ID_FINCA,
        'NOM_FINCA', F.NOM_FINCA,
        'MUNICIPIO_FINCA', F.MUNICIPIO_FINCA,
        'VEREDA_FINCA', F.VEREDA_FINCA,
        'ROL_FINCA', P.ROL_FINCA,
        'ANIMALES_ACTIVOS', (SELECT COUNT(*) FROM TAB_ANIMALES A WHERE A.ID_FINCA = F.ID_FINCA AND A.ESTADO_ANIMAL = 'ACTIVO')
    ) ORDER BY F.NOM_FINCA) INTO LISTA_FINCAS
    FROM TAB_FINCAS_PERSONAS P
    JOIN TAB_FINCAS F ON F.ID_FINCA = P.ID_FINCA
    WHERE P.ID_USUARIO = jID_USUARIO
      AND P.ESTADO_FINCA_PERSONA = 'ACTIVO'
      AND F.ESTADO_FINCA = 'ACTIVO';

    IF LISTA_FINCAS IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Todavía no trabajas en ninguna finca');
    ELSE
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Tus fincas', 'DATOS', LISTA_FINCAS);
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LOS DATOS DE UNA FINCA CON EL ROL DE QUIEN PREGUNTA
CREATE OR REPLACE FUNCTION FUN_OBTENER_FINCA_POR_ID_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jDATOS JSON;
BEGIN
    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT json_build_object(
        'ID_FINCA', ID_FINCA,
        'NOM_FINCA', NOM_FINCA,
        'MUNICIPIO_FINCA', MUNICIPIO_FINCA,
        'VEREDA_FINCA', VEREDA_FINCA,
        'REGISTRO_ICA_FINCA', REGISTRO_ICA_FINCA,
        'HIERRO_FINCA', HIERRO_FINCA,
        'ROL_FINCA', jVALIDACION -> 'DATOS' ->> 'ROL_FINCA',
        'FECHA_CREACION', FECHA_CREACION
    ) INTO jDATOS
    FROM TAB_FINCAS
    WHERE ID_FINCA = jID_FINCA;

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Datos de la finca', 'DATOS', jDATOS);
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA AGREGAR UNA PERSONA A LA FINCA (SOLO EL DUEÑO). LA CUENTA YA DEBE EXISTIR EN SEGURIDAD: ms-logica LA BUSCA Y PASA SU id_usuario Y NOMBRE
-- SI LA PERSONA YA ESTUVO EN LA FINCA Y SE HABIA QUITADO, SE REACTIVA CON EL ROL NUEVO
CREATE OR REPLACE FUNCTION FUN_AGREGAR_PERSONA_FINCA_JSON(
    jID_FINCA TAB_FINCAS_PERSONAS.ID_FINCA%TYPE,
    jID_USUARIO_PERSONA TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jNOM_PERSONA TAB_FINCAS_PERSONAS.NOM_PERSONA%TYPE,
    jROL_FINCA TAB_FINCAS_PERSONAS.ROL_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_FINCA_PERSONA INTEGER;
    jESTADO_ACTUAL VARCHAR;
BEGIN
    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT ID_FINCA_PERSONA, ESTADO_FINCA_PERSONA INTO jID_FINCA_PERSONA, jESTADO_ACTUAL
    FROM TAB_FINCAS_PERSONAS WHERE ID_FINCA = jID_FINCA AND ID_USUARIO = TRIM(jID_USUARIO_PERSONA);

    --VALIDACIONES
    IF jID_USUARIO_PERSONA IS NULL OR TRIM(jID_USUARIO_PERSONA) = '' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige la persona');
        RETURN RETORNO;
    ELSIF jNOM_PERSONA IS NULL OR TRIM(jNOM_PERSONA) = '' OR LENGTH(TRIM(jNOM_PERSONA)) > 150 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Falta el nombre de la persona');
        RETURN RETORNO;
    ELSIF jROL_FINCA IS NULL OR jROL_FINCA NOT IN ('DUENIO', 'VAQUERO', 'VETERINARIO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige un rol válido: dueño, vaquero o veterinario');
        RETURN RETORNO;
    ELSIF jESTADO_ACTUAL = 'ACTIVO' THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Esa persona ya trabaja en esta finca');
        RETURN RETORNO;
    END IF;

    IF jID_FINCA_PERSONA IS NOT NULL THEN
        --YA ESTUVO EN LA FINCA: SE REACTIVA CON EL ROL NUEVO
        UPDATE TAB_FINCAS_PERSONAS
        SET ROL_FINCA = jROL_FINCA,
            NOM_PERSONA = regexp_replace(TRIM(jNOM_PERSONA), '\s+', ' ', 'g'),
            ESTADO_FINCA_PERSONA = 'ACTIVO',
            USUARIO_MODIFICACION = jID_USUARIO,
            FECHA_MODIFICACION = NOW()
        WHERE ID_FINCA_PERSONA = jID_FINCA_PERSONA;
    ELSE
        jID_FINCA_PERSONA := funcion_Retorna_ultmoid('TAB_FINCAS_PERSONAS', 'ID_FINCA_PERSONA');
        INSERT INTO TAB_FINCAS_PERSONAS (ID_FINCA_PERSONA, ID_FINCA, ID_USUARIO, NOM_PERSONA, ROL_FINCA, USUARIO_CREACION)
        VALUES (jID_FINCA_PERSONA, jID_FINCA, TRIM(jID_USUARIO_PERSONA), regexp_replace(TRIM(jNOM_PERSONA), '\s+', ' ', 'g'), jROL_FINCA, jID_USUARIO);
    END IF;

    --VERIFICAR SI LA OPERACION FUE EXITOSA
    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Persona agregada a la finca', 'DATOS', json_build_object('ID_FINCA_PERSONA', jID_FINCA_PERSONA));
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al agregar la persona');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION PARA CAMBIAR EL ROL O QUITAR / DEVOLVER A UNA PERSONA DE LA FINCA (SOLO EL DUEÑO)
-- NADIE SE CAMBIA NI SE QUITA A SI MISMO Y LA FINCA NUNCA QUEDA SIN DUEÑO ACTIVO
CREATE OR REPLACE FUNCTION FUN_ACTUALIZAR_PERSONA_FINCA_JSON(
    jID_FINCA_PERSONA TAB_FINCAS_PERSONAS.ID_FINCA_PERSONA%TYPE,
    jROL_FINCA TAB_FINCAS_PERSONAS.ROL_FINCA%TYPE,
    jESTADO TAB_FINCAS_PERSONAS.ESTADO_FINCA_PERSONA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jID_FINCA INTEGER;
    jID_USUARIO_PERSONA VARCHAR;
    jROL_ACTUAL VARCHAR;
    jOTROS_DUENIOS INTEGER;
BEGIN
    SELECT ID_FINCA, ID_USUARIO, ROL_FINCA INTO jID_FINCA, jID_USUARIO_PERSONA, jROL_ACTUAL
    FROM TAB_FINCAS_PERSONAS WHERE ID_FINCA_PERSONA = jID_FINCA_PERSONA;

    IF jID_FINCA IS NULL THEN
        RETORNO := json_build_object('CODIGO', 404, 'MENSAJE', 'Esa persona no está en la finca');
        RETURN RETORNO;
    END IF;

    --VALIDAR EL ACCESO
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, ARRAY['DUENIO']);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT COUNT(*) INTO jOTROS_DUENIOS FROM TAB_FINCAS_PERSONAS
    WHERE ID_FINCA = jID_FINCA AND ROL_FINCA = 'DUENIO' AND ESTADO_FINCA_PERSONA = 'ACTIVO' AND ID_FINCA_PERSONA <> jID_FINCA_PERSONA;

    --VALIDACIONES
    IF jROL_FINCA IS NULL OR jROL_FINCA NOT IN ('DUENIO', 'VAQUERO', 'VETERINARIO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'Elige un rol válido: dueño, vaquero o veterinario');
        RETURN RETORNO;
    ELSIF jESTADO IS NULL OR jESTADO NOT IN ('ACTIVO', 'INACTIVO') THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'El estado debe ser ACTIVO o INACTIVO');
        RETURN RETORNO;
    ELSIF jID_USUARIO_PERSONA = jID_USUARIO THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'No puedes cambiar tu propio rol ni quitarte de la finca');
        RETURN RETORNO;
    ELSIF jROL_ACTUAL = 'DUENIO' AND (jROL_FINCA <> 'DUENIO' OR jESTADO = 'INACTIVO') AND jOTROS_DUENIOS = 0 THEN
        RETORNO := json_build_object('CODIGO', 400, 'MENSAJE', 'La finca se quedaría sin dueño');
        RETURN RETORNO;
    END IF;

    --ACTUALIZAR
    UPDATE TAB_FINCAS_PERSONAS
    SET ROL_FINCA = jROL_FINCA,
        ESTADO_FINCA_PERSONA = jESTADO,
        USUARIO_MODIFICACION = jID_USUARIO,
        FECHA_MODIFICACION = NOW()
    WHERE ID_FINCA_PERSONA = jID_FINCA_PERSONA;

    IF FOUND THEN
        RETORNO := json_build_object('CODIGO', 200, 'MENSAJE',
            CASE WHEN jESTADO = 'INACTIVO' THEN 'La persona ya no ve esta finca' ELSE 'Persona actualizada' END);
    ELSE
        RETORNO := json_build_object('CODIGO', 500, 'MENSAJE', 'Error al actualizar la persona');
    END IF;
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;



-- FUNCION QUE DEVUELVE LAS PERSONAS DE LA FINCA (CUALQUIER ROL LAS PUEDE VER: EL VAQUERO SABE QUIEN ES EL DUEÑO)
CREATE OR REPLACE FUNCTION FUN_OBTENER_PERSONAS_FINCA_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    LISTA_PERSONAS JSON;
BEGIN
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    SELECT json_agg(json_build_object(
        'ID_FINCA_PERSONA', ID_FINCA_PERSONA,
        'ID_USUARIO', ID_USUARIO,
        'NOM_PERSONA', NOM_PERSONA,
        'ROL_FINCA', ROL_FINCA,
        'ESTADO_FINCA_PERSONA', ESTADO_FINCA_PERSONA
    ) ORDER BY ESTADO_FINCA_PERSONA, CASE ROL_FINCA WHEN 'DUENIO' THEN 1 WHEN 'VETERINARIO' THEN 2 ELSE 3 END, NOM_PERSONA) INTO LISTA_PERSONAS
    FROM TAB_FINCAS_PERSONAS
    WHERE ID_FINCA = jID_FINCA;

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Personas de la finca', 'DATOS', LISTA_PERSONAS);
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
