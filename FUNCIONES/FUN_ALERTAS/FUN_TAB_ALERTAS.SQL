-- FUNCIONES DE LAS ALERTAS DE LA FINCA (FASE 3: PANTALLA "HOY") ----------------------------------------------------------------------------------------
-- LAS CALCULA LA BASE CON LOS EVENTOS ACTIVOS (NADA SE GUARDA: SALEN DE LA LINEA DE TIEMPO). EL CELULAR GUARDA EL RESULTADO EN CADA
-- SINCRONIZACION Y LO MUESTRA SIN SEÑAL ("ALERTAS DE LA ULTIMA VEZ QUE HUBO SEÑAL"): LA LOGICA NO SE REPITE EN TYPESCRIPT
-- LOS DIAS DE CADA AVISO ESTAN EN TAB_CONFIGURACION (DIAS_GESTACION, DIAS_AVISO_PARTO, DIAS_PALPAR_DESPUES_SERVICIO, DIAS_VACIA_ALERTA, DIAS_AVISO_VACUNA)
--
-- ALERTA                 QUE MIRA
-- PARTOS_PROXIMOS        HEMBRAS CON UN SERVICIO DESPUES DE SU ULTIMO PARTO (Y SIN PALPACION VACIA DESPUES DEL SERVICIO) O PALPADAS PREÑADAS:
--                        PARTO PROBABLE = SERVICIO + DIAS_GESTACION, O PALPACION + (9 - MESES) MESES. DESDE 30 DIAS ATRASADO HASTA DIAS_AVISO_PARTO
-- PALPAR                 SERVICIO DE HACE DIAS_PALPAR_DESPUES_SERVICIO O MAS SIN NINGUNA PALPACION DESPUES
-- VACIAS                 VACAS (CON PARTOS) CUYO ULTIMO PARTO FUE HACE MAS DE DIAS_VACIA_ALERTA Y QUE NO ESTAN SERVIDAS NI PREÑADAS DESPUES DE ESE PARTO
-- VACUNAS_POR_APLICAR    LA PROXIMA DOSIS DE LA ULTIMA APLICACION DE CADA PRODUCTO A CADA ANIMAL: DESDE 30 DIAS ATRASADA HASTA DIAS_AVISO_VACUNA
-- RETIROS_LECHE          TRATAMIENTOS CON RETIRO DE LECHE QUE SIGUE VIGENTE HOY
-- CICLOS_ICA             CICLOS DEL ICA VIGENTES O QUE EMPIEZAN EN 30 DIAS, CON CUANTOS ANIMALES ACTIVOS FALTAN POR VACUNAR EN ESE CICLO



-- FUNCION QUE DEVUELVE LAS ALERTAS DE LA FINCA PARA UN DIA (NULL = HOY). CUALQUIER ROL DE LA FINCA LAS PUEDE VER
-- SIEMPRE RESPONDE 200 CON LAS SEIS LISTAS (VACIAS SI NO HAY NADA): "SIN ALERTAS" ES UNA BUENA NOTICIA, NO UN 404
CREATE OR REPLACE FUNCTION FUN_OBTENER_ALERTAS_JSON(
    jID_FINCA TAB_FINCAS.ID_FINCA%TYPE,
    jID_USUARIO TAB_FINCAS_PERSONAS.ID_USUARIO%TYPE,
    jFECHA DATE
) RETURNS JSON AS
$$
DECLARE
    RETORNO JSON;
    jVALIDACION JSON;
    jHOY DATE;
    jDIAS_GESTACION INTEGER;
    jDIAS_AVISO_PARTO INTEGER;
    jDIAS_PALPAR INTEGER;
    jDIAS_VACIA INTEGER;
    jDIAS_AVISO_VACUNA INTEGER;
    LISTA_PARTOS JSON;
    LISTA_PALPAR JSON;
    LISTA_VACIAS JSON;
    LISTA_VACUNAS JSON;
    LISTA_RETIROS JSON;
    LISTA_CICLOS JSON;
BEGIN
    --VALIDAR EL ACCESO (CUALQUIER ROL DE LA FINCA)
    jVALIDACION := FUN_VALIDAR_ACCESO_FINCA(jID_FINCA, jID_USUARIO, NULL);
    IF (jVALIDACION ->> 'CODIGO')::INTEGER != 200 THEN
        RETURN jVALIDACION;
    END IF;

    --DIAS DE LA CONFIGURACION (CON EL VALOR DE FABRICA SI NO ESTA)
    jHOY := COALESCE(jFECHA, CURRENT_DATE);
    jDIAS_GESTACION := COALESCE(FUN_CONFIGURACION_NUMERO('DIAS_GESTACION'), 283)::INTEGER;
    jDIAS_AVISO_PARTO := COALESCE(FUN_CONFIGURACION_NUMERO('DIAS_AVISO_PARTO'), 30)::INTEGER;
    jDIAS_PALPAR := COALESCE(FUN_CONFIGURACION_NUMERO('DIAS_PALPAR_DESPUES_SERVICIO'), 45)::INTEGER;
    jDIAS_VACIA := COALESCE(FUN_CONFIGURACION_NUMERO('DIAS_VACIA_ALERTA'), 120)::INTEGER;
    jDIAS_AVISO_VACUNA := COALESCE(FUN_CONFIGURACION_NUMERO('DIAS_AVISO_VACUNA'), 15)::INTEGER;

    --PARTOS PROXIMOS: POR EL ULTIMO SERVICIO (SIN PALPACION VACIA DESPUES) O, SI NO HAY SERVICIO, POR LA ULTIMA PALPACION PREÑADA
    SELECT json_agg(json_build_object(
        'UUID_ANIMAL', T.UUID_ANIMAL, 'CHAPETA_ANIMAL', T.CHAPETA_ANIMAL, 'NOM_ANIMAL', T.NOM_ANIMAL,
        'FECHA_PARTO_PROBABLE', T.FECHA_PROBABLE, 'DIAS', T.FECHA_PROBABLE - jHOY, 'SEGUN', T.SEGUN, 'PADRE', T.PADRE
    ) ORDER BY T.FECHA_PROBABLE, T.CHAPETA_ANIMAL) INTO LISTA_PARTOS
    FROM (
        SELECT A.UUID_ANIMAL, A.CHAPETA_ANIMAL, A.NOM_ANIMAL,
            CASE WHEN S.FECHA_EVENTO IS NOT NULL THEN S.FECHA_EVENTO::DATE + jDIAS_GESTACION
                 ELSE (P.FECHA_EVENTO + make_interval(months => 9 - P.MESES_GESTACION))::DATE END AS FECHA_PROBABLE,
            CASE WHEN S.FECHA_EVENTO IS NOT NULL THEN 'SERVICIO' ELSE 'PALPACION' END AS SEGUN,
            COALESCE(TORO.CHAPETA_ANIMAL, TORO.NOM_ANIMAL, S.TORO_EXTERNO) AS PADRE
        FROM TAB_ANIMALES A
        LEFT JOIN LATERAL (SELECT MAX(FECHA_EVENTO) AS F FROM TAB_PARTOS WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_PARTO = 'ACTIVO') UP ON true
        LEFT JOIN LATERAL (SELECT * FROM TAB_SERVICIOS WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_SERVICIO = 'ACTIVO'
                           AND FECHA_EVENTO > COALESCE(UP.F, '-infinity') ORDER BY FECHA_EVENTO DESC LIMIT 1) S ON true
        LEFT JOIN TAB_ANIMALES TORO ON TORO.ID_ANIMAL = S.ID_TORO
        LEFT JOIN LATERAL (SELECT * FROM TAB_PALPACIONES WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_PALPACION = 'ACTIVO'
                           AND FECHA_EVENTO > COALESCE(S.FECHA_EVENTO, UP.F, '-infinity') ORDER BY FECHA_EVENTO DESC LIMIT 1) P ON true
        WHERE A.ID_FINCA = jID_FINCA AND A.ESTADO_ANIMAL = 'ACTIVO' AND A.SEXO_ANIMAL = 'H'
          AND ((S.FECHA_EVENTO IS NOT NULL AND COALESCE(P.RESULTADO_PALPACION, 'PRENIADA') = 'PRENIADA')
               OR (S.FECHA_EVENTO IS NULL AND P.RESULTADO_PALPACION = 'PRENIADA'))
    ) T
    WHERE T.FECHA_PROBABLE BETWEEN jHOY - 30 AND jHOY + jDIAS_AVISO_PARTO;

    --PALPAR: SERVIDAS HACE DIAS_PALPAR O MAS Y SIN PALPACION DESPUES DEL SERVICIO
    SELECT json_agg(json_build_object(
        'UUID_ANIMAL', T.UUID_ANIMAL, 'CHAPETA_ANIMAL', T.CHAPETA_ANIMAL, 'NOM_ANIMAL', T.NOM_ANIMAL,
        'FECHA_SERVICIO', T.FECHA_SERVICIO, 'DIAS_DESDE_SERVICIO', jHOY - T.FECHA_SERVICIO
    ) ORDER BY T.FECHA_SERVICIO, T.CHAPETA_ANIMAL) INTO LISTA_PALPAR
    FROM (
        SELECT A.UUID_ANIMAL, A.CHAPETA_ANIMAL, A.NOM_ANIMAL, S.FECHA_EVENTO::DATE AS FECHA_SERVICIO
        FROM TAB_ANIMALES A
        LEFT JOIN LATERAL (SELECT MAX(FECHA_EVENTO) AS F FROM TAB_PARTOS WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_PARTO = 'ACTIVO') UP ON true
        JOIN LATERAL (SELECT * FROM TAB_SERVICIOS WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_SERVICIO = 'ACTIVO'
                      AND FECHA_EVENTO > COALESCE(UP.F, '-infinity') ORDER BY FECHA_EVENTO DESC LIMIT 1) S ON true
        WHERE A.ID_FINCA = jID_FINCA AND A.ESTADO_ANIMAL = 'ACTIVO' AND A.SEXO_ANIMAL = 'H'
          AND S.FECHA_EVENTO::DATE <= jHOY - jDIAS_PALPAR
          AND NOT EXISTS (SELECT 1 FROM TAB_PALPACIONES PA WHERE PA.ID_ANIMAL = A.ID_ANIMAL AND PA.ESTADO_PALPACION = 'ACTIVO' AND PA.FECHA_EVENTO > S.FECHA_EVENTO)
    ) T;

    --VACIAS: VACAS CON EL ULTIMO PARTO HACE MAS DE DIAS_VACIA, SIN SERVICIO DESPUES (O CON LA ULTIMA PALPACION VACIA Y SIN SERVICIO DESPUES DE ELLA)
    SELECT json_agg(json_build_object(
        'UUID_ANIMAL', T.UUID_ANIMAL, 'CHAPETA_ANIMAL', T.CHAPETA_ANIMAL, 'NOM_ANIMAL', T.NOM_ANIMAL,
        'FECHA_ULTIMO_PARTO', T.ULTIMO_PARTO, 'DIAS_VACIA', jHOY - T.ULTIMO_PARTO
    ) ORDER BY T.ULTIMO_PARTO, T.CHAPETA_ANIMAL) INTO LISTA_VACIAS
    FROM (
        SELECT A.UUID_ANIMAL, A.CHAPETA_ANIMAL, A.NOM_ANIMAL, UP.F::DATE AS ULTIMO_PARTO
        FROM TAB_ANIMALES A
        JOIN LATERAL (SELECT MAX(FECHA_EVENTO) AS F FROM TAB_PARTOS WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_PARTO = 'ACTIVO') UP ON UP.F IS NOT NULL
        LEFT JOIN LATERAL (SELECT * FROM TAB_SERVICIOS WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_SERVICIO = 'ACTIVO'
                           AND FECHA_EVENTO > UP.F ORDER BY FECHA_EVENTO DESC LIMIT 1) S ON true
        LEFT JOIN LATERAL (SELECT * FROM TAB_PALPACIONES WHERE ID_ANIMAL = A.ID_ANIMAL AND ESTADO_PALPACION = 'ACTIVO'
                           AND FECHA_EVENTO > UP.F ORDER BY FECHA_EVENTO DESC LIMIT 1) P ON true
        WHERE A.ID_FINCA = jID_FINCA AND A.ESTADO_ANIMAL = 'ACTIVO' AND A.SEXO_ANIMAL = 'H'
          AND UP.F::DATE < jHOY - jDIAS_VACIA
          AND COALESCE(P.RESULTADO_PALPACION, '') <> 'PRENIADA'
          AND (S.FECHA_EVENTO IS NULL OR (P.RESULTADO_PALPACION = 'VACIA' AND P.FECHA_EVENTO > S.FECHA_EVENTO))
    ) T;

    --VACUNAS POR APLICAR: LA ULTIMA APLICACION DE CADA PRODUCTO A CADA ANIMAL, CON SU PROXIMA DOSIS DENTRO DEL AVISO (O ATRASADA HASTA 30 DIAS)
    SELECT json_agg(json_build_object(
        'UUID_ANIMAL', T.UUID_ANIMAL, 'CHAPETA_ANIMAL', T.CHAPETA_ANIMAL, 'NOM_ANIMAL', T.NOM_ANIMAL,
        'ID_VACUNA', T.ID_VACUNA, 'NOM_VACUNA', T.NOM_VACUNA, 'FECHA_PROXIMA_DOSIS', T.FECHA_PROXIMA_DOSIS, 'DIAS', T.FECHA_PROXIMA_DOSIS - jHOY
    ) ORDER BY T.FECHA_PROXIMA_DOSIS, T.NOM_VACUNA, T.CHAPETA_ANIMAL) INTO LISTA_VACUNAS
    FROM (
        SELECT DISTINCT ON (VC.ID_ANIMAL, VC.ID_VACUNA) A.UUID_ANIMAL, A.CHAPETA_ANIMAL, A.NOM_ANIMAL, V.ID_VACUNA, V.NOM_VACUNA, VC.FECHA_PROXIMA_DOSIS
        FROM TAB_VACUNACIONES VC
        JOIN TAB_ANIMALES A ON A.ID_ANIMAL = VC.ID_ANIMAL
        JOIN TAB_VACUNAS V ON V.ID_VACUNA = VC.ID_VACUNA
        WHERE VC.ID_FINCA = jID_FINCA AND VC.ESTADO_VACUNACION = 'ACTIVO' AND A.ESTADO_ANIMAL = 'ACTIVO'
        ORDER BY VC.ID_ANIMAL, VC.ID_VACUNA, VC.FECHA_EVENTO DESC
    ) T
    WHERE T.FECHA_PROXIMA_DOSIS BETWEEN jHOY - 30 AND jHOY + jDIAS_AVISO_VACUNA;

    --RETIROS DE LECHE VIGENTES: NO VENDER LA LECHE DE ESTOS ANIMALES HASTA LA FECHA
    SELECT json_agg(json_build_object(
        'UUID_ANIMAL', T.UUID_ANIMAL, 'CHAPETA_ANIMAL', T.CHAPETA_ANIMAL, 'NOM_ANIMAL', T.NOM_ANIMAL,
        'NOM_VACUNA', T.NOM_VACUNA, 'FECHA_FIN_RETIRO', T.FECHA_FIN_RETIRO, 'DIAS_RESTANTES', T.FECHA_FIN_RETIRO - jHOY
    ) ORDER BY T.FECHA_FIN_RETIRO DESC, T.CHAPETA_ANIMAL) INTO LISTA_RETIROS
    FROM (
        SELECT DISTINCT ON (VC.ID_ANIMAL) A.UUID_ANIMAL, A.CHAPETA_ANIMAL, A.NOM_ANIMAL, V.NOM_VACUNA, VC.FECHA_FIN_RETIRO
        FROM TAB_VACUNACIONES VC
        JOIN TAB_ANIMALES A ON A.ID_ANIMAL = VC.ID_ANIMAL
        JOIN TAB_VACUNAS V ON V.ID_VACUNA = VC.ID_VACUNA
        WHERE VC.ID_FINCA = jID_FINCA AND VC.ESTADO_VACUNACION = 'ACTIVO' AND A.ESTADO_ANIMAL = 'ACTIVO'
          AND VC.FECHA_FIN_RETIRO >= jHOY AND VC.FECHA_EVENTO::DATE <= jHOY
        ORDER BY VC.ID_ANIMAL, VC.FECHA_FIN_RETIRO DESC
    ) T;

    --CICLOS DEL ICA VIGENTES O QUE EMPIEZAN EN 30 DIAS, CON LOS ANIMALES ACTIVOS QUE AUN NO TIENEN ESA VACUNA EN EL CICLO
    SELECT json_agg(json_build_object(
        'ID_CICLO', C.ID_CICLO, 'NOM_CICLO', C.NOM_CICLO, 'NOM_VACUNA', V.NOM_VACUNA,
        'FECHA_INICIO_CICLO', C.FECHA_INICIO_CICLO, 'FECHA_FIN_CICLO', C.FECHA_FIN_CICLO,
        'VIGENTE', jHOY BETWEEN C.FECHA_INICIO_CICLO AND C.FECHA_FIN_CICLO,
        'DIAS_PARA_EMPEZAR', GREATEST(C.FECHA_INICIO_CICLO - jHOY, 0), 'DIAS_PARA_TERMINAR', C.FECHA_FIN_CICLO - jHOY,
        'FALTAN', (SELECT COUNT(*) FROM TAB_ANIMALES A
                   WHERE A.ID_FINCA = jID_FINCA AND A.ESTADO_ANIMAL = 'ACTIVO'
                     AND NOT EXISTS (SELECT 1 FROM TAB_VACUNACIONES VC WHERE VC.ID_ANIMAL = A.ID_ANIMAL AND VC.ID_VACUNA = C.ID_VACUNA
                                     AND VC.ESTADO_VACUNACION = 'ACTIVO' AND VC.FECHA_EVENTO::DATE BETWEEN C.FECHA_INICIO_CICLO AND C.FECHA_FIN_CICLO))
    ) ORDER BY C.FECHA_INICIO_CICLO) INTO LISTA_CICLOS
    FROM TAB_CICLOS_ICA C
    JOIN TAB_VACUNAS V ON V.ID_VACUNA = C.ID_VACUNA
    WHERE C.ESTADO_CICLO = 'ACTIVO' AND C.FECHA_FIN_CICLO >= jHOY AND C.FECHA_INICIO_CICLO <= jHOY + 30;

    RETORNO := json_build_object('CODIGO', 200, 'MENSAJE', 'Alertas de la finca',
        'DATOS', json_build_object(
            'FECHA', jHOY,
            'PARTOS_PROXIMOS', COALESCE(LISTA_PARTOS, '[]'::JSON),
            'PALPAR', COALESCE(LISTA_PALPAR, '[]'::JSON),
            'VACIAS', COALESCE(LISTA_VACIAS, '[]'::JSON),
            'VACUNAS_POR_APLICAR', COALESCE(LISTA_VACUNAS, '[]'::JSON),
            'RETIROS_LECHE', COALESCE(LISTA_RETIROS, '[]'::JSON),
            'CICLOS_ICA', COALESCE(LISTA_CICLOS, '[]'::JSON),
            'DIAS_VACIA_ALERTA', jDIAS_VACIA,
            'DIAS_AVISO_PARTO', jDIAS_AVISO_PARTO));
    RETURN RETORNO;
END;
$$ LANGUAGE plpgsql;
