-- PRUEBAS de FUN_OBTENER_ALERTAS_JSON (FASE 3)
-- SE EJECUTAN DENTRO DE UNA TRANSACCION Y AL FINAL SE HACE ROLLBACK PARA NO DEJAR DATOS DE PRUEBA
-- LAS FECHAS SON RELATIVAS A HOY: CADA VACA ESTA PUESTA PARA CAER EN UNA SOLA ALERTA
--   23 SERVIDA HACE 270 DIAS CON EL TORO T1      -> PARTO PROXIMO EN 13 DIAS (SEGUN SERVICIO); Y TRATADA HACE 2 DIAS -> RETIRO DE LECHE
--   24 PARIO HACE 200 DIAS Y NO LA HAN SERVIDO   -> VACIA 200 DIAS; Y AFTOSA HACE 170 DIAS -> PROXIMA DOSIS EN 10 DIAS
--   25 SERVIDA HACE 60 DIAS Y SIN PALPAR          -> PALPAR
--   26 PALPADA PREÑADA DE 8 MESES HACE 10 DIAS    -> PARTO PROXIMO EN UNOS 20 DIAS (SEGUN PALPACION)
--   27 SERVIDA HACE 60 DIAS Y PALPADA VACIA        -> NINGUNA (NO ES VACA: NO TIENE PARTOS)
BEGIN;

SELECT FUN_CREAR_FINCA_JSON('Finca Prueba', 'San Gil', NULL, NULL, NULL, 'PRU-DUENO', 'Dueño Prueba') ->> 'CODIGO' AS FINCA_200;
CREATE FUNCTION pg_temp.FINCA() RETURNS INTEGER AS $$ SELECT ID_FINCA FROM TAB_FINCAS WHERE NOM_FINCA = 'Finca Prueba' $$ LANGUAGE sql;
--EL UUID SALE DE LA CHAPETA (T1 -> ...00F1: UN UUID SOLO ACEPTA HEXADECIMAL)
CREATE FUNCTION pg_temp.U(jSUFIJO VARCHAR) RETURNS UUID AS $$ SELECT ('00000000-0000-0000-0000-' || lpad(replace(jSUFIJO, 'T', 'F'), 12, '0'))::UUID $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.HACE(jDIAS INTEGER) RETURNS TIMESTAMP AS $$ SELECT (CURRENT_DATE - jDIAS) + TIME '08:00' $$ LANGUAGE sql;
CREATE FUNCTION pg_temp.ALERTAS() RETURNS JSON AS $$ SELECT FUN_OBTENER_ALERTAS_JSON(pg_temp.FINCA(), 'PRU-DUENO', NULL) -> 'DATOS' $$ LANGUAGE sql;

--LAS VACAS Y EL TORO (COMPRADOS, ADULTOS)
SELECT FUN_CREAR_ANIMAL_JSON(pg_temp.U(c), pg_temp.FINCA(), NULL, NULL, c, NULL, CASE WHEN c = 'T1' THEN 'M' ELSE 'H' END, '2019-01-01', 'SI', NULL, NULL, NULL,
       'COMPRADO', (CURRENT_DATE - 400), 'PRU-DUENO') ->> 'CODIGO' AS ANIMAL_200
FROM unnest(ARRAY['23', '24', '25', '26', '27', 'T1']) AS c;

--LOS EVENTOS
SELECT FUN_CREAR_SERVICIO_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('23'), 'MONTA', pg_temp.U('T1'), NULL, pg_temp.HACE(270), NULL, 'PRU-DUENO') ->> 'CODIGO' AS SERVICIO_23,
       FUN_CREAR_PALPACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('23'), 'PRENIADA', 6, pg_temp.HACE(90), NULL, 'PRU-DUENO') ->> 'CODIGO' AS PALPACION_23,
       FUN_CREAR_VACUNACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('23'), 8, NULL, pg_temp.HACE(2), NULL, 'PRU-DUENO') ->> 'CODIGO' AS TRATAMIENTO_23;
SELECT FUN_CREAR_PARTO_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('24'), 'NORMAL', 'NO', NULL, NULL, NULL, NULL, NULL, pg_temp.HACE(200), NULL, 'PRU-DUENO') ->> 'CODIGO' AS PARTO_24,
       FUN_CREAR_VACUNACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('24'), 1, NULL, pg_temp.HACE(170), NULL, 'PRU-DUENO') ->> 'CODIGO' AS AFTOSA_24;
SELECT FUN_CREAR_SERVICIO_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('25'), 'INSEMINACION', NULL, 'Pajilla Gyr', pg_temp.HACE(60), NULL, 'PRU-DUENO') ->> 'CODIGO' AS SERVICIO_25,
       FUN_CREAR_PALPACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('26'), 'PRENIADA', 8, pg_temp.HACE(10), NULL, 'PRU-DUENO') ->> 'CODIGO' AS PALPACION_26,
       FUN_CREAR_SERVICIO_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('27'), 'MONTA', NULL, NULL, pg_temp.HACE(60), NULL, 'PRU-DUENO') ->> 'CODIGO' AS SERVICIO_27,
       FUN_CREAR_PALPACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('27'), 'VACIA', NULL, pg_temp.HACE(20), NULL, 'PRU-DUENO') ->> 'CODIGO' AS PALPACION_27;
--CICLO DE AFTOSA VIGENTE (EMPEZO HACE 5 DIAS)
SELECT FUN_CREAR_CICLO_ICA_JSON(1, 'Ciclo de prueba', CURRENT_DATE - 5, CURRENT_DATE + 20, 'PRU-ADMIN') ->> 'CODIGO' AS CICLO_200;


SELECT 'PRUEBA 1.1: Partos próximos. DEBE SALIR 23 (SERVICIO, PADRE T1, EN 13 DIAS) Y 26 (PALPACION, EN UNOS 20 DIAS)' as PRUEBA;
SELECT E ->> 'CHAPETA_ANIMAL' AS CHAPETA, E ->> 'SEGUN' AS SEGUN, E ->> 'PADRE' AS PADRE, E ->> 'DIAS' AS DIAS
FROM json_array_elements(pg_temp.ALERTAS() -> 'PARTOS_PROXIMOS') E;

SELECT 'PRUEBA 1.2: Palpar. DEBE SALIR SOLO 25 (60 DIAS DESDE EL SERVICIO)' as PRUEBA;
SELECT E ->> 'CHAPETA_ANIMAL' AS CHAPETA, E ->> 'DIAS_DESDE_SERVICIO' AS DIAS FROM json_array_elements(pg_temp.ALERTAS() -> 'PALPAR') E;

SELECT 'PRUEBA 1.3: Vacías. DEBE SALIR SOLO 24 (200 DIAS)' as PRUEBA;
SELECT E ->> 'CHAPETA_ANIMAL' AS CHAPETA, E ->> 'DIAS_VACIA' AS DIAS FROM json_array_elements(pg_temp.ALERTAS() -> 'VACIAS') E;

SELECT 'PRUEBA 1.4: Vacunas por aplicar. DEBE SALIR 24 CON FIEBRE AFTOSA EN 10 DIAS' as PRUEBA;
SELECT E ->> 'CHAPETA_ANIMAL' AS CHAPETA, E ->> 'NOM_VACUNA' AS VACUNA, E ->> 'DIAS' AS DIAS FROM json_array_elements(pg_temp.ALERTAS() -> 'VACUNAS_POR_APLICAR') E;

SELECT 'PRUEBA 1.5: Retiros de leche. DEBE SALIR 23 CON 3 DIAS RESTANTES (OXITETRACICLINA: 5 DIAS)' as PRUEBA;
SELECT E ->> 'CHAPETA_ANIMAL' AS CHAPETA, E ->> 'NOM_VACUNA' AS PRODUCTO, E ->> 'DIAS_RESTANTES' AS DIAS FROM json_array_elements(pg_temp.ALERTAS() -> 'RETIROS_LECHE') E;

SELECT 'PRUEBA 1.6: Ciclo del ICA vigente. DEBE SALIR VIGENTE true Y FALTAN 6 (LA AFTOSA DE 24 FUE ANTES DEL CICLO)' as PRUEBA;
SELECT E ->> 'NOM_CICLO' AS CICLO, E ->> 'VIGENTE' AS VIGENTE, E ->> 'FALTAN' AS FALTAN FROM json_array_elements(pg_temp.ALERTAS() -> 'CICLOS_ICA') E;

SELECT 'PRUEBA 2.1: Lo que cambia la alerta. Palpar a 25 la saca de PALPAR (0); vacunar a 24 con aftosa hoy la saca de VACUNAS (0) y baja el ciclo a 5; servir a 24 la saca de VACIAS (0)' as PRUEBA;
SELECT FUN_CREAR_PALPACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('25'), 'PRENIADA', 2, pg_temp.HACE(0), NULL, 'PRU-DUENO') ->> 'CODIGO' AS PALPAR_25,
       FUN_CREAR_VACUNACION_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('24'), 1, NULL, pg_temp.HACE(0), NULL, 'PRU-DUENO') ->> 'CODIGO' AS AFTOSA_24_HOY,
       FUN_CREAR_SERVICIO_JSON(gen_random_uuid(), pg_temp.FINCA(), pg_temp.U('24'), 'MONTA', pg_temp.U('T1'), NULL, pg_temp.HACE(0), NULL, 'PRU-DUENO') ->> 'CODIGO' AS SERVIR_24;
SELECT json_array_length(pg_temp.ALERTAS() -> 'PALPAR') AS PALPAR_0,
       json_array_length(pg_temp.ALERTAS() -> 'VACUNAS_POR_APLICAR') AS VACUNAS_0,
       json_array_length(pg_temp.ALERTAS() -> 'VACIAS') AS VACIAS_0,
       pg_temp.ALERTAS() -> 'CICLOS_ICA' -> 0 ->> 'FALTAN' AS FALTAN_5;

SELECT 'PRUEBA 3.1: Acceso. Extraño 400; finca inexistente 404' as PRUEBA;
SELECT FUN_OBTENER_ALERTAS_JSON(pg_temp.FINCA(), 'PRU-EXTRANO', NULL) ->> 'CODIGO' AS EXTRANO_400,
       FUN_OBTENER_ALERTAS_JSON(-1, 'PRU-DUENO', NULL) ->> 'CODIGO' AS NO_EXISTE_404;

ROLLBACK;
