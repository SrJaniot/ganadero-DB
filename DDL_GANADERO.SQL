-- FUNCION QUE RETORNA EL SIGUIENTE ID DE UNA TABLA ------------------------------------------------------------------------------------------------------
CREATE OR REPLACE FUNCTION funcion_Retorna_ultmoid(wnom_tabla VARCHAR,wnom_columna_id VARCHAR)RETURNS INTEGER AS

$$ DECLARE ULTIMOID INTEGER;
	BEGIN
		  --CANDADO POR TABLA HASTA QUE TERMINE LA TRANSACCION (14/10/2026): SI DOS INSERCIONES PIDEN ID A LA VEZ, LA SEGUNDA
		  --ESPERA A QUE LA PRIMERA GUARDE Y LUEGO LEE EL MAX YA ACTUALIZADO. SIN ESTO, CON PEDIDOS SIMULTANEOS SALIA
		  --"duplicate key value violates unique constraint" (PRUEBA DE ESTRES: 14 DE 20 PEDIDOS A LA VEZ FALLABAN)
		  PERFORM pg_advisory_xact_lock(hashtext(lower(wnom_tabla)));
		  EXECUTE 'SELECT MAX  ('||wnom_columna_id||')  FROM ' || wnom_tabla INTO ULTIMOID ;

		IF ULTIMOID IS NULL  THEN
			ULTIMOID=1;
			RETURN ULTIMOID;
		ELSE
		ULTIMOID=ULTIMOID+1;
		RETURN ULTIMOID;
		END IF;
	END;
$$
LANGUAGE PLPGSQL;
